# The body of function $2 in assembly file $1, from its label to the next .globl.
body() {
    awk -v f="$2" '{ l = $0; sub(/^_/, "", l) } l == f ":" { p = 1; next } p && /\.globl/ { exit } p' "$1"
}

TARGETS="arm64-linux"; [ "$PLAT" = osx ] && TARGETS="arm64-linux arm64"   # macOS needs its SDK frameworks
for A in $TARGETS; do
    for C in "$REF" "$XC"; do
        n=$(basename "$C")
        if ! "$C" -q -O3 --par-style=cpu -A "$A" -H . -S -o "$W/s.$A.$n.s" "$W/s.xc" 2> "$W/err"; then
            echo "FAIL $n -A $A: build"; head -5 "$W/err"; fail=1
        fi
    done
    if ! cmp -s "$W/s.$A.xcc.s" "$W/s.$A.xcc-xc.s"; then
        echo "FAIL -A $A: the two compilers write different assembly"; fail=1
    fi
    s="$W/s.$A.xcc-xc.s"
    body "$s" runA > "$W/a"; body "$s" runB > "$W/b"; body "$s" runC > "$W/c"
    nsb=$(grep -cE '_sb[0-9]+_a:$' "$W/a")
    ntb=$(grep -cE '^[[:space:]]+tbn?z[[:space:]]' "$W/a")
    nfc=$(grep -cE '^[[:space:]]+fcsel[[:space:]].*, (eq|ne)$' "$W/a")
    [ "$nsb" -ge 4 ] || { echo "FAIL -A $A: runA has $nsb select-made branches (want 4)"; fail=1; }
    [ "$ntb" -ge 4 ] || { echo "FAIL -A $A: runA has $ntb tbz/tbnz (want 4)"; fail=1; }
    # The h & 4 swaps stay fcsel (no arm computes): 2 per grad, 4 in all.
    [ "$nfc" -le 4 ] || { echo "FAIL -A $A: runA keeps $nfc fcsel on a bit (want at most the 4 swaps)"; fail=1; }
    grep -qE '^[[:space:]]+tbn?z[[:space:]]+w[0-9]+, #3,' "$W/b" || { echo "FAIL -A $A: runB's branch on bit 3 is not tbz/tbnz"; fail=1; }
    grep -qE '_tbr_[0-9]+:$' "$W/c" || { echo "FAIL -A $A: runC's far test has no _tbr_ form"; fail=1; }
done

# This machine: -O0 and -O3 print the same values, and the far form assembles.
case "$PLAT-$(uname -m)" in
    osx-arm64)                 NATIVE=arm64 ;;
    linux-aarch64|linux-arm64) NATIVE=arm64-linux ;;
    *)                         NATIVE= ;;
esac
if [ -n "$NATIVE" ]; then
    want=
    for C in "$REF" "$XC"; do
        n=$(basename "$C")
        for o in O0 O3; do
            "$C" -q -$o --par-style=cpu -A "$NATIVE" -H . -o "$W/s.$o.$n" "$W/s.xc" 2> "$W/err" || { echo "FAIL $n -$o: build"; head -5 "$W/err"; fail=1; continue; }
            got=$("$W/s.$o.$n")
            [ -z "$want" ] && want=$got
            [ "$got" = "$want" ] || { echo "FAIL $n -$o: printed"; echo "$got"; echo "want"; echo "$want"; fail=1; }
        done
    done
fi
[ $fail = 0 ] && echo "select-branch: ok"
exit $fail
