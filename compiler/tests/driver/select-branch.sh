#!/bin/bash
# select-branch.sh — a float Select whose arm computes, on one bit, is a
# branch again on arm64 (OptSelectBranch / XTIROptSelectBranch), and a branch
# on one bit is tbz/tbnz (#22).
#
#   (a) grad: perlin's `(h & 1) ? -u : u` selects become branches (blocks
#       `_sb<n>_a`/`_sb<n>_j`), each tested with tbz/tbnz, and no fcsel of
#       them is left in the loop;
#   (b) bits: an integer branch on one bit around a store (so it stays a
#       branch) whose join takes a phi is tbz/tbnz too;
#   (c) far: a one-bit branch around more than 32 KB of code, which tbz cannot
#       reach, is the inverse test over a `b` (label `_tbr_`) and assembles.
#
# Built with --par-style=cpu, so no loop becomes a par block. Both compilers
# write the same assembly (arm64 Linux; macOS on a Mac), and
# built for this machine with -O0 and -O3 the program prints the same values.
#
#   bash tests/driver/select-branch.sh
set -u
cd "$(dirname "$0")/../.." || exit 1
PLAT=$([ "$(uname -s)" = Darwin ] && echo osx || echo linux)
REF=${REF:-bin/$PLAT/xcc}; XC=${XC:-bin/$PLAT/xcc-xc}
W=$(mktemp -d /tmp/selbr.XXXX)
trap 'rm -rf "$W"' EXIT
