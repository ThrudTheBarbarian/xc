            @"static void *_xtc_bank_regions[3][256]={{0}};\n"
            @"void *_xtc_bank(uint8_t type,uint8_t idx){if(type>1)return 0;"
            @"if(!_xtc_bank_regions[type][idx])_xtc_bank_regions[type][idx]=calloc(1,12288);"
            @"return _xtc_bank_regions[type][idx];}\n"];
    }
    return s;
}

// Assemble + link an arm64 `.s` into a native executable via clang, supplying
// the host stub and libxt.c (Time/PRNG). Returns the clang exit status.
// Native-link passthrough (#6): the parsed -l / -framework / -Xlinker / -Wl
// args plus a whitespace-split $XTC_LDFLAGS, in clang command order. Lets an
// ObjC/AppKit/Cocoa xtc program link against dyld-shared-cache libraries and
// frameworks that have no importable DWARF .dylib.
// User link flags for the native link stage: `-L<dir>` for every `-L` the user
// gave (opts.libraryPaths), then the recorded linker args (-l/-framework/
// -Xlinker/-Wl,), then $XTC_LDFLAGS. `directLd` = YES when ld.lld is invoked
// DIRECTLY (the Linux path, no compiler driver): only the portable `-L`/`-l`
// requests are forwarded — the driver-only/mac idioms (-framework, -Xlinker,
// -Wl,) have no meaning to a bare ld and would make it error.
// On the DIRECT-ld path a `-Wl,a,b` wrapper is clang-speak for "pass a and b
// to the linker" — unwrap it; every other token was explicitly addressed to
// the linker (a bare `-Xlinker` argument, `-l`, `-L`, or an $XTC_LDFLAGS
// token) and passes through verbatim. These used to be silently DROPPED when
// they weren't -l/-L (blewit: -Wl,/-Xlinker/XTC_LDFLAGS never reached
// ld.lld) — a silent-degradation bug: the link succeeded without what the
// user asked for. Order is preserved throughout; lld's lazy-archive
// retention additionally makes inter-archive -l order forgiving.
static void appendLdToken(NSMutableArray<NSString *> *out, NSString *tok, BOOL directLd) {
    if (!tok.length) return;
    // `-Xlinker <arg>` is CLANG-speak for "hand <arg> to the linker", and the
    // pair is stored intact for the clang paths. A bare ld has never heard of
    // the wrapper, so on the direct path only the ARGUMENT should go: dropping
    // the wrapper here leaves the next token (its argument) to pass through
    // verbatim on the following call, which is exactly what was wanted.
    //
    // Without this, ld.lld received a literal `-Xlinker` and failed the link —
    // so `-Wl,` (which IS unwrapped, just below) was the only spelling that
    // worked on x86-64 Linux. Reported by blewit while overriding musl's
    // malloc with mimalloc, where `-Wl,` was the path that got the object in.
    if (directLd && [tok isEqualToString:@"-Xlinker"]) return;
    if (directLd && [tok hasPrefix:@"-Wl,"]) {
        for (NSString *part in
             [[tok substringFromIndex:4] componentsSeparatedByString:@","])
            if (part.length) [out addObject:part];
        return;
    }
    [out addObject:tok];
}

static NSArray<NSString *> *appendLinkerFlags(XTCommandLineOptions *opts, BOOL directLd) {
    NSMutableArray<NSString *> *out = [NSMutableArray array];
    for (NSString *dir in opts.libraryPaths)
        [out addObject:[@"-L" stringByAppendingString:dir]];
    for (NSString *arg in opts.linkerArgs)
        appendLdToken(out, arg, directLd);
    const char *ld = getenv("XTC_LDFLAGS");
    if (ld && *ld) {
        for (NSString *tok in [@(ld) componentsSeparatedByCharactersInSet:
                               [NSCharacterSet whitespaceCharacterSet]])
            appendLdToken(out, tok, directLd);
    }
    return out;
}

// Does the user's command line ask for link inputs the in-house x86-64 linker
// cannot satisfy? It has no library search, no static archives, and no notion of
// the driver-only idioms; `-l<name>` becomes a DT_NEEDED soname at best.
// Silently dropping such a request would build a binary missing what the user
// asked for, so the caller falls back to clang instead.
//
// `-L` alone is NOT such a request: it is a search path, and the driver has
// already used it to resolve `#import <Lib>` into a concrete library path by the
// time we get here. Tripping on it would send every `#import <Lib>` build to
// clang.
// An OBJECT or ARCHIVE named through -Wl is something the in-house linker can
// take — it merges objects and pulls archive members already — so it must not
// force the fallback. That mattered for a library WRAPPING external C: the shim
// and its archive sent the whole link to clang, which bundles the C but not the
// xtc runtime, so neither path produced a complete library (#1191/#1193).
static BOOL x86LinkTokenIsFileInput(NSString *tok) {
    NSString *e = tok.pathExtension;
    return [e isEqualToString:@"o"] || [e isEqualToString:@"a"];
}

// Resolve every `-l<name>` on the command line into a static archive the
// in-house x86-64 linker can pull from (finding #15). The old behaviour sent
// ANY -l to the clang fallback — which links the C library but NOT the
// in-house runtime, so a program using Stdio.printf (whose x86 build reaches
// the runtime's _xt_fmt_f) could not also link a C archive: printf XOR
// -lmbedcrypto. The in-house linker reads archives (#1170); all the driver
// ever had to do was turn the flag into a path.
//
// Search order: the -L dirs (opts + raw tokens), then the musl sysroot's lib.
// Returns YES with every -l resolved into `out` (or none present); NO — a
// shared-only library, or an ld idiom we don't speak — leaves the caller on
// the fallback exactly as before.
static BOOL dashLResolveArchives(XTCommandLineOptions *opts, NSFileManager *fm,
                                 NSArray<NSString *> *defaultDirs,
                                 NSMutableArray<NSString *> *out) {
    NSMutableArray<NSString *> *toks = [NSMutableArray array];
    for (NSString *arg in opts.linkerArgs) {
        if (!arg.length) continue;
        if ([arg hasPrefix:@"-Wl,"]) {
            for (NSString *p in [[arg substringFromIndex:4] componentsSeparatedByString:@","])
                if (p.length) [toks addObject:p];
        } else [toks addObject:arg];
    }
    const char *ld = getenv("XTC_LDFLAGS");
    if (ld && *ld)
        for (NSString *t in [@(ld) componentsSeparatedByCharactersInSet:
                             [NSCharacterSet whitespaceCharacterSet]])
            if (t.length) [toks addObject:t];
    // Pass 1: every search dir, wherever it appears relative to the -l.
    NSMutableArray<NSString *> *dirs = [opts.libraryPaths mutableCopy] ?: [NSMutableArray array];
    for (NSString *t in toks)
        if ([t hasPrefix:@"-L"] && t.length > 2) [dirs addObject:[t substringFromIndex:2]];
    [dirs addObjectsFromArray:defaultDirs];
    // Pass 2: resolve. An object or archive named DIRECTLY (-Wl,foo.o /
    // -Wl,libbar.a / a bare path in XTC_LDFLAGS) joins the link line as
    // itself — the in-house linker classifies .o (merged unconditionally)
    // vs .a (a pool) by extension. This used to `continue` with a comment
    // claiming another channel handed them over; no such channel existed on
    // this path, so every -Wl object was silently DROPPED — blewit's
    // tlsshim-musl.o defined xt_tls_read and the link still said undefined,
    // while the same -Wl objects had always reached the CLANG fallback fine,
    // which is what made it look like a per-symbol bug rather than a
    // missing-input one.
    for (NSString *t in toks) {
        if ([t hasPrefix:@"-L"]) continue;
        if (x86LinkTokenIsFileInput(t)) {
            if (![fm fileExistsAtPath:t]) return NO;   // clang may know it; we don't
            [out addObject:t];
            continue;
        }
        if ([t hasPrefix:@"-l"] && t.length > 2) {
            NSString *ar = [NSString stringWithFormat:@"lib%@.a", [t substringFromIndex:2]];
            NSString *found = nil;
            for (NSString *dir in dirs) {
                NSString *p = [dir stringByAppendingPathComponent:ar];
                if ([fm fileExistsAtPath:p]) { found = p; break; }
            }
            if (!found) return NO;
            [out addObject:found];
            continue;
        }
        return NO;
    }
    return YES;
}

static BOOL x86SelfHostCanIgnoreLinkFlags(XTCommandLineOptions *opts) {
    for (NSString *arg in opts.linkerArgs) {
        if (!arg.length) continue;
        NSString *t = [arg hasPrefix:@"-Wl,"] ? [arg substringFromIndex:4] : arg;
        BOOL allFiles = YES;
        for (NSString *piece in [t componentsSeparatedByString:@","])
            if (piece.length && !x86LinkTokenIsFileInput(piece)) { allFiles = NO; break; }
        if (allFiles) continue;                 // objects/archives: we can take these
        return NO;
    }
    const char *ld = getenv("XTC_LDFLAGS");
    if (ld && *ld) {
        for (NSString *tok in [@(ld) componentsSeparatedByCharactersInSet:
                               [NSCharacterSet whitespaceCharacterSet]])
            if (tok.length && ![tok hasPrefix:@"-L"]) return NO;
    }
    return YES;
}

