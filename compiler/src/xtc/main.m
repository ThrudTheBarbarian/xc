// arm64 self-hosting is the DEFAULT: the in-house assembler + Mach-O writer +
// ad-hoc signer produce the binary with no clang, no system as, no codesign.
// `--no-self-host` forces the clang path (`--self-host` remains accepted, and is
// now simply an explicit affirmation of the default). Anything the in-house linker
// genuinely cannot resolve still falls back to clang on its own, so the flip can
// only change WHICH tool links a program that both can link.
//
// The in-house writer emits **Mach-O**, so `-A arm64` always means an
// arm64-macOS binary regardless of the build host — there is no arm64-Linux
// backend. On macOS this is the default (a native build); on any other host it
// is a CROSS-compile to macOS, which only the in-house writer can do (no clang
// on Linux targets arm64-macOS), so `--self-host` there is honoured, not gated
// away. The writer, signer and runtime are all host-independent, so a Linux or
// Windows box produces the same Mach-O a Mac would.
//
// The one thing a non-Mac host cannot do is resolve macOS SDK `.tbd`/framework
// imports (there is no SDK present), so a program that needs those still can't
// be built there — but that surfaces as a normal missing-symbol error, not as a
// silent host gate.

// A clang fallback after the IN-HOUSE tool has FAILED hides exactly the defects
// we most want to see: the backend emitting something its own assembler cannot
// take. That silhouette has now appeared three times — `@GOTPAGE`/`@GOTPAGEOFF`
// (#999), `uaddlp` from the vectoriser (bug 028), and nine x86-64 SIMD
// mnemonics (bug 029) — and every one of them was invisible on the default path
// because the fallback quietly produced a working binary.
//
// So the fallback is now OFF: a failed in-house link is a failed build, and it
// says which tool gave up. `XTC_ALLOW_CLANG_FALLBACK=1` restores the old
// behaviour for anyone who needs to get work done while a gap is being fixed.
static BOOL clangFallbackAllowed(void) {
    const char *e = getenv("XTC_ALLOW_CLANG_FALLBACK");
    return e && *e && strcmp(e, "0") != 0;
}

// `-fmalloc=mimalloc`: the mimalloc object for this arch, or nil.
//
// Returned as a path to be placed FIRST among the link inputs. Under a static
// link an ARCHIVE member is pulled only to satisfy an undefined symbol, so a
// mimalloc `.a` would override only the part of the malloc family libc had not
// already supplied — two allocators in one program, and a `free` handed a
// pointer the other owns. A plain object is unconditional. See
// support/MIMALLOC.md.
static NSString * _Nullable mimallocObjectFor(NSString *arch, const char *argv0,
                                              XTCommandLineOptions *opts) {
    if (![opts.hostMalloc isEqualToString:@"mimalloc"]) return nil;
    NSString *support = resolveSupportRoot(argv0, opts);
    if (!support) return nil;
    NSString *p = [support stringByAppendingPathComponent:
                   [NSString stringWithFormat:@"%@/runtime/mimalloc.o", arch]];
    return [[NSFileManager defaultManager] fileExistsAtPath:p] ? p : nil;
}

// The in-house x86-64 link's half of -fmalloc=mimalloc: the object goes in as
// the FIRST object input (the linker merges objects in order, after the
// assembled sources), so libc's malloc members are never pulled. It used to be
// added on the clang path only, which made the flag a silent no-op on the
// default path. A requested allocator that is missing is an error, not a
// quiet fall back to the system one.
static BOOL x86AddMimalloc(const char *argv0, XTCommandLineOptions *opts,
                           NSMutableArray<NSString *> *args) {
    if (![opts.hostMalloc isEqualToString:@"mimalloc"]) return YES;
    NSString *mi = mimallocObjectFor(@"x86_64", argv0, opts);
    if (!mi) {
        fprintf(stderr, "xcc: error: -fmalloc=mimalloc needs x86_64/runtime/mimalloc.o "
                        "in the support tree, and it is not there\n");
        return NO;
    }
    [args addObject:mi];
    return YES;
}

// The system toolchain finished a build the in-house one was supposed to do.
// That is never a detail: it means the binary in front of you was NOT produced
// by this compiler's own assembler/linker, so any gap in them is invisible to
// you and to every test that just checks the program runs.
//
// It hid a DEAD win64 linker. #1083 regenerated the freestanding runtime without
// -DXT_WIN64, so the in-house link failed on every program that prints — and the
// driver answered with a one-line `note:` and a mingw retry, reporting success.
// The differential that should have caught it counts a link failure as an ORACLE
// failure, so it went to 0-compared and still printed `ok`. Two quiet fallbacks,
// two weeks.
//
// So this is a WARNING, on by default, and it names what was skipped. Suppress
// it with -Wno-toolchain-fallback only where the fallback is the deliberate
// choice — which should be almost nowhere, and never in our own scripts.
static void warnToolchainFallback(XTCommandLineOptions *opts,
                                  const char *what, const char *why) {
    if ([opts.suppressedWarnings containsObject:@"toolchain-fallback"]) return;
    fprintf(stderr,
        "xcc: warning: %s was built by the SYSTEM toolchain, not the in-house one.\n"
        "  Reason: %s\n"
        "  The in-house assembler/linker did not produce this binary, so a gap in\n"
        "  them is not visible here. Silence with -Wno-toolchain-fallback if this\n"
        "  fallback is deliberate.\n",
        what, why);
}

// Report a refused fallback. Returns the exit status the caller should return.
static int clangFallbackRefused(const char *what) {
    fprintf(stderr,
        "xcc: error: %s failed, and the clang fallback is disabled.\n"
        "  The in-house toolchain could not build this. That is a REAL gap — most\n"
        "  likely the backend emitted something the in-house assembler does not\n"
        "  implement yet. Re-run with -V to see the failing line.\n"
        "  Set XTC_ALLOW_CLANG_FALLBACK=1 to fall back to clang meanwhile.\n",
        what);
    return 1;
}

// If --sign was given, run xcc-sign over the finished Mach-O as a last stage,
// replacing the default ad-hoc signature with a developer one. Returns 0 when
// nothing was requested or signing succeeded, non-zero (already reported) on
// failure. Only meaningful for Mach-O outputs (arm64 / ios).
static int signIfRequested(XTCommandLineOptions *opts, const char *argv0, NSString *outPath) {
    if (!opts.signIdentityPath) return 0;
    NSString *tool = resolveSiblingTool(argv0, @"xcc-sign");
    if (!tool) { fprintf(stderr, "xcc: error: --sign needs xcc-sign (not found)\n"); return 1; }
    NSMutableArray<NSString *> *args =
        [@[@"--identity", opts.signIdentityPath, @"--identifier",
           outPath.lastPathComponent, outPath] mutableCopy];
    if (opts.signEntitlementsPath)
        [args insertObject:opts.signEntitlementsPath atIndex:2],
        [args insertObject:@"--entitlements" atIndex:2];
    int rc = runChild(tool, args);
    if (rc != 0) { fprintf(stderr, "xcc: error: xcc-sign failed (rc=%d)\n", rc); return rc; }
    if (!opts.quiet)
        fprintf(stderr, "xcc: developer-signed -> '%s'\n", outPath.UTF8String);
    return 0;
}

// In-house by DEFAULT on x86_64, win64 and arm9 — arm64 has its own
// useSelfHost below, host-gated because it writes Mach-O. `--no-self-host`
// forces the external toolchain; `--self-host` is still accepted and is now an
// affirmation of the default rather than a request.
//
// "No external toolchain" is what happens when you type nothing, which was the
// whole point. Every call site still falls back on its own when the in-house
// path genuinely cannot do the job — a `-l` it cannot satisfy, a raw linker
// flag — so this changes WHICH tool links a program both could link, and
// nothing else.
//
// It was NOT flipped the first time it was tried, and that is worth keeping:
// flipping took the corpus from 389 fixtures built to 375, because this tree
// refuses a silent clang fallback and a gap therefore becomes a hard error.
// Four gaps had to close first — `_xtc_sinit_run` missing from the freestanding
// runtime (#1173), the real libc reached through archive reading (#1170,
// #1174), two SSE mnemonics (#1175), and `getpid`, which mingw had been quietly
// supplying to win64 (#1176). Each was found by measuring, not by reasoning:
// the corpus named every one of them.
//
// With them closed, both targets match the toolchain they replace:
//   x86_64  389 built, compile-fail 0, PASS 387 — musl-clang's number exactly,
//           on the same two pre-existing failures (hfa_struct_return,
//           vectorize_outer_iv_addend).
//   win64   388 built, compile-fail 1, PASS 387 — the mingw baseline, on the
//           same two (cvariadic_call, vectorize_outer_iv_addend).
//
// Re-measure both before touching this gate; a regression here is silent from
// the compiler's side and only the sweeps see it.

// The static musl libc. Used by the IN-HOUSE link: our own linker reads `.a`
// archives now (#1170), so a program calling a real C function needs the
// library rather than a reimplementation of it. Resolution order: the env
// override, the dev-machine toolchain, then the copy `make install` vendors
// into the install as lib/xc/x86_64-sysroot (task #32) — which is what keeps
// `-A x86_64` toolchain-free on a machine that never saw /opt/clang.
//
// Nil means NO pool anywhere, and since the runtime's heap delegates to
// calloc/free that is fatal for a static executable — even main(){return 42}
// references libc. The old "a freestanding program that touches no libc links
// exactly as before" property died with that delegation; callers hard-error
// via x86MissingPool() rather than letting the link fail on 'calloc' five
// layers down.
static NSString * _Nullable x86MuslLibc(NSString * _Nullable support) {
    NSFileManager *fm = [NSFileManager defaultManager];
    const char *tcEnv = getenv("XTC_X86_64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/linux";
    NSString *a = [tc stringByAppendingPathComponent:@"x86_64-linux-musl/lib/libc.a"];
    if ([fm fileExistsAtPath:a]) return a;
    NSString *v = [support stringByAppendingPathComponent:@"x86_64-sysroot/libc.a"];
    return (v && [fm fileExistsAtPath:v]) ? v : nil;
}

static int x86MissingPool(NSString * _Nullable support) {
    const char *tcEnv = getenv("XTC_X86_64_TOOLCHAIN");
    fprintf(stderr,
        "xcc: error: the x86-64 static link needs musl's libc.a, and no copy was found.\n"
        "  Looked beside %s%s and in %s/x86_64-sysroot.\n"
        "  `make install` vendors the pool into the install when /opt/clang/linux\n"
        "  exists; otherwise point XTC_X86_64_TOOLCHAIN at a musl cross toolchain.\n",
        tcEnv ? tcEnv : "/opt/clang/linux",
        tcEnv ? " (XTC_X86_64_TOOLCHAIN)" : "",
        support ? support.UTF8String : "(no support root)");
    return 1;
}

// crt-linux.s leaves the process through `call exit`, so a musl link runs
// atexit + the stdio flush (task #30 — a raw exit_group dropped everything
// still buffered on a piped stdout: musl goes fully buffered after its first
// write to a non-tty, and nothing ever wrote the rest). A link with NO libc
// pool must still define `exit`: this is the raw exit_group fallback.
// Appended exactly when the pool is absent — beside the pool it would shadow
// musl's exit, because an archive member is only pulled for a symbol nothing
// else defines.
static NSString * _Nullable x86ExitStub(NSString * _Nullable support) {
    if (!support) return nil;
    NSString *p = [support stringByAppendingPathComponent:
                   @"x86_64/runtime/exitstub-linux.s"];
    return [[NSFileManager defaultManager] fileExistsAtPath:p] ? p : nil;
}

// The compiler-support builtins beside it (finding #16). C code compiled by
// clang/gcc calls libgcc for what the ISA lacks an instruction for — 128-bit
// division (`__udivti3`, mbedcrypto's bignum), soft-float oddments — and
// neither our runtime nor musl defines those. The pool goes LAST: builtins
// are freestanding, so nothing they pull can re-open an earlier archive.
static NSString * _Nullable x86MuslLibgcc(NSString * _Nullable support) {
    NSFileManager *fm = [NSFileManager defaultManager];
    const char *tcEnv = getenv("XTC_X86_64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/linux";
    NSString *a = [tc stringByAppendingPathComponent:@"x86_64-linux-musl/lib/libgcc.a"];
    if ([fm fileExistsAtPath:a]) return a;
    NSString *v = [support stringByAppendingPathComponent:@"x86_64-sysroot/libgcc.a"];
    return (v && [fm fileExistsAtPath:v]) ? v : nil;
}

// The Windows C runtime, same idea as x86MuslLibc() — a POOL our own linker
// pulls from, not a toolchain we shell out to. Nil when the sysroot is absent,
// which is not an error: a program touching no libc links exactly as before.
//
// TWO archives, and the split is not arbitrary. libmingwex.a is mingw's own
// static C99 code; libmsvcrt.a carries the `ucrt_extra` objects, which is where
// snprintf actually lives. Neither is msvcrt.dll itself — msvcrt's printf is
// not C99-conformant, so mingw ships its own and reaches the real formatter
// through `__imp___stdio_common_vsprintf` in ucrtbase.dll, resolved from
// win32-imports.map. That indirection is why adding msvcrt to the import map
// alone could never have worked.
// Unlike x86-64, absence stays non-fatal: the win64 freestanding runtime
// carries its own allocator and printf, so a program touching no real C
// function links and runs with no pool at all (verified: Stdio.printf under
// wine with the toolchain hidden). Each archive falls back to the install's
// vendored lib/xc/win64-sysroot copy (task #32) independently.
static NSArray<NSString *> * _Nullable win64Libc(NSString * _Nullable support) {
    const char *tcEnv = getenv("XTC_WIN64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/win64";
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *vend = [support stringByAppendingPathComponent:@"win64-sysroot"];
    NSString *(^find)(NSString *) = ^NSString *(NSString *rel) {
        NSString *p = [tc stringByAppendingPathComponent:
                       [@"x86_64-w64-mingw32/" stringByAppendingString:rel]];
        if ([fm fileExistsAtPath:p]) return p;
        NSString *v = [vend stringByAppendingPathComponent:rel.lastPathComponent];
        return (v && [fm fileExistsAtPath:v]) ? v : nil;
    };
    NSMutableArray<NSString *> *out = [NSMutableArray array];
    for (NSString *n in @[@"lib/libmingwex.a", @"lib/libmsvcrt.a"]) {
        NSString *p = find(n);
        if (p) [out addObject:p];
    }
    // The compiler-support builtins, LAST (finding #16, the win64 face of it):
    // 128-bit division and friends that C members reference and no libc
    // defines. Freestanding, so nothing it pulls re-opens an earlier archive.
    NSString *rt = find(@"clang-rt/libclang_rt.builtins-x86_64.a");
    if (rt) [out addObject:rt];
    return out.count ? out : nil;
}

static BOOL selfHostByDefault(XTCommandLineOptions *opts) {
    return !opts.noSelfHost;
}

static BOOL useSelfHost(XTCommandLineOptions *opts) {
    // In-house on EVERY host (task #32). This was opt-in on non-Apple hosts
    // ("a bare -A arm64 there is unusual"), but off-by-default meant `-A
    // arm64` on Linux/Windows failed by default — there is no clang-for-mac
    // fallback on those hosts AT ALL, which is exactly why the in-house
    // writer exists. Caveat that stays: -l against macOS SYSTEM libraries
