// The macOS SDK's usr/lib dirs — where the `.tbd` text stubs for shared-cache
// system libraries live (a real `/usr/lib/lib*.dylib` no longer exists on disk).
// $SDKROOT wins; else the version-independent `MacOSX.sdk` symlink under Xcode or
// the Command Line Tools. Empty if no SDK is found (→ those -l fall back to clang).
// The Apple SDK roots for a platform: $SDKROOT first, then the
// version-independent .sdk symlinks under Xcode (and, for macOS only, the
// Command Line Tools). `platform` is opts.applePlatform — nil means macOS.
static NSArray<NSString *> *appleSdkRoots(NSString *platform) {
    NSMutableArray<NSString *> *sdks = [NSMutableArray array];
    const char *sdkroot = getenv("SDKROOT");
    if (sdkroot && *sdkroot) [sdks addObject:@(sdkroot)];
    if ([platform isEqualToString:@"ios"]) {
        [sdks addObject:@"/Applications/Xcode.app/Contents/Developer/Platforms/"
                         "iPhoneOS.platform/Developer/SDKs/iPhoneOS.sdk"];
    } else if ([platform isEqualToString:@"ios-sim"]) {
        [sdks addObject:@"/Applications/Xcode.app/Contents/Developer/Platforms/"
                         "iPhoneSimulator.platform/Developer/SDKs/iPhoneSimulator.sdk"];
    } else {
        [sdks addObjectsFromArray:@[
            @"/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk",
            @"/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk"]];
    }
    return sdks;
}

static NSArray<NSString *> *macosSdkLibDirs(NSString *platform) {
    NSFileManager *fm = [NSFileManager defaultManager];
    for (NSString *sdk in appleSdkRoots(platform)) {
        NSString *lib = [sdk stringByAppendingPathComponent:@"usr/lib"];
        BOOL isDir = NO;
        if ([fm fileExistsAtPath:lib isDirectory:&isDir] && isDir)
            return @[lib, [lib stringByAppendingPathComponent:@"system"]];
    }
    return @[];
}

// The macOS SDK's framework dirs — where `<F>.framework/<F>.tbd` stubs live.
static NSArray<NSString *> *macosSdkFrameworkDirs(NSString *platform) {
    NSFileManager *fm = [NSFileManager defaultManager];
    for (NSString *sdk in appleSdkRoots(platform)) {
        NSString *fw = [sdk stringByAppendingPathComponent:@"System/Library/Frameworks"];
        BOOL isDir = NO;
        if ([fm fileExistsAtPath:fw isDirectory:&isDir] && isDir)
            return @[fw, [sdk stringByAppendingPathComponent:@"System/Library/PrivateFrameworks"]];
    }
    return @[];
}

// Resolve the user's link flags into things the in-house linker can take:
// concrete library PATHS (dylib / .tbd stub / static .a) and raw ld directives.
// Sets *sysLibs when something is genuinely unresolvable, which is the signal
// to fall back to clang rather than build an image missing what was asked for.
//
// Shared by the EXECUTABLE and DYLIB link paths. It used to be inline in the
// executable one, which is why `--emit-lib` silently ignored every -Wl object
// and archive: a library wrapping external C came out the same size whatever
// was passed, and aborted at load on the first wrapped symbol.
static void resolveUserLinkInputs(XTCommandLineOptions *opts, NSFileManager *fm,
                                  NSMutableArray<NSString *> *userDylibs,
                                  NSMutableArray<NSString *> *linkerRaw,
                                  BOOL *sysLibsOut) {
    BOOL sysLibs = NO;
    NSMutableArray<NSString *> *dylibDirs = [opts.libraryPaths mutableCopy] ?: [NSMutableArray array];
    [dylibDirs addObjectsFromArray:@[@"/usr/local/lib", @"/opt/homebrew/lib", @"/usr/lib"]];
    // For a system library with no on-disk .dylib, fall to the SDK's .tbd stub.
    NSMutableArray<NSString *> *tbdDirs = [opts.libraryPaths mutableCopy] ?: [NSMutableArray array];
    [tbdDirs addObjectsFromArray:macosSdkLibDirs(opts.applePlatform)];
    // Framework search dirs: user -F (from opts.linkerArgs / libraryPaths, if
    // any) then the SDK. `-framework <F>` binds `<F>.framework/<F>.tbd`.
    NSMutableArray<NSString *> *fwDirs = [NSMutableArray array];
    [fwDirs addObjectsFromArray:macosSdkFrameworkDirs(opts.applePlatform)];
    // Full driver-style flag list (NO = not a bare-ld invocation): we want the
    // -l/-framework/-Wl,/-Xlinker set so we can resolve or forward each.
    NSArray<NSString *> *lflags = appendLinkerFlags(opts, NO);  // -l/-framework… + $XTC_LDFLAGS
    for (NSUInteger fi = 0; fi < lflags.count; fi++) {
        NSString *fl = lflags[fi];
        if ([fl hasPrefix:@"-l"] && fl.length > 2) {
            NSString *base = [fl substringFromIndex:2];
            NSString *found = nil;
            NSString *dylib = [NSString stringWithFormat:@"lib%@.dylib", base];
            for (NSString *dir in dylibDirs) {
                NSString *p = [dir stringByAppendingPathComponent:dylib];
                if ([fm fileExistsAtPath:p]) { found = p; break; }
            }
            if (!found) {                      // no real dylib → try an SDK .tbd stub
                NSString *tbd = [NSString stringWithFormat:@"lib%@.tbd", base];
                for (NSString *dir in tbdDirs) {
                    NSString *p = [dir stringByAppendingPathComponent:tbd];
                    if ([fm fileExistsAtPath:p]) { found = p; break; }
                }
            }
            if (!found) {                      // no dylib/.tbd → try a static .a archive
                NSString *ar = [NSString stringWithFormat:@"lib%@.a", base];
                for (NSString *dir in dylibDirs) {
                    NSString *p = [dir stringByAppendingPathComponent:ar];
                    if ([fm fileExistsAtPath:p]) { found = p; break; }
                }
            }
            if (found) [userDylibs addObject:found];   // xtcln-arm64 dispatches by extension
            else { sysLibs = YES; break; }    // genuinely unresolvable → clang
        } else if ([fl isEqualToString:@"-framework"] && fi + 1 < lflags.count) {
            NSString *name = lflags[++fi];     // `-framework <Name>`
            NSString *found = nil;
            NSString *rel = [NSString stringWithFormat:@"%@.framework/%@.tbd", name, name];
            for (NSString *dir in fwDirs) {
                NSString *p = [dir stringByAppendingPathComponent:rel];
                if ([fm fileExistsAtPath:p]) { found = p; break; }
            }
            if (found) [userDylibs addObject:found];
            else { sysLibs = YES; break; }    // no framework .tbd (or umbrella) → clang
        } else if ([fl hasPrefix:@"-L"] || [fl hasPrefix:@"-F"]) {
            continue;                          // search dir (already in the dir lists)
        } else if ([fl isEqualToString:@"-Xlinker"] && fi + 1 < lflags.count) {
            [linkerRaw addObject:lflags[++fi]];   // unwrap `-Xlinker <arg>` → raw ld arg
        } else if ([fl hasPrefix:@"-Wl,"]) {      // `-Wl,a,b,c` → raw ld args a b c
            for (NSString *tok in [[fl substringFromIndex:4] componentsSeparatedByString:@","])
                if (tok.length) [linkerRaw addObject:tok];
        } else {
            // Any other linker directive: forward it raw to the in-house linker
            // rather than falling back to clang. It honours what it understands
            // (e.g. -rpath) and ignores the rest — a dropped flag that mattered
            // is then a fixable xtcln-arm64 bug, not a silent clang divergence.
            [linkerRaw addObject:fl];
        }
    }
    // Bug 068: an ObjC object needs libobjc, and nothing else in the link
    // provides it. `_objc_msgSend` lives in /usr/lib/libobjc.A.dylib; libSystem
    // does NOT re-export it (checked), and clang passes `-lobjc` implicitly for
    // Objective-C while we never did — so the symbol took fallback ordinal 1 and
    // dyld refused at LAUNCH, naming a library that never had it.
    //
    // Added only when something actually references ObjC, so no binary that has
    // none gains a load command. The test reads the FOREIGN objects' symbol
    // tables: xtc emits no `_objc_*` itself, so any such reference arrived in a
    // `-Xlinker foo.o` or an archive, which is exactly what is scanned here.
    if (!sysLibs && (userDylibs.count || opts.applePlatform)) {
        // The test is a scan of the object's BYTES for an ObjC symbol name,
        // rather than a parse: the driver does not link the Mach-O reader, and
        // pulling the whole writer in to answer one yes/no would be a poor
        // trade. Every Mach-O object carries its symbol names as plain text in
        // the string table, so the substring is a faithful signal. A C file
        // that merely contains the literal would add a load command it does not
        // need — harmless, and the alternative costs far more.
        BOOL wantsObjc = NO;
        for (NSString *raw in linkerRaw) {
            if (!([raw hasSuffix:@".o"] || [raw hasSuffix:@".a"])) continue;
            NSData *blob = [NSData dataWithContentsOfFile:raw
                                                  options:NSDataReadingMappedIfSafe error:NULL];
            if (!blob.length) continue;
            NSData *needle = [@"_OBJC_CLASS_$_" dataUsingEncoding:NSUTF8StringEncoding];
            NSData *needle2 = [@"_objc_msgSend" dataUsingEncoding:NSUTF8StringEncoding];
            if ([blob rangeOfData:needle options:0 range:NSMakeRange(0, blob.length)].location != NSNotFound
             || [blob rangeOfData:needle2 options:0 range:NSMakeRange(0, blob.length)].location != NSNotFound) {
                wantsObjc = YES; break;
            }
        }
        // iOS: the platform shim (xtios.c) reaches NSURLSession through the
        // ObjC runtime, so every iOS image depends on Foundation and libobjc
        // — Foundation after the user's frameworks unless named already.
        if (opts.applePlatform) {
            BOOL haveFoundation = NO;
            for (NSString *p in userDylibs)
                if ([p hasSuffix:@"/Foundation.framework/Foundation.tbd"]) haveFoundation = YES;
            if (!haveFoundation)
                for (NSString *dir in fwDirs) {
                    NSString *p = [dir stringByAppendingPathComponent:@"Foundation.framework/Foundation.tbd"];
                    if ([fm fileExistsAtPath:p]) { [userDylibs addObject:p]; break; }
                }
            wantsObjc = YES;
        }
        if (wantsObjc) {
            // libobjc sits beside the frameworks, in the same SDK.
            for (NSString *fw in fwDirs) {
                NSRange r = [fw rangeOfString:@"/System/Library/"];
                if (r.location == NSNotFound) continue;
                NSString *lib = [[fw substringToIndex:r.location]
                                    stringByAppendingString:@"/usr/lib/libobjc.tbd"];
                if ([fm fileExistsAtPath:lib] && ![userDylibs containsObject:lib]) {
                    [userDylibs addObject:lib];
                    break;
                }
            }
        }
    }
    if (sysLibsOut) *sysLibsOut = sysLibs;
}

// Rewrite the arm64 backend's Mach-O-flavoured asm into ELF for Android/bionic.
// The backend emits one Mach-O convention uniformly — every symbol carries a
// leading `_` (the Mach-O C-symbol prefix), addresses use @PAGE/@PAGEOFF, and
// sections are __TEXT/__DATA — so the transform is mechanical: strip exactly one
// leading underscore from every symbol occurrence (which lines the names up with
// the SAME stub compiled for ELF, where C symbols gain no prefix), rewrite the
// page relocations to the GNU `:lo12:` / `:got:` forms, and remap the sections.
// Static initialisers (`__mod_init_func`) become `.init_array`, which bionic's
// loader runs before main — the same guarantee Mach-O gives.
// Mach-O-flavoured arm64 asm → ELF asm. `shared` additionally makes the result
// linkable as a **shared object**, which a bare rewrite is not:
//
//   * Every `.globl` gains a `.hidden`. In a `.so` a global symbol is
//     PREEMPTIBLE, and lld refuses `adrp`/`add :lo12:` (ADR_PREL_PG_HI21 /
//     ADD_ABS_LO12_NC) and `.quad <sym>` (ABS64) against a preemptible symbol
//     — "recompile with -fPIC". Hidden symbols still link across the objects
//     that make up this library; they simply cannot be interposed, which is
//     what lets lld keep the pc-relative pair and rewrite each vtable `.quad`
//     into an `R_AARCH64_RELATIVE` the loader biases at map time. This is why
//     the same asm links fine as a PIE and as a Mach-O dylib (Mach-O symbols
//     are non-preemptible to begin with) but not as an ELF `.so`.
//   * Every `.comm` becomes a concrete hidden object in `.bss`. A common
//     symbol has no home section, so it is preemptible by construction and no
//     amount of visibility marking fixes it; giving it a definition does.
//     The emitting section is restored afterwards so the surrounding `.data`
//     run is unbroken.
// Drop exactly ONE leading underscore from every symbol, leaving the operand
// syntax (`@PAGE` / `@PAGEOFF`) alone. That is the whole difference between the
// backend's Mach-O symbol names and the ELF ones the Android runtime uses: C's
// `_xtc_alloc` gains an underscore on Darwin and none on ELF, so the backend's
// `__xtc_alloc` and the runtime's `_xtc_alloc` are the same symbol. The
// in-house Android path needs this WITHOUT the dialect rewrite, because it
// feeds XAArm64Assembler, which reads the Mach-O dialect.
static NSString *stripSymbolUnderscoreArm64(NSString *asm_) {
    if (!asm_) return @"";
    NSRegularExpression *strip = [NSRegularExpression
        regularExpressionWithPattern:@"(^|[\\s,\\[])_([A-Za-z_$.])"
                             options:0 error:NULL];
    NSMutableArray<NSString *> *out = [NSMutableArray array];
    for (NSString *l in [asm_ componentsSeparatedByString:@"\n"])
        [out addObject:XTRegexReplace(strip, l, @"$1$2")];
    return [out componentsJoinedByString:@"\n"];
}

// machoToElfArm64 lives in link/XTMachOToElfArm64.m now: the arm64 codegen
// TESTS need the same rewrite to run their fixtures under an ELF toolchain,
// and a second copy of it would be free to drift from this one.


// The NDK's aarch64-linux-android clang, discovered under $ANDROID_NDK_HOME /
// $ANDROID_HOME/ndk/<ver>. Returns the newest per-API wrapper (API 24 — a broad
// floor that still runs on the emulator), or nil with a diagnostic.
static NSString *_Nullable androidNdkClangEx(NSString *_Nonnull *_Nullable ndkOut) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSMutableArray<NSString *> *ndks = [NSMutableArray array];
    const char *nh = getenv("ANDROID_NDK_HOME");
    if (nh && *nh) [ndks addObject:@(nh)];
    for (NSString *var in @[@"ANDROID_HOME", @"ANDROID_SDK_ROOT"]) {
        const char *v = getenv(var.UTF8String);
        NSString *root = (v && *v) ? @(v)
            : [NSHomeDirectory() stringByAppendingPathComponent:@"Library/Android/sdk"];
        NSString *nd = [root stringByAppendingPathComponent:@"ndk"];
        for (NSString *e in [[fm contentsOfDirectoryAtPath:nd error:NULL]
                             sortedArrayUsingSelector:@selector(compare:)])
            [ndks addObject:[nd stringByAppendingPathComponent:e]];
    }
    for (NSString *ndk in [ndks reverseObjectEnumerator]) {   // newest first
        NSString *tc = [ndk stringByAppendingPathComponent:@"toolchains/llvm/prebuilt"];
        for (NSString *host in [fm contentsOfDirectoryAtPath:tc error:NULL]) {
            NSString *cc = [tc stringByAppendingPathComponent:
                [host stringByAppendingPathComponent:@"bin/aarch64-linux-android24-clang"]];
            if ([fm isExecutableFileAtPath:cc]) { if (ndkOut) *ndkOut = ndk; return cc; }
        }
    }
    fprintf(stderr, "xcc: error: Android NDK not found. Set $ANDROID_NDK_HOME (or "
                    "$ANDROID_HOME with an ndk/<ver> under it).\n");
    return nil;
}

static NSString *_Nullable androidNdkClang(void) { return androidNdkClangEx(NULL); }

// The NativeActivity entry point lives in support/arm64/runtime/android-glue.c,
// with a checked-in assembly translation beside it (glue-android.s, generated by
// gen-glue-android.sh). The clang path compiles the .c; the in-house path
// assembles the .s. ONE source, so the two cannot drift — an inline copy in this
// file was the second definition that would have.

// A Java-package-safe identifier from the output name: lower-case, non-alnum to
// `_`, and never leading with a digit (`9lives` → `_9lives`).


// The in-house Android link: assemble and lay out an aarch64 ELF PIE with NO
// NDK clang and no ld.lld, exactly as the macOS path does for Mach-O and the
// x86_64/arm9 paths do for their ELF. Returns 0 on success, or non-zero to let
// the caller fall back to the clang path.
//
// The input is one translation unit — crt + runtime + the program — because we
// are the whole-program linker. Two spellings have to be reconciled first:
// the backend names symbols the Mach-O way (`__xtc_alloc`) and the runtime the
// ELF way (`_xtc_alloc`), so the program's asm loses one leading underscore;
// and the runtime is NDK-generated, so it arrives in the GNU dialect, which
// XAArm64Assembler normalises. Bionic supplies the rest through DT_NEEDED.

// uxkit/032: the DT_NEEDED list the android ELF writer is handed, as the CSV
// the linker's argv slot takes. The base set is what every Android image is
// expected to name; `--needed` appends. bionic resolves a library's imports
// against its own local group plus the global group and does NOT honour
// RTLD_GLOBAL promotion of an already-loaded library, so a payload that calls
// into a companion .so has to NAME it — which is exactly what the driver's
// post-link addneeded.py was doing by hand.
static NSString *androidNeededCsv(XTCommandLineOptions *opts, NSString *base) {
    NSArray<NSString *> *extra = opts.neededSonames;
    if (extra.count == 0) return base;
    NSMutableArray<NSString *> *all =
        [[base componentsSeparatedByString:@","] mutableCopy];
    for (NSString *n in extra)
        if (n.length && ![all containsObject:n]) [all addObject:n];
    return [all componentsJoinedByString:@","];
}

static int linkAndroidSelfHost(const char *argv0, XTCommandLineOptions *opts,
                               NSString *support, NSString *asmPath, NSString *outPath) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *ln  = resolveSiblingTool(argv0, @"xcc-ln-arm64");
    NSString *crt = [support stringByAppendingPathComponent:@"arm64/runtime/crt-android.s"];
    NSString *rt  = [support stringByAppendingPathComponent:@"arm64/runtime/rt-android.s"];
    if (!ln || ![fm fileExistsAtPath:crt] || ![fm fileExistsAtPath:rt]) {
        if (!opts.quiet)
            fprintf(stderr, "xcc: note: android self-host pieces missing "
                    "(xcc-ln-arm64=%s, crt=%s, rt=%s)\n",
                    ln ? "ok" : "(missing)",
                    [fm fileExistsAtPath:crt] ? "ok" : crt.UTF8String,
                    [fm fileExistsAtPath:rt]  ? "ok" : rt.UTF8String);
        return 1;
    }
    NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                               encoding:NSUTF8StringEncoding error:NULL];
    if (!prog) return 1;
    // NOT renameMainSymbol: there is no C stub here to own `main`. The crt's
    // `_start` calls the program's `main` directly, through __libc_init.
    NSString *stubs   = arm64ClassAllocStubs(prog);   // built from the Mach-O names…
    NSString *crtsrc  = [NSString stringWithContentsOfFile:crt encoding:NSUTF8StringEncoding error:NULL];
    NSString *rtsrc   = [NSString stringWithContentsOfFile:rt  encoding:NSUTF8StringEncoding error:NULL];
    NSString *combined = [NSString stringWithFormat:@"%@\n%@\n%@\n%@",
        crtsrc, rtsrc,
        stripSymbolUnderscoreArm64(stubs),            // …then stripped with the program
        stripSymbolUnderscoreArm64(prog)];
    NSString *combinedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-android-selfhost.s"];
    [combined writeToFile:combinedPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    // libc.so covers stdio/malloc/pthread; libm.so the _xm_* wrappers' tail
    // calls; libdl.so is what every Android image is expected to name.
    int rc = runChild(ln, @[@"--android", @"exe", @"_start", @"-",
                            androidNeededCsv(opts, @"libc.so,libm.so,libdl.so"),
                            combinedPath, outPath]);
    if (!opts.verbose) [fm removeItemAtPath:combinedPath error:NULL];
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: android aarch64 ELF (self-hosted, no clang) -> '%s'  "
                        "(adb push; run)\n", outPath.UTF8String);
    return rc;
}


// -A android --emit-lib: a real Android shared library (bug 067).
//
// NOT the APK path's `.so`, which is a NativeActivity PAYLOAD: that one links
// the android glue, renames the user's `main` to `xt_main` and exports
// ANativeActivity_onCreate. A library wants none of it — no glue, no crt, its
// own public API exported, a soname and the base DT_NEEDED set.
//
// It used to fall through to the HOST's Mach-O dylib path (android rides the
// arm64 back end, and the android branch lives inside linkArm64Executable,
// which the --emit-lib arm goes around), writing a Mach-O into a `.so`: the
// wrong FILE FORMAT for a target that cannot load one, under a name that said
// otherwise.
static int linkAndroidShared(const char *argv0, XTCommandLineOptions *opts,
                             NSString *asmPath, NSString *outPath) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm64");
    NSString *rt = support ? [support stringByAppendingPathComponent:@"arm64/runtime/rt-android.s"] : nil;
    if (!support || !ln || !rt || ![fm fileExistsAtPath:rt]) {
        fprintf(stderr, "xcc: error: -A android --emit-lib needs the android runtime "
                        "(xcc-ln-arm64 + support/arm64/runtime/rt-android.s)\n");
        return 1;
    }
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                 encoding:NSUTF8StringEncoding error:NULL] ?: @"";
    // Public API = this module's own `.globl`s, gathered BEFORE the runtime is
    // prepended so the runtime's own globals stay private.
    NSMutableSet<NSString *> *exports = [NSMutableSet set];
    NSRegularExpression *ge = [NSRegularExpression
        regularExpressionWithPattern:@"(?m)^\\s*\\.globl\\s+(\\S+)" options:0 error:NULL];
    for (NSTextCheckingResult *m in [ge matchesInString:asmText options:0
                                                  range:NSMakeRange(0, asmText.length)])
        [exports addObject:stripSymbolUnderscoreArm64([asmText substringWithRange:[m rangeAtIndex:1]])];

    NSString *rtsrc = [NSString stringWithContentsOfFile:rt encoding:NSUTF8StringEncoding error:NULL] ?: @"";
    NSString *combined = [NSString stringWithFormat:@"%@\n%@\n%@",
        rtsrc,
        stripSymbolUnderscoreArm64(arm64ClassAllocStubs(asmText)),
        stripSymbolUnderscoreArm64(asmText)];
    NSString *tmp = xtcTempDir();
    // Written AS IS, exactly as the APK's .so link does. machoToElfArm64Ex is
    // for the CLANG path only: the in-house assembler takes the back end's
    // Mach-O flavour natively, and rt-android.s is already ELF-flavoured
    // (generated by the NDK clang). Running the converter over the pair strips
    // the runtime's labels and adrp operands while leaving its `:lo12:` ones
    // alone, which turns a self-consistent file into `adrp x20, xt_threads_active`
    // paired with `:lo12:_xt_threads_active` — a symbol that then exists nowhere.
    NSString *elfPath = [tmp stringByAppendingPathComponent:@"xtc-android-lib.s"];
    [combined writeToFile:elfPath atomically:YES
                 encoding:NSUTF8StringEncoding error:NULL];
    NSString *exportsPath = [tmp stringByAppendingPathComponent:@"xtc-android-lib-exports.txt"];
    [[[exports allObjects] componentsJoinedByString:@"\n"] writeToFile:exportsPath
        atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    NSString *soname = outPath.lastPathComponent;
    int rc = runChild(ln, @[@"--android", @"so", soname, exportsPath,
                            androidNeededCsv(opts, @"libc.so,libm.so,libdl.so"),
                            elfPath, outPath]);
    if (rc != 0) {
        fprintf(stderr, "xcc: error: android shared-library link failed\n");
        return 1;
    }
    if (!opts.quiet)
        fprintf(stderr, "xcc: android aarch64 shared library -> '%s'  (soname %s)\n",
                outPath.UTF8String, soname.UTF8String);
    return 0;
}

static int linkAndroidExecutable(const char *argv0, XTCommandLineOptions *opts,
                                 NSString *asmPath, NSString *outPath) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    if (support && useSelfHost(opts)) {
        int rc = linkAndroidSelfHost(argv0, opts, support, asmPath, outPath);
        if (rc == 0) return 0;
        if (!clangFallbackAllowed())
            return clangFallbackRefused("android in-house link");
        warnToolchainFallback(opts, "this android executable",
                              "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
    }
    NSString *cc = androidNdkClang();
    if (!cc || !support) return 1;
    NSString *libxt = [support stringByAppendingPathComponent:@"arm64/runtime/libxt.c"];
    if (![fm fileExistsAtPath:libxt]) {
        fprintf(stderr, "xcc: error: arm64 runtime not found at '%s'\n", libxt.UTF8String);
        return 1;
    }
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    // Same rename the macOS path does: the user's `main` becomes `xt_main`, and
    // the stub supplies the real `main` that wraps it (arg capture + exit code).
    NSString *renamed = asmText ? renameMainSymbol(asmText) : @"";
    NSString *elf = XTMachOToElfArm64(renamed);
    NSString *elfPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-android.s"];
    [elf writeToFile:elfPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-android-stub.c"];
    [arm64StubSource(renamed) writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    NSMutableArray<NSString *> *a = [@[cc, @"-fPIC", @"-pie", @"-O2",
        elfPath, stubPath, libxt, @"-lm", @"-o", outPath] mutableCopy];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) { [fm removeItemAtPath:stubPath error:NULL];
                         [fm removeItemAtPath:elfPath error:NULL]; }
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: android aarch64 ELF -> '%s'  (adb push; run)\n", outPath.UTF8String);
    return rc;
}


// ─────────────────────────────────────────────────────────────────────────────
// -A android --emit-apk: an installable NativeActivity APK.
//
// Same compiler output as the ELF path, packaged differently. The program is
// linked as `lib<name>.so` (NOT an executable) because that is what a
// NativeActivity loads; its entry point is `android_main`, supplied by the glue
// below, which calls the renamed user `xt_main`. stdout/stderr are dup'd onto a
// pipe drained by a thread into logcat, so the UNCHANGED runtime's printf is
// visible without the library knowing it is on Android at all.
// ─────────────────────────────────────────────────────────────────────────────

// The NativeActivity entry point lives in support/arm64/runtime/android-glue.c,
// with a checked-in assembly translation beside it (glue-android.s, generated by
// gen-glue-android.sh). The clang path compiles the .c; the in-house path
// assembles the .s. ONE source, so the two cannot drift — an inline copy in this
// file was the second definition that would have.

// A Java-package-safe identifier from the output name: lower-case, non-alnum to
// `_`, and never leading with a digit (`9lives` → `_9lives`).
static NSString *androidSafeName(NSString *base) {
    NSMutableString *m = [NSMutableString string];
    for (NSUInteger i = 0; i < base.length; i++) {
        unichar c = [base characterAtIndex:i];
        if (c >= 'A' && c <= 'Z') c = (unichar)(c - 'A' + 'a');
        [m appendFormat:@"%C", (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ? c : (unichar)'_'];
    }
    if (m.length == 0) [m setString:@"app"];
    unichar f = [m characterAtIndex:0];
    if (f >= '0' && f <= '9') [m insertString:@"_" atIndex:0];
    return m;
}


// The debug signing key, generated ONCE and cached under ~/.xcc.
//
// Android will not install an unsigned package, and its only interest in the
// certificate is identity — two packages are "the same app" when the signing
// certificate matches. So a debug key needs no authority, only stability:
// generated on first use and reused after, exactly as the SDK's debug keystore
// behaves, but with no JDK and no `keytool` involved.
//
// Returned as @{@"n","e","d","cert"}. NOT for release: a release build should
// be signed with the developer's own key.
static NSDictionary *_Nullable androidDebugKey(void) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *dir = [NSHomeDirectory() stringByAppendingPathComponent:@".xcc"];
    NSString *path = [dir stringByAppendingPathComponent:@"android-debug.key"];
    NSDictionary *have = [NSDictionary dictionaryWithContentsOfFile:path];
    if (have[@"n"] && have[@"e"] && have[@"d"] && have[@"cert"]) {
        // Backfill the raw sidecar for a cache made before it existed, so the
        // xtc driver can sign with the key this one already uses.
        NSString *rawPath = [path stringByAppendingPathExtension:@"raw"];
        if (![fm fileExistsAtPath:rawPath]) {
            NSMutableData *raw = [NSMutableData data];
            [raw appendBytes:"XKEY1" length:5];
            for (NSString *f in @[@"n", @"e", @"d", @"cert"]) {
                NSData *v = have[f];
                uint32_t n32 = (uint32_t)v.length;
                for (int i = 0; i < 4; i++) { uint8_t b = (uint8_t)(n32 >> (8*i)); [raw appendBytes:&b length:1]; }
                [raw appendData:v];
            }
            [raw writeToFile:rawPath atomically:YES];
            [fm setAttributes:@{NSFilePosixPermissions: @0600} ofItemAtPath:rawPath error:NULL];
        }
        return have;
    }

    if (!getenv("XTC_QUIET_KEYGEN"))
        fprintf(stderr, "xcc: generating a debug signing key (once) -> %s\n", path.UTF8String);
    NSDictionary<NSString *, NSData *> *k = [XTCrypto rsaGenerateKeyOfBits:2048];
    if (!k) {
        fprintf(stderr, "xcc: error: cannot generate a signing key (no /dev/urandom?)\n");
        return nil;
    }
    NSError *err = nil;
    NSData *cert = [XTApkSign selfSignedCertificateWithModulus:k[@"n"]
                                                publicExponent:k[@"e"]
                                               privateExponent:k[@"d"]
                                                    commonName:@"xc debug"
                                                         error:&err];
    if (!cert) {
        fprintf(stderr, "xcc: error: cannot build the debug certificate: %s\n",
                err.localizedDescription.UTF8String);
        return nil;
    }
    NSDictionary *out = @{ @"n": k[@"n"], @"e": k[@"e"], @"d": k[@"d"], @"cert": cert };
    [fm createDirectoryAtPath:dir withIntermediateDirectories:YES attributes:nil error:NULL];
    [out writeToFile:path atomically:YES];
    // ...and the same key in a RAW form the xtc driver can read. A plist needs a
    // plist parser, which the port has no business growing to sign a package;
    // this is four length-prefixed blobs. Written beside the plist rather than
    // replacing it, so an existing cache keeps working and both drivers sign
    // with the SAME key — a package rebuilt by either one keeps its identity,
    // which is what `adb install -r` requires.
    NSMutableData *raw = [NSMutableData data];
    [raw appendBytes:"XKEY1" length:5];
    for (NSString *f in @[@"n", @"e", @"d", @"cert"]) {
        NSData *v = out[f];
        uint32_t n32 = (uint32_t)v.length;
        for (int i = 0; i < 4; i++) { uint8_t b = (uint8_t)(n32 >> (8*i)); [raw appendBytes:&b length:1]; }
        [raw appendData:v];
    }
    NSString *rawPath = [path stringByAppendingPathExtension:@"raw"];
    [raw writeToFile:rawPath atomically:YES];
    [fm setAttributes:@{NSFilePosixPermissions: @0600} ofItemAtPath:rawPath error:NULL];
    // The private key is readable only by its owner, as an ssh key would be.
    [fm setAttributes:@{NSFilePosixPermissions: @0600} ofItemAtPath:path error:NULL];
    return out;
}

static int linkAndroidApk(const char *argv0, XTCommandLineOptions *opts,
                          NSString *asmPath, NSString *outPath) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    if (!support) return 1;
    // No SDK. aapt2 / zipalign / apksigner / android.jar were all replaced by
    // XTApkWriter and XTApkSign, so `--emit-apk` needs nothing installed beyond
    // this compiler — which is what THE RULE asks for. The glue
    // and the runtime are checked in; only the CLANG FALLBACK below still wants
    // an NDK, and only when the in-house link is refused.
    NSString *libxt = [support stringByAppendingPathComponent:@"arm64/runtime/libxt.c"];
    NSString *glueC = [support stringByAppendingPathComponent:@"arm64/runtime/android-glue.c"];

    NSString *base  = [outPath.lastPathComponent stringByDeletingPathExtension];
    NSString *name  = androidSafeName(base);
    NSString *pkg   = [@"org.compile_xc." stringByAppendingString:name];
    NSString *tmp   = xtcTempDir();
    NSString *stage = [tmp stringByAppendingPathComponent:@"apk"];
    NSString *libDir = [stage stringByAppendingPathComponent:@"lib/arm64-v8a"];
    [fm removeItemAtPath:stage error:NULL];
    [fm createDirectoryAtPath:libDir withIntermediateDirectories:YES attributes:nil error:NULL];

    // ── the program, as a shared object ───────────────────────────────────
    // The .so has no `main`: the user's is renamed `xt_main` and the glue's
    // ANativeActivity_onCreate is the entry the framework dlsym()s.
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                  encoding:NSUTF8StringEncoding error:NULL];
    NSString *renamed = asmText ? renameMainSymbol(asmText) : @"";
    NSString *soPath = [libDir stringByAppendingPathComponent:
        [NSString stringWithFormat:@"lib%@.so", name]];
    int rc = 1;
    NSString *elfPath = nil, *stubPath = nil, *exportsPath = nil;

    NSString *ln     = resolveSiblingTool(argv0, @"xcc-ln-arm64");
    NSString *rt     = [support stringByAppendingPathComponent:@"arm64/runtime/rt-android.s"];
    NSString *glueS  = [support stringByAppendingPathComponent:@"arm64/runtime/glue-android.s"];
    BOOL inHouse = useSelfHost(opts) && ln
                && [fm fileExistsAtPath:rt] && [fm fileExistsAtPath:glueS];
    if (inHouse) {
        // Same shape as the executable's in-house link, minus the crt (a .so has
        // no entry point) and plus the glue.
        NSString *rtsrc  = [NSString stringWithContentsOfFile:rt    encoding:NSUTF8StringEncoding error:NULL];
        NSString *gsrc   = [NSString stringWithContentsOfFile:glueS encoding:NSUTF8StringEncoding error:NULL];
        NSString *combined = [NSString stringWithFormat:@"%@\n%@\n%@\n%@",
            gsrc, rtsrc,
            stripSymbolUnderscoreArm64(arm64ClassAllocStubs(renamed)),
            stripSymbolUnderscoreArm64(renamed)];
        elfPath = [tmp stringByAppendingPathComponent:@"xtc-android-so.s"];
        [combined writeToFile:elfPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        // ONE export. Everything else stays internal to the library, which is
        // what lets the writer resolve it all at link time.
        exportsPath = [tmp stringByAppendingPathComponent:@"xtc-android-exports.txt"];
        [@"ANativeActivity_onCreate" writeToFile:exportsPath atomically:YES
                                        encoding:NSUTF8StringEncoding error:NULL];
        rc = runChild(ln, @[@"--android", @"so",
                            [NSString stringWithFormat:@"lib%@.so", name],
                            exportsPath,
                            androidNeededCsv(opts,
                                @"libc.so,libm.so,libdl.so,liblog.so,libandroid.so"),
                            elfPath, soPath]);
        if (rc != 0 && !clangFallbackAllowed())
            return clangFallbackRefused("android in-house --emit-apk link");
    }
    if (rc != 0) {
        NSString *cc = androidNdkClang();
        if (!cc) return 1;
        elfPath = [tmp stringByAppendingPathComponent:@"xtc-android-pic.s"];
        [XTMachOToElfArm64Ex(renamed, YES) writeToFile:elfPath atomically:YES
                                            encoding:NSUTF8StringEncoding error:NULL];
        stubPath = [tmp stringByAppendingPathComponent:@"xtc-android-libstub.c"];
        [arm64StubSourceEx(renamed, YES) writeToFile:stubPath atomically:YES
                                            encoding:NSUTF8StringEncoding error:NULL];
        rc = runChild(@"/usr/bin/env", @[cc, @"-shared", @"-fPIC", @"-O2",
            elfPath, stubPath, libxt, glueC,
            @"-llog", @"-landroid", @"-lm", @"-o", soPath]);
        if (rc != 0) return rc;
    }

    // ── the package ───────────────────────────────────────────────────────
    // Built here rather than shelled out to aapt2 / zip / zipalign: an APK is
    // a ZIP with a compiled manifest, and none of that is compilation — it is
    // a second toolchain the user would have to install for a file this
    // compiler has already finished. See XTApkWriter.
    NSData *soData = [NSData dataWithContentsOfFile:soPath];
    if (!soData) { fprintf(stderr, "xcc: error: cannot read '%s'\n", soPath.UTF8String); return 1; }
    // An optional committed classes.dex rides at the archive ROOT (uxkit/031).
    // The manifest's hasCode follows its presence: with hasCode="false" ART
    // skips classes.dex entirely, which is indistinguishable from a dex that
    // failed to load and cost the android-bridge spike its first launch.
    NSData *dexData = nil;
    if (opts.withDex) {
        dexData = [NSData dataWithContentsOfFile:opts.withDex];
        if (!dexData) {
            fprintf(stderr, "xcc: error: cannot read --with-dex '%s'\n",
                    opts.withDex.UTF8String);
            return 1;
        }
    }
    // uxkit/032: an extra prebuilt .so beside the payload, and which of the two
    // the system loads. The Android UI driver packages an NDK-built shim whose
    // onCreate runs FIRST — it stashes the activity and VM, loads the bridge
    // dex, then dlopens the payload and delegates — so `android.app.lib_name`
    // has to name the shim, not the payload it defaults to.
    NSData *extraLib = nil;
    NSString *extraLibEntry = nil;
    if (opts.withLib) {
        extraLib = [NSData dataWithContentsOfFile:opts.withLib];
        if (!extraLib) {
            fprintf(stderr, "xcc: error: cannot read --with-lib '%s'\n",
                    opts.withLib.UTF8String);
            return 1;
        }
        NSString *bn = opts.withLib.lastPathComponent;
        // Android loads by soname from lib/<abi>/, so the stored name has to be
        // the library's own `lib<X>.so` — not a renamed copy of it.
        if (![bn hasPrefix:@"lib"] || ![bn hasSuffix:@".so"]) {
            fprintf(stderr, "xcc: error: --with-lib '%s' must be named lib<name>.so "
                            "— Android resolves it from lib/arm64-v8a/ by that name\n",
                    bn.UTF8String);
            return 1;
        }
        extraLibEntry = [NSString stringWithFormat:@"lib/arm64-v8a/%@", bn];
    }
    NSString *manifestLib = opts.libName.length ? opts.libName : name;
    NSData *axml = [XTApkWriter binaryManifestForPackage:pkg libName:manifestLib
                                                   label:base minSdk:24 targetSdk:35
                                                 hasCode:(dexData != nil)];
    // The native library is aligned to 4 KB so the loader can map it straight
    // out of the package; the manifest is read, not mapped, so it needs none.
    NSMutableArray<NSDictionary *> *entries = [@[
        @{@"name": @"AndroidManifest.xml", @"data": axml},
        @{@"name": [NSString stringWithFormat:@"lib/arm64-v8a/lib%@.so", name],
          @"data": soData},
    ] mutableCopy];
    if (extraLib) [entries addObject:@{@"name": extraLibEntry, @"data": extraLib}];
    if (dexData) [entries addObject:@{@"name": @"classes.dex", @"data": dexData}];
    NSData *apkUnsigned = [XTApkWriter zipWithEntries:entries
                                            alignment:4096 alignSuffix:@".so"];
    NSString *unaligned = [tmp stringByAppendingPathComponent:@"xtc-unsigned.apk"];
    [fm removeItemAtPath:unaligned error:NULL];
    if (![apkUnsigned writeToFile:unaligned atomically:YES]) {
        fprintf(stderr, "xcc: error: cannot write the package\n"); return 1;
    }
    [fm removeItemAtPath:outPath error:NULL];
    if (![apkUnsigned writeToFile:outPath atomically:YES]) {
        fprintf(stderr, "xcc: error: cannot write '%s'\n", outPath.UTF8String); return 1;
    }
    NSString *manifest = unaligned;   // nothing else to clean up
    // ── the signature ─────────────────────────────────────────────────────
    // APK Signature Scheme v2, in-house. v1 (JAR signing) would not do: Android
    // 11 and later reject a package whose targetSdk is 30+ when it carries only
    // a v1 signature, and this one targets 35.
    NSDictionary *key = androidDebugKey();
    if (!key) return 1;
    NSError *sErr = nil;
    NSData *signed_ = [XTApkSign signedApkFromUnsigned:apkUnsigned
                                               certDer:key[@"cert"]
                                               modulus:key[@"n"]
                                        publicExponent:key[@"e"]
                                       privateExponent:key[@"d"]
                                                 error:&sErr];
    if (!signed_) {
        fprintf(stderr, "xcc: error: signing failed: %s\n",
                sErr.localizedDescription.UTF8String);
        return 1;
    }
    if (![signed_ writeToFile:outPath atomically:YES]) {
        fprintf(stderr, "xcc: error: cannot write '%s'\n", outPath.UTF8String);
        return 1;
    }

    if (!opts.verbose) {
        for (NSString *p in @[elfPath ?: @"", stubPath ?: @"",
                              exportsPath ?: @"", manifest, unaligned])
            if (p.length) [fm removeItemAtPath:p error:NULL];
        [fm removeItemAtPath:stage error:NULL];
    }
    if (!opts.quiet)
        fprintf(stderr, "xcc: android APK -> '%s'  (adb install -r %s; "
                        "adb shell am start -n %s/android.app.NativeActivity; "
                        "adb logcat -s xcapp)\n",
                outPath.UTF8String, outPath.UTF8String, pkg.UTF8String);
    return 0;
}

static int linkArm64Executable(const char *argv0, XTCommandLineOptions *opts,
                               NSString *asmPath, NSString *outPath,
                               NSArray<NSString *> *neededLibs) {
    if (opts.androidTarget)
        return opts.emitApk ? linkAndroidApk(argv0, opts, asmPath, outPath)
                            : linkAndroidExecutable(argv0, opts, asmPath, outPath);
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    if (!support) {
        fprintf(stderr, "xcc: error: cannot locate support/ (set XTC_HOME) — "
                "needed for the arm64 host runtime\n");
        return 1;
    }

    // ── --self-host: assemble + link + sign entirely in-house (no clang) ──
    // Handles xtc `#import <Lib>` dylibs natively (passed to xtcln-arm64, which
    // inspects each for its exports and binds against it) AND user `-l<name>`
    // libraries that resolve to a real `lib<name>.dylib` on disk — xtcln-arm64's
    // Mach-O reader parses any arm64 dylib's install name + exports, so it can bind
    // against a third-party dylib exactly as it does an xtc one. What it can't
    // resolve in-house forces the clang fallback: a `-framework`/`-Xlinker`/`-Wl,`
    // directive, or an `-l<name>` that exists only as a `.tbd`/shared-cache/static
    // library (no real .dylib file — e.g. a system framework). This keeps
    // --self-host a strict improvement: anything it can't handle degrades to
    // exactly the clang path, never worse (a failed in-house link retries too).
    NSMutableArray<NSString *> *userDylibs = [NSMutableArray array];
    NSMutableArray<NSString *> *linkerRaw = [NSMutableArray array];   // forwarded ld directives
    BOOL sysLibs = NO;
    resolveUserLinkInputs(opts, fm, userDylibs, linkerRaw, &sysLibs);
    // ── -c: compile to a relocatable object and stop ──────────────────────
    // The object carries the MODULE and nothing else: its own code plus its
    // per-class allocators. Deliberately NOT crt/rt — the runtime belongs to
    // the final link, and baking it into every object would collide the moment
    // two of them met. Unresolved references stay unresolved, as relocations.
    // Stage 1 of private:docs/Design/separate-compilation.md.
    if (opts.compileOnly) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm64");
        if (!ln) {
            fprintf(stderr, "xcc: error: -c needs xcc-ln-arm64 (not found)\n");
            return 1;
        }
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *combined = [NSString stringWithFormat:@"%@\n%@",
                              arm64ClassAllocStubs(prog), prog ?: @""];
        NSString *objAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-c-object.s"];
        [combined writeToFile:objAsm atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        NSMutableArray<NSString *> *objArgs = [@[@"--object", objAsm, opts.outputPath] mutableCopy];
        if (opts.applePlatform)
            [objArgs addObjectsFromArray:@[@"-platform", opts.applePlatform]];
        int rc = runChild(ln, objArgs);
        if (rc == 0 && !opts.quiet)
            fprintf(stderr, "xcc: arm64 object -> '%s'\n", opts.outputPath.UTF8String);
        return rc;
    }

    if (useSelfHost(opts) && !sysLibs) {
        NSString *ln  = resolveSiblingTool(argv0, @"xcc-ln-arm64");
        NSString *crt = [support stringByAppendingPathComponent:@"arm64/runtime/crt-macos.s"];
        NSString *rt  = [support stringByAppendingPathComponent:@"arm64/runtime/rt-macos.s"];
        if (!ln || ![fm fileExistsAtPath:crt] || ![fm fileExistsAtPath:rt]) {
            fprintf(stderr, "xcc: error: self-host tools missing (xtcln-arm64=%s, crt=%s, rt=%s)\n",
                    ln ? ln.UTF8String : "(missing)", crt.UTF8String, rt.UTF8String);
            return 1;
        }
        NSString *prog   = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
        NSString *crtsrc = [NSString stringWithContentsOfFile:crt     encoding:NSUTF8StringEncoding error:NULL];
        NSString *rtsrc  = [NSString stringWithContentsOfFile:rt      encoding:NSUTF8StringEncoding error:NULL];
        // The iOS platform shim (support/ios/runtime, iOS.md stage 4) rides
        // after the runtime, in the simulator or device flavour.
        if (opts.applePlatform) {
            NSString *ios = [support stringByAppendingPathComponent:
                             [opts.applePlatform isEqualToString:@"ios-sim"]
                                 ? @"ios/runtime/xtios-sim.s" : @"ios/runtime/xtios.s"];
            NSString *iossrc = [NSString stringWithContentsOfFile:ios encoding:NSUTF8StringEncoding error:NULL];
            if (!iossrc.length) {
                fprintf(stderr, "xcc: error: the iOS runtime shim %s is missing\n", ios.UTF8String);
                return 1;
            }
            rtsrc = [NSString stringWithFormat:@"%@\n%@", rtsrc, iossrc];
        }
        // A CHECKED build links the reporter too. Its own translation unit,
        // built with different flags (frame pointers, -O0), and linked ONLY
        // here — an ordinary build carries none of it.
        NSString *chksrc = @"";
        if (opts.boundsCheck) {
            NSString *chk = [support stringByAppendingPathComponent:
                             @"arm64/runtime/rt-checked-macos.s"];
            chksrc = [NSString stringWithContentsOfFile:chk
                                               encoding:NSUTF8StringEncoding error:NULL] ?: @"";
            if (!chksrc.length) {
                fprintf(stderr, "xcc: error: -fbounds-check needs %s, which is missing\n",
                        chk.UTF8String);
                return 1;
            }
        }
        // Per-class allocators (`new Class` → __xtc_new_<Class>); see helper.
        NSString *combined = [NSString stringWithFormat:@"%@\n%@\n%@\n%@\n%@",
            crtsrc, rtsrc, chksrc, arm64ClassAllocStubs(prog), prog ?: @""];
        NSString *combinedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-selfhost.s"];
        [combined writeToFile:combinedPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        NSMutableArray<NSString *> *args = [@[combinedPath, outPath] mutableCopy];
        if (opts.applePlatform)
            [args addObjectsFromArray:@[@"-platform", opts.applePlatform]];
        [args addObjectsFromArray:neededLibs];               // #import <Lib> dylib paths
        [args addObjectsFromArray:userDylibs];               // resolved -l<name> dylib paths
        [args addObjectsFromArray:linkerRaw];                // forwarded ld directives (-rpath, …)
        int rc = runChild(ln, args);
        if (!opts.verbose) [fm removeItemAtPath:combinedPath error:NULL];
        if (rc == 0) {
            if (!opts.quiet)
                fprintf(stderr, "xcc: arm64 executable (self-hosted, no clang) -> '%s'\n", outPath.UTF8String);
            return signIfRequested(opts, argv0, outPath);
        }
        if (!clangFallbackAllowed()) return clangFallbackRefused("arm64 in-house link");
        warnToolchainFallback(opts, "this arm64 executable",
                              "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
    } else if (useSelfHost(opts) && sysLibs) {
        warnToolchainFallback(opts, "this arm64 executable",
                              "it links system libraries the in-house linker cannot yet resolve");
    }

    NSString *libxt = [support stringByAppendingPathComponent:@"arm64/runtime/libxt.c"];
    if (![fm fileExistsAtPath:libxt]) {
        fprintf(stderr, "xcc: error: arm64 runtime not found at '%s'\n", libxt.UTF8String);
        return 1;
    }
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                  encoding:NSUTF8StringEncoding error:NULL];
    NSString *renamed = asmText ? renameMainSymbol(asmText) : nil;
    if (renamed)
        [renamed writeToFile:asmPath atomically:YES
                    encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-stub.c"];
    [arm64StubSource(renamed) writeToFile:stubPath atomically:YES
                                 encoding:NSUTF8StringEncoding error:NULL];
    NSMutableArray<NSString *> *a = [@[@"clang", @"-arch", @"arm64", @"-O2"] mutableCopy];
    [a addObjectsFromArray:@[asmPath, stubPath, libxt]];
    // Link against every `#import <Lib>` dylib the front end recorded. Each is
    // an absolute path to a lib<name>.dylib; clang takes the path verbatim, and
    // an `@loader_path` rpath lets the produced binary find the dylib beside it
    // (or in the same lib dir) at run time without DYLD_LIBRARY_PATH.
    NSMutableSet<NSString *> *rpaths = [NSMutableSet set];
    for (NSString *lib in neededLibs) {
        [a addObject:lib];
        NSString *dir = [lib stringByDeletingLastPathComponent];
        if (dir.length) [rpaths addObject:dir];
    }
    for (NSString *dir in rpaths)
        [a addObjectsFromArray:@[@"-Wl,-rpath", [@"-Wl," stringByAppendingString:dir]]];
    // System-library / framework passthrough (#6): -l<name>, -framework <F>,
    // -Xlinker <arg>, -Wl,... forwarded to clang, plus $XTC_LDFLAGS. macOS keeps
    // libobjc / the frameworks in the dyld shared cache (no DWARF .dylib to
    // #import), so this is how an ObjC/AppKit program links against them.
    [a addObjectsFromArray:appendLinkerFlags(opts, NO)];   // -L/-l/-framework/-Xlinker/$XTC_LDFLAGS
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: arm64 executable -> '%s'\n", outPath.UTF8String);
    if (rc == 0) return signIfRequested(opts, argv0, outPath);
    return rc;
}

// Build an arm64 macOS `.dylib` from `--emit-lib` output — the native-host
// analogue of linkArm9Shared. The library's public functions were kept and
// `.globl`-exported by xtcg-arm64 --emit-lib; here we assemble them, link a
// main-less runtime stub (so `new`/ARC in the library still resolve), and
// embed the module interface as a Mach-O `__XTC,__iface` section that an app's
// `#import <Lib>` reads back to type-check against the real binary.
//
// Objects cross the boundary safely: every image's `_xtc_alloc`/`_xtc_new_*`
// bottoms out in libc `malloc`, so the heap is shared, and a destructor is
// dispatched through the absolute function pointer stamped into the object
// header at allocation time (valid across images under ASLR).
// Synthesise the per-class `new` allocators for the self-host path. `new Class`
// lowers to `__xtc_new_<Class>`, which is program-specific (it installs the
// class's dealloc) — rt-macos.s ships only the primitive allocators. Each stub
// is a 3-insn tail-call: `x2 = &<Class>$dealloc; b __xtc_alloc` (x2=0 when the
// class has no dealloc). Shared by the executable and shared-library paths.
static NSString *arm64ClassAllocStubs(NSString *prog) {
    NSMutableString *out = [NSMutableString string];
    if (!prog) return out;
    NSRegularExpression *re = [NSRegularExpression
        regularExpressionWithPattern:@"__xtc_new_([A-Za-z_][A-Za-z0-9_]*)" options:0 error:NULL];
    NSMutableSet *seen = [NSMutableSet set];
    for (NSTextCheckingResult *m in [re matchesInString:prog options:0 range:NSMakeRange(0,prog.length)]) {
        NSString *cls = [prog substringWithRange:[m rangeAtIndex:1]];
        if (XTIRIsPrimitiveElemName(cls) || [seen containsObject:cls]) continue;
        [seen addObject:cls];
        BOOL hasDe = [prog containsString:[NSString stringWithFormat:@"_%@$dealloc:", cls]];
        [out appendFormat:@".text\n.globl __xtc_new_%@\n.align 2\n__xtc_new_%@:\n", cls, cls];
        if (hasDe) [out appendFormat:
            @"    adrp x2, _%@$dealloc@PAGE\n    add x2, x2, _%@$dealloc@PAGEOFF\n    b __xtc_alloc\n", cls, cls];
        else [out appendString:@"    mov x2, #0\n    b __xtc_alloc\n"];
    }
    return out;
}

// The x86-64 counterpart of arm64ClassAllocStubs: `new Class` lowers to a call
// to `_xtc_new_<Class>`, which is per-program (it has to know that class's
// destructor), so it cannot live in the shipped runtime. A tail jump to
// _xtc_alloc keeps the first two arguments untouched; only the third — the
// destructor — has to be placed, and that is the one register the two ABIs
// disagree on: rdx under System V, r8 under Microsoft x64.
static NSString *x86_64ClassAllocStubs(NSString *prog, BOOL win64) {
    NSMutableString *out = [NSMutableString string];
    if (!prog) return out;
    NSRegularExpression *re = [NSRegularExpression
        regularExpressionWithPattern:@"_xtc_new_([A-Za-z_][A-Za-z0-9_]*)" options:0 error:NULL];
    NSMutableSet *seen = [NSMutableSet set];
    for (NSTextCheckingResult *m in [re matchesInString:prog options:0 range:NSMakeRange(0,prog.length)]) {
        NSString *cls = [prog substringWithRange:[m rangeAtIndex:1]];
        if (XTIRIsPrimitiveElemName(cls) || [seen containsObject:cls]) continue;
        [seen addObject:cls];
        BOOL hasDe = [prog containsString:[NSString stringWithFormat:@"%@$dealloc:", cls]];
        [out appendFormat:@"\t.intel_syntax noprefix\n\t.text\n\t.globl\t_xtc_new_%@\n"
                          @"_xtc_new_%@:\n", cls, cls];
        NSString *argReg = win64 ? @"r8" : @"rdx";
        if (hasDe) [out appendFormat:@"\tlea\t%@, [rip+%@$dealloc]\n", argReg, cls];
        else       [out appendFormat:@"\txor\t%@, %@\n",
                                     win64 ? @"r8d" : @"edx", win64 ? @"r8d" : @"edx"];
        [out appendString:@"\tjmp\t_xtc_alloc\n"];
    }
    return out;
}

static int linkArm64Shared(const char *argv0, XTCommandLineOptions *opts,
                           NSString *asmPath, NSString *outPath,
                           NSString *_Nullable ifaceJson,
                           NSArray<NSString *> *neededLibs) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                  encoding:NSUTF8StringEncoding error:NULL];

    // ── --self-host: assemble + link + sign the dylib in-house (no clang) ──
    if (useSelfHost(opts)) {
        NSString *support = resolveSupportRoot(argv0, opts);
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm64");
        NSString *rt = [support stringByAppendingPathComponent:@"arm64/runtime/rt-macos.s"];
        if (support && ln && [fm fileExistsAtPath:rt]) {
            // Public API = the library's own .globl'd symbols (the runtime's
            // .globls live in rt-macos.s, which we scan separately, so they stay
            // private). Gather them from the library asm before prepending rt.
            NSMutableSet<NSString *> *exports = [NSMutableSet set];
            NSRegularExpression *ge = [NSRegularExpression
                regularExpressionWithPattern:@"(?m)^\\s*\\.globl\\s+(\\S+)" options:0 error:NULL];
            for (NSTextCheckingResult *m in [ge matchesInString:asmText options:0 range:NSMakeRange(0,asmText.length)])
                [exports addObject:[asmText substringWithRange:[m rangeAtIndex:1]]];

            NSString *rtsrc = [NSString stringWithContentsOfFile:rt encoding:NSUTF8StringEncoding error:NULL];
            NSString *combined = [NSString stringWithFormat:@"%@\n%@\n%@",
                rtsrc, arm64ClassAllocStubs(asmText), asmText];
            NSString *combinedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-selfhost-lib.s"];
            [combined writeToFile:combinedPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

            NSString *ifacePath = @"-";
            if (ifaceJson.length) {
                ifacePath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-selfhost-iface.json"];
                [ifaceJson writeToFile:ifacePath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
            }
            NSString *exportsPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-selfhost-exports.txt"];
            [[[exports allObjects] componentsJoinedByString:@"\n"]
                writeToFile:exportsPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

            NSString *instName = [@"@rpath/" stringByAppendingString:outPath.lastPathComponent];
            // The user's own link inputs, resolved the same way the executable
            // path resolves them. A library that WRAPS external C — a shim
            // object plus a static archive — is self-contained only if those
            // land in the .dylib; they were being resolved by nobody here, so
            // `-Wl,shim.o -Wl,libmbedtls.a` built a library of exactly the same
            // size as passing nothing, which then aborted at load on the first
            // wrapped symbol. Only OBJECTS and ARCHIVES are bundled: a .dylib
            // on the line is a dependency, not content.
            NSMutableArray<NSString *> *libDylibs = [NSMutableArray array];
            NSMutableArray<NSString *> *libRaw = [NSMutableArray array];
            BOOL libSysLibs = NO;
            resolveUserLinkInputs(opts, fm, libDylibs, libRaw, &libSysLibs);
            NSMutableArray<NSString *> *dylibArgs =
                [@[@"--dylib", instName, ifacePath, exportsPath, combinedPath, outPath] mutableCopy];
            // The libraries this one `#import`s (bug 440): the linker records
            // each as an LC_LOAD_DYLIB, so a client that imports only this
            // library still loads them.
            for (NSString *p in neededLibs)
                if ([p.pathExtension isEqualToString:@"dylib"]) [dylibArgs addObject:p];
            for (NSString *p in libDylibs)
                if ([p.pathExtension isEqualToString:@"a"]) [dylibArgs addObject:p];
            for (NSString *p in libRaw) {
                NSString *e = p.pathExtension;
                if ([e isEqualToString:@"o"] || [e isEqualToString:@"a"]) [dylibArgs addObject:p];
            }
            // Something the in-house path cannot resolve is a REFUSAL, not a
            // quiet omission — the whole failure being fixed here was content
            // that went missing without a word.
            if (libSysLibs) {
                if (!opts.quiet)
                    fprintf(stderr, "xcc: note: --emit-lib uses clang — a link input could "
                                    "not be resolved in-house\n");
            } else {
                int rc = runChild(ln, dylibArgs);
                if (!opts.verbose) {
                    [fm removeItemAtPath:combinedPath error:NULL];
                    [fm removeItemAtPath:exportsPath error:NULL];
                }
                if (rc == 0 && !opts.quiet)
                    fprintf(stderr, "xcc: arm64 shared library (self-hosted, no clang) -> '%s'\n",
                            outPath.UTF8String);
                if (rc == 0) return 0;
                if (!clangFallbackAllowed())
                    return clangFallbackRefused("arm64 in-house --emit-lib link");
            }
        }
        if (!opts.quiet)
            fprintf(stderr, "xcc: note: --self-host shared-lib tools missing, using clang\n");
    }

    // The library's own ARC/heap/print runtime — same synthesised stub the
    // executable links, minus the `main`/`xt_main` wrapper (a dylib has no
    // entry point).
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lib-stub.c"];
    [arm64StubSourceEx(asmText, YES) writeToFile:stubPath atomically:YES
                                        encoding:NSUTF8StringEncoding error:NULL];

    // Embed the interface JSON as a Mach-O section the importer reads back.
    // Section names are `SEGMENT,SECTION`, each ≤ 16 chars: `__XTC,__iface`.
    NSString *ifaceAsmPath = nil;
    if (ifaceJson.length) {
        NSString *jsonPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-iface-lib.json"];
        [ifaceJson writeToFile:jsonPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        ifaceAsmPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-iface-lib.s"];
        NSString *ifaceAsm = [NSString stringWithFormat:
            @"\t.section __XTC,__iface\n"
            @"\t.incbin \"%@\"\n\t.byte 0\n", jsonPath];
        [ifaceAsm writeToFile:ifaceAsmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    }

    NSMutableArray<NSString *> *a =
        [@[@"clang", @"-arch", @"arm64", @"-O2", @"-dynamiclib"] mutableCopy];
    // -install_name @rpath/<lib>: the app records this as the load path, so it
    // finds the dylib next to itself (an app links with -rpath @loader_path).
    [a addObjectsFromArray:@[@"-install_name",
        [@"@rpath/" stringByAppendingString:outPath.lastPathComponent]]];
    [a addObjectsFromArray:@[asmPath, stubPath]];
    if (ifaceAsmPath) [a addObject:ifaceAsmPath];
    [a addObjectsFromArray:appendLinkerFlags(opts, NO)];   // -L/-l/-framework/-Xlinker/$XTC_LDFLAGS
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: arm64 shared library -> '%s'\n", outPath.UTF8String);
    (void)argv0;
    return rc;
}

// Assemble + link an x86-64 `.s` into a static Linux ELF via the musl cross-clang.
// Two steps on purpose: `clang -c` assembles (the toolchain's .cfg auto-injects a
// bogus `-lc++` only at LINK), then `ld.lld` links directly against musl crt+libc,
// The glibc x86-64 cross toolchain ($XTC_X86_64_GUI_TOOLCHAIN, default
// /opt/clang/linux-gui). Unlike the static-musl one it produces DYNAMICALLY
// linked ELF — the only x86-64 path that can emit or consume a `.so`. Returns
// the clang driver path and fills *sysrootOut; nil (with a diagnostic) if absent.
static NSString *_Nullable x86_64GuiClang(NSString *_Nonnull *_Nullable sysrootOut) {
    const char *env = getenv("XTC_X86_64_GUI_TOOLCHAIN");
    NSString *tc = env ? @(env) : @"/opt/clang/linux-gui";
    NSString *cc = [tc stringByAppendingPathComponent:@"bin/x86_64-linux-gnu-clang"];
    if (![[NSFileManager defaultManager] fileExistsAtPath:cc]) {
        fprintf(stderr, "xcc: error: x86-64 glibc toolchain not found at '%s' "
                "(set XTC_X86_64_GUI_TOOLCHAIN) — needed for shared libraries\n", tc.UTF8String);
        return nil;
    }
    if (sysrootOut) *sysrootOut = [tc stringByAppendingPathComponent:@"x86_64-linux-gnu"];
    return cc;
}

// Emit a dynamically linked x86-64 client with the glibc toolchain. Used when the
// program `#import <Lib>`s a `.so` — a static-musl executable cannot load a glibc
// shared object, so the whole link moves to glibc. crt/libc come from the clang
// driver; the stub defines the ARC/heap runtime; each needed .so is linked with an
// $ORIGIN rpath so it resolves beside the binary at run time.
static int linkX86_64Dynamic(const char *argv0, XTCommandLineOptions *opts, NSString *asmPath,
                             NSString *outPath, NSArray<NSString *> *neededLibs) {
    NSFileManager *fm = [NSFileManager defaultManager];

    // ── --self-host: a PIE that DT_NEEDEDs the libraries, linked in-house ──
    // Same writer path as an .so, plus an entry point and PT_INTERP. DT_RUNPATH
    // $ORIGIN so the library is found beside the binary without LD_LIBRARY_PATH.
    if (selfHostByDefault(opts) && !x86SelfHostCanIgnoreLinkFlags(opts)) {
        warnToolchainFallback(opts, "this x86-64 executable",
                              "the in-house linker cannot satisfy -l/-L or raw linker flags");
    } else if (selfHostByDefault(opts)) {
        NSString *support = resolveSupportRoot(argv0, opts);
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-x86_64");
        NSMutableArray<NSString *> *rtPaths = [NSMutableArray array];
        BOOL haveRt = (support != nil && ln != nil);
        for (NSString *n in @[@"crt-linux.s", @"sys-linux.s",
                              @"rtgen-linux.s", @"rtfiles-linux.s", @"libmgen-linux.s"]) {
            NSString *pth = [support stringByAppendingPathComponent:
                             [@"x86_64/runtime/" stringByAppendingString:n]];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [rtPaths addObject:pth];
        }
        if (haveRt) {
            NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                       encoding:NSUTF8StringEncoding error:NULL];
            NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-dyn-newstubs.s"];
            [x86_64ClassAllocStubs(prog, NO) writeToFile:stubPath atomically:YES
                                            encoding:NSUTF8StringEncoding error:NULL];
            NSMutableArray<NSString *> *args = [rtPaths mutableCopy];
            [args addObject:stubPath];
            [args addObject:asmPath];
            // The exit stub only when there is no musl pool: libc.a's exit(3)
            // runs the atexit handlers and flushes stdio, and a second `exit`
            // would keep it from being pulled. The shipped driver never adds it.
            if (!x86MuslLibc(support))
                { NSString *es = x86ExitStub(support); if (es) [args addObject:es]; }
            if (!x86AddMimalloc(argv0, opts, args)) return 1;
            // The shared deps go on the line as INPUTS (not -l names): the
            // in-house linker reads each .so's soname (→ DT_NEEDED) and its
            // libc/crt imports, which it then satisfies from libc.a below and
            // exports, so the .so binds to THIS exe's one initialised musl.
            NSMutableSet<NSString *> *depDirs = [NSMutableSet set];
            for (NSString *lib in neededLibs) {
                [args addObject:lib];
                NSString *dir = [lib stringByDeletingLastPathComponent];
                if (dir.length) [depDirs addObject:dir];
            }
            // The exe is the single libc provider (musl is static — no libc.so):
            // it pulls libc.a for its own AND its shared deps' needs, plus the
            // libgcc builtins pool the wrapped C may reach for.
            { NSString *libc = x86MuslLibc(support); if (libc) [args addObject:libc]; }
            { NSString *gcc = x86MuslLibgcc(support); if (gcc) [args addObject:gcc]; }
            [args addObjectsFromArray:@[@"-pie", @"-e", @"_start",
                                        @"-rpath", @"$ORIGIN", @"-o", outPath]];
            for (NSString *dir in depDirs) { [args addObject:@"-rpath"]; [args addObject:dir]; }
            int rc = runChild(ln, args);
            if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
            if (rc == 0) {
                if (!opts.quiet)
                    fprintf(stderr, "xcc: x86-64 dynamic ELF (self-hosted, no clang) -> '%s'\n",
                            outPath.UTF8String);
                return 0;
            }
            if (!clangFallbackAllowed())
                return clangFallbackRefused("x86-64 in-house dynamic link");
            warnToolchainFallback(opts, "this x86-64 dynamic executable",
                                  "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
        }
    }

    NSString *sysroot = nil;
    NSString *cc = x86_64GuiClang(&sysroot);
    if (!cc) return 1;
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-dyn-stub.c"];
    [x86_64StubSource(asmText, resolveSupportRoot(argv0, opts)) writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    NSMutableArray<NSString *> *a = [@[cc, @"--no-default-config",
        @"--target=x86_64-linux-gnu", [@"--sysroot=" stringByAppendingString:sysroot],
        @"-O2", @"-fPIC", asmPath, stubPath] mutableCopy];
    NSMutableSet<NSString *> *rpaths = [NSMutableSet set];
    for (NSString *lib in neededLibs) {
        [a addObject:lib];
        NSString *dir = [lib stringByDeletingLastPathComponent];
        if (dir.length) [rpaths addObject:dir];
    }
    [a addObject:@"-Wl,-rpath,$ORIGIN"];               // find the .so beside the binary
    for (NSString *dir in rpaths)
        [a addObject:[@"-Wl,-rpath," stringByAppendingString:dir]];
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: x86-64 dynamic ELF -> '%s'\n", outPath.UTF8String);
    return rc;
}

// Build an x86-64 glibc `.so` from `--emit-lib` output — the Linux analogue of
// linkArm64Shared/linkArm9Shared. Public functions were kept + `.globl`-exported
// by xtcg-x86_64 --emit-lib; the RIP-relative codegen is already position-
// independent, so `-shared -fPIC` needs no text relocations. The serialised
// interface rides along as a `.xtc.iface` ELF section for `#import <Lib>`.
static int linkX86_64Shared(const char *argv0, XTCommandLineOptions *opts, NSString *asmPath,
                            NSString *outPath, NSString *_Nullable ifaceJson) {
    NSFileManager *fm = [NSFileManager defaultManager];

    // ── --self-host: write the ET_DYN in-house (no clang, no ld.lld, no glibc) ──
    // The runtime goes in whole: a library has no dead-symbol elimination here,
    // and an .so that imports its allocator from the host would defeat the point.
    // crt-linux.s is excluded — a shared object has no process entry.
    if (selfHostByDefault(opts) && !x86SelfHostCanIgnoreLinkFlags(opts)) {
        warnToolchainFallback(opts, "this x86-64 shared library",
                              "the in-house linker cannot satisfy -l/-L or raw linker flags");
    } else if (selfHostByDefault(opts)) {
        NSString *support = resolveSupportRoot(argv0, opts);
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-x86_64");
        NSMutableArray<NSString *> *rtPaths = [NSMutableArray array];
        BOOL haveRt = (support != nil && ln != nil);
        for (NSString *n in @[@"sys-linux.s", @"rtgen-linux.s", @"rtfiles-linux.s", @"libmgen-linux.s"]) {
            NSString *pth = [support stringByAppendingPathComponent:
                             [@"x86_64/runtime/" stringByAppendingString:n]];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [rtPaths addObject:pth];
        }
        if (!haveRt) {
            fprintf(stderr, "xcc: error: x86-64 self-host tools missing "
                    "(xtcln-x86_64=%s, runtime under %s)\n",
                    ln ? ln.UTF8String : "(missing)",
                    support ? support.UTF8String : "(no support root)");
            return 1;
        }
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-so-newstubs.s"];
        [x86_64ClassAllocStubs(prog, NO) writeToFile:stubPath atomically:YES
                                        encoding:NSUTF8StringEncoding error:NULL];
        // The serialised interface rides in a `.xtc.iface` section — without it a
        // consumer's `#import <Lib>` sees no classes and fails with an undefined
        // identifier far from the real cause.
        NSString *ifacePath = @"-";
        if (ifaceJson.length) {
            ifacePath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-so-iface.json"];
            [ifaceJson writeToFile:ifacePath atomically:YES
                          encoding:NSUTF8StringEncoding error:NULL];
        }
        NSMutableArray<NSString *> *args = [rtPaths mutableCopy];
        [args addObject:stubPath];
        [args addObject:asmPath];
        // The user's own objects and archives, so a library that WRAPS external
        // C is self-contained — the x86-64 half of #1191/#1192. xcc-ln-x86_64
        // merges objects and pulls archive members already (#1170); the .so path
        // simply never handed them over.
        {
            NSMutableArray<NSString *> *uLibs = [NSMutableArray array];
            NSMutableArray<NSString *> *uRaw  = [NSMutableArray array];
            BOOL uSys = NO;
            resolveUserLinkInputs(opts, fm, uLibs, uRaw, &uSys);
            for (NSString *p in uLibs)
                if ([p.pathExtension isEqualToString:@"a"]) [args addObject:p];
            for (NSString *p in uRaw) {
                NSString *e = p.pathExtension;
                if ([e isEqualToString:@"o"] || [e isEqualToString:@"a"]) [args addObject:p];
            }
        }
        // We deliberately do NOT bundle musl's libc.a into the .so. A wrapped C
        // library (Mbed TLS + the socket shim) calls calloc, printf,
        // clock_gettime … but musl is a STATIC libc: bundling it would give the
        // .so its own second, uninitialised copy of musl's per-process state
        // (__libc, the TLS header, the vdso clock cache) and the first libc call
        // from the loaded .so would fault in __vdsosym. Instead libc stays an
        // IMPORT, resolved at load against the EXECUTABLE's one crt-initialised
        // musl — the consuming exe pulls the .so's libc/crt needs from libc.a and
        // exports them (see linkX86_64Dynamic + xtcln-x86_64's shared-dep
        // handling). That is how this .so RUNS a verified TLS handshake in-house.
        {   // builtins pool for the wrapped C's 128-bit division etc. (#16)
            NSString *gccA = x86MuslLibgcc(support);
            if (gccA) [args addObject:gccA];
        }
        [args addObjectsFromArray:@[@"-shared", @"-soname", outPath.lastPathComponent,
                                    @"-iface", ifacePath, @"-o", outPath]];
        int rc = runChild(ln, args);
        if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
        if (rc == 0) {
            if (!opts.quiet)
                fprintf(stderr, "xcc: x86-64 shared library (self-hosted, no clang) -> '%s'\n",
                        outPath.UTF8String);
            return 0;
        }
        if (!clangFallbackAllowed())
            return clangFallbackRefused("x86-64 in-house shared link");
        warnToolchainFallback(opts, "this x86-64 shared library",
                              "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
    }

    NSString *sysroot = nil;
    NSString *cc = x86_64GuiClang(&sysroot);
    if (!cc) return 1;
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-so-stub.c"];
    [x86_64StubSource(asmText, resolveSupportRoot(argv0, opts)) writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    // Embed the interface JSON as a `.xtc.iface` section (a tiny .s with .incbin).
    NSString *ifaceAsmPath = nil;
    if (ifaceJson.length) {
        NSString *jsonPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-iface.json"];
        [ifaceJson writeToFile:jsonPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        ifaceAsmPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-iface.s"];
        NSString *ifaceAsm = [NSString stringWithFormat:
            @"\t.section .xtc.iface,\"\",%%progbits\n\t.incbin \"%@\"\n\t.byte 0\n", jsonPath];
        [ifaceAsm writeToFile:ifaceAsmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    }

    // -Bsymbolic binds the library's own defined globals locally (its refs stay
    // relative, not preemptible), matching the arm9 .so convention.
    NSMutableArray<NSString *> *a = [@[cc, @"--no-default-config",
        @"--target=x86_64-linux-gnu", [@"--sysroot=" stringByAppendingString:sysroot],
        @"-O2", @"-fPIC", @"-shared", @"-Wl,-Bsymbolic",
        [@"-Wl,-soname," stringByAppendingString:outPath.lastPathComponent],
        asmPath, stubPath] mutableCopy];
    if (ifaceAsmPath) [a addObject:ifaceAsmPath];
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) { [fm removeItemAtPath:stubPath error:NULL];
                         if (ifaceAsmPath) [fm removeItemAtPath:ifaceAsmPath error:NULL]; }
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: x86-64 shared library -> '%s'\n", outPath.UTF8String);
    return rc;
}

// avoiding that. Toolchain root from $XTC_X86_64_TOOLCHAIN (default /opt/clang/
// linux). Static musl → a self-contained ELF; run it on an x86-64 Linux host.
static int linkX86_64Executable(const char *argv0, XTCommandLineOptions *opts,
                                NSString *asmPath, NSString *outPath) {
    NSFileManager *fm = [NSFileManager defaultManager];

    // ── -c: compile to a relocatable ELF object and stop ──────────────────
    // The arm64 shape exactly (see linkArm64Executable): the object carries the
    // MODULE and nothing else — its own code plus its per-class allocators, and
    // deliberately no crt/runtime, which belongs to the final link and would
    // collide the moment two objects met. Unresolved references stay
    // unresolved, as relocations. Stage 1 of separate-compilation, x86_64.
    //
    // In-house regardless of `--self-host`, unlike the executable path below:
    // an object is not a link, so none of the reasons that path defers to
    // musl-clang (libc, -l flags, a loader) apply to it.
    if (opts.compileOnly) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-x86_64");
        if (!ln) {
            fprintf(stderr, "xcc: error: -c needs xcc-ln-x86_64 (not found)\n");
            return 1;
        }
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *combined = [NSString stringWithFormat:@"%@\n%@",
                              x86_64ClassAllocStubs(prog, NO), prog ?: @""];
        NSString *objAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-c-object-x86.s"];
        [combined writeToFile:objAsm atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        int rc = runChild(ln, @[@"--object", objAsm, outPath]);
        if (rc == 0 && !opts.quiet)
            fprintf(stderr, "xcc: x86-64 object -> '%s'\n", outPath.UTF8String);
        return rc;
    }

    // ── --self-host: assemble + link entirely in-house (no clang, no ld.lld, no
    // musl). The output talks to the kernel through raw syscalls; the runtime is
    // support/x86_64/runtime/. Unlike arm64 this is NOT host-gated — it writes
    // ELF, which is what `-A x86_64` means on any host — but it is opt-in until
    // it has as much mileage as the arm64 path.
    NSMutableArray<NSString *> *userArchives = [NSMutableArray array];
    const char *x86tcEnv = getenv("XTC_X86_64_TOOLCHAIN");
    NSString *x86tc = x86tcEnv ? @(x86tcEnv) : @"/opt/clang/linux";
    NSArray<NSString *> *x86DefDirs =
        @[[x86tc stringByAppendingPathComponent:@"x86_64-linux-musl/lib"]];
    if (selfHostByDefault(opts) && !dashLResolveArchives(opts, fm, x86DefDirs, userArchives)) {
        warnToolchainFallback(opts, "this x86-64 static executable",
                              "a -l names no static archive on the -L paths or the musl "
                              "sysroot, or a raw linker flag is not ours to honour");
    } else if (selfHostByDefault(opts)) {
        NSString *support = resolveSupportRoot(argv0, opts);
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-x86_64");
        NSArray<NSString *> *rtNames = @[@"crt-linux.s", @"sys-linux.s",
                                         @"rtgen-linux.s", @"rtfiles-linux.s", @"libmgen-linux.s"];
        NSMutableArray<NSString *> *rtPaths = [NSMutableArray array];
        BOOL haveRt = (support != nil && ln != nil);
        for (NSString *n in rtNames) {
            NSString *pth = [support stringByAppendingPathComponent:
                             [@"x86_64/runtime/" stringByAppendingString:n]];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [rtPaths addObject:pth];
        }
        if (!haveRt) {
            fprintf(stderr, "xcc: error: x86-64 self-host tools missing "
                    "(xtcln-x86_64=%s, runtime under %s)\n",
                    ln ? ln.UTF8String : "(missing)",
                    support ? support.UTF8String : "(no support root)");
            return 1;
        }
        // Per-class allocators, as a sixth input rather than concatenated: the
        // linker namespaces each input's local labels, and a plain concatenation
        // of separately compiled files collides on clang's .LBB numbering.
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *stubs = x86_64ClassAllocStubs(prog, NO);
        NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-newstubs.s"];
        [stubs writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

        NSMutableArray<NSString *> *args = [rtPaths mutableCopy];
        [args addObject:stubPath];
        [args addObject:asmPath];
        if (!x86AddMimalloc(argv0, opts, args)) return 1;
        // The user's -l archives (finding #15), resolved above — so a program
        // may use Stdio.printf AND link -lmbedcrypto in one build. They come
        // before libc: the user's code references them, and whatever THEY need
        // from libc is still undefined when the pool is reached.
        [args addObjectsFromArray:userArchives];
        // The real libc goes LAST, so it is only ever a POOL for what is still
        // undefined: our freestanding runtime keeps its `_xt_*` contract and its
        // own definitions win, and musl supplies the rest — `dprintf`,
        // `getpid`, anything a program legitimately calls. The alternative is
        // reimplementing libc a function at a time, which is what the 6502-era
        // shims were for and is no longer the situation we are in.
        NSString *muslA = x86MuslLibc(support);
        if (!muslA) return x86MissingPool(support);
        [args addObject:muslA];
        NSString *gccA = x86MuslLibgcc(support);   // builtins pool (finding #16)
        if (gccA) [args addObject:gccA];
        [args addObjectsFromArray:@[@"-o", outPath]];
        int rc = runChild(ln, args);
        if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
        if (rc == 0) {
            if (!opts.quiet)
                fprintf(stderr, "xcc: x86-64 ELF (self-hosted, no clang) -> '%s'\n",
                        outPath.UTF8String);
            return 0;
        }
        if (!clangFallbackAllowed())
            return clangFallbackRefused("x86-64 in-house link");
        warnToolchainFallback(opts, "this x86-64 static executable",
                              "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
    }

    const char *tcEnv = getenv("XTC_X86_64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/linux";
    NSString *cc      = [tc stringByAppendingPathComponent:@"bin/x86_64-linux-musl-clang"];
    NSString *lld     = [tc stringByAppendingPathComponent:@"bin/ld.lld"];
    NSString *sysroot = [tc stringByAppendingPathComponent:@"x86_64-linux-musl"];
    NSString *lib     = [sysroot stringByAppendingPathComponent:@"lib"];
    if (![fm fileExistsAtPath:cc]) {
        fprintf(stderr, "xcc: error: x86-64 musl toolchain not found at '%s' "
                "(set XTC_X86_64_TOOLCHAIN)\n", tc.UTF8String);
        return 1;
    }
    NSString *objPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64.o"];
    NSString *stubSrcPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-stub.c"];
    NSString *stubObjPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-x86_64-stub.o"];

    // 1. assemble .s → .o
    int rc = runChild(@"/usr/bin/env", @[cc, @"--no-default-config",
        @"--target=x86_64-linux-musl",
        [@"--sysroot=" stringByAppendingString:sysroot], @"-c", asmPath, @"-o", objPath]);
    if (rc != 0) return rc;

    // 1b. synthesise the program-specific ARC/heap runtime (the _xtc_new_*/alloc/
    // dealloc/weak symbols the asm references) and compile it to a .o.
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    [x86_64StubSource(asmText, resolveSupportRoot(argv0, opts)) writeToFile:stubSrcPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    rc = runChild(@"/usr/bin/env", @[cc, @"--no-default-config", @"--target=x86_64-linux-musl",
        [@"--sysroot=" stringByAppendingString:sysroot], @"-O2", @"-c", stubSrcPath, @"-o", stubObjPath]);
    if (rc != 0) { if (!opts.verbose) [fm removeItemAtPath:objPath error:NULL]; return rc; }

    // 2. link static-musl with ld.lld (crt1/crti + program + stub + libc/libm + crtn)
    NSMutableArray<NSString *> *la = [@[lld, @"-static"] mutableCopy];
    for (NSString *o in @[@"crt1.o", @"crti.o"]) [la addObject:[lib stringByAppendingPathComponent:o]];
    // FIRST, ahead of the program and of libc: a static link resolves
    // left-to-right, and mimalloc only overrides what libc has not already
    // supplied.
    NSString *mi = mimallocObjectFor(@"x86_64", argv0, opts);
    if (mi) [la addObject:mi];
    [la addObject:objPath];
    [la addObject:stubObjPath];
    // User -L/-l BEFORE the system libs: with -static, ld resolves left-to-right,
    // so a user library referenced by the program must precede libc, and can in
    // turn pull symbols from libc/libm that follow it.
    [la addObjectsFromArray:appendLinkerFlags(opts, YES)];   // -L/-l (+ $XTC_LDFLAGS -L/-l)
    for (NSString *l in @[@"libc.a", @"libm.a"]) [la addObject:[lib stringByAppendingPathComponent:l]];
    [la addObject:[lib stringByAppendingPathComponent:@"crtn.o"]];
    [la addObjectsFromArray:@[@"-o", outPath]];
    rc = runChild(@"/usr/bin/env", la);

    if (!opts.verbose) { [fm removeItemAtPath:objPath error:NULL];
                         [fm removeItemAtPath:stubSrcPath error:NULL];
                         [fm removeItemAtPath:stubObjPath error:NULL]; }
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: x86-64 ELF -> '%s'\n", outPath.UTF8String);
    return rc;
}

// Link a Win64 program (from xtcg-win64 output) into a static PE (.exe) with the
// mingw-w64 cross-clang. Toolchain root from $XTC_WIN64_TOOLCHAIN (default
// /opt/clang/win64). The mingw clang drives the whole pipeline — assembles the
// .s, compiles the per-program ARC/heap runtime stub, and links its own crt +
// static libc — so a single invocation yields a self-contained .exe. Runs under
// The `lib<x>.a` basenames the self-hosted win64 linker can satisfy: one per DLL
// named in support/win64/win32-imports.map. Derived from the map so regenerating
// it automatically widens what self-host accepts.
static NSSet<NSString *> *win64SelfHostCoveredLibs(const char *argv0,
                                                   XTCommandLineOptions *opts) {
    NSMutableSet<NSString *> *out = [NSMutableSet set];
    NSString *support = resolveSupportRoot(argv0, opts);
    if (!support) return out;
    NSString *body = [NSString stringWithContentsOfFile:
        [support stringByAppendingPathComponent:@"win64/win32-imports.map"]
                                               encoding:NSUTF8StringEncoding error:NULL];
    if (!body) return out;
    for (NSString *ln in [body componentsSeparatedByString:@"\n"]) {
        if (ln.length == 0 || [ln hasPrefix:@"#"]) continue;
        NSRange tab = [ln rangeOfString:@"\t"];
        if (tab.location == NSNotFound) continue;
        NSString *dll = [[ln substringFromIndex:tab.location+1]
            stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceCharacterSet]];
        NSString *stem = [dll stringByDeletingPathExtension].lowercaseString;
        if (stem.length) [out addObject:[NSString stringWithFormat:@"lib%@.a", stem]];
    }
    return out;
}

// Wine on macOS/Linux or natively on Windows.
static int linkWin64Executable(const char *argv0, XTCommandLineOptions *opts,
                               NSString *asmPath, NSString *outPath,
                               NSArray<NSString *> *neededLibs) {
    NSFileManager *fm = [NSFileManager defaultManager];

    // ── -c: compile to a relocatable COFF object and stop ─────────────────
    // The arm64/x86_64 shape exactly: the object carries the MODULE and nothing
    // else — no crt, no runtime, and no import table, because an object
    // declares no imports. Unresolved references stay unresolved, as
    // relocations. In-house regardless of `--self-host`: an object is not a
    // link, so none of the reasons the executable path below defers to mingw
    // apply to it. Stage 1 of separate-compilation, win64.
    if (opts.compileOnly) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-win64");
        if (!ln) {
            fprintf(stderr, "xcc: error: -c needs xcc-ln-win64 (not found)\n");
            return 1;
        }
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *combined = [NSString stringWithFormat:@"%@\n%@",
                              x86_64ClassAllocStubs(prog, YES), prog ?: @""];
        NSString *objAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-c-object-win64.s"];
        [combined writeToFile:objAsm atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        int rc = runChild(ln, @[@"--object", objAsm, outPath]);
        if (rc == 0 && !opts.quiet)
            fprintf(stderr, "xcc: win64 object -> '%s'\n", outPath.UTF8String);
        return rc;
    }

    // ── --self-host: assemble + write the PE in-house (no mingw, no lld-link,
    // no Windows SDK). Windows has no stable syscall ABI, so unlike the Linux
    // path this still imports from kernel32.dll — but through an import table we
    // build ourselves, not a toolchain's.
    // Which system import libs can the in-house path satisfy? Exactly the DLLs
    // the generated symbol→DLL map covers — read that rather than keeping a
    // second hardcoded list, which drifts (it used to allow only kernel32/user32/
    // gdi32, so a program touching comctl32 was diverted to mingw even though the
    // in-house linker could have resolved it).
    NSSet<NSString *> *coveredLibs = win64SelfHostCoveredLibs(argv0, opts);
    BOOL onlySystemLibs = YES;
    for (NSString *lib in neededLibs) {
        if (![coveredLibs containsObject:lib.lastPathComponent.lowercaseString]) {
            onlySystemLibs = NO; break;
        }
    }
    // The user's -l archives, resolved to lib<name>.a on the -L paths or the
    // mingw sysroot (finding #15's win64 face: -l used to force the mingw
    // fallback, which links the C library but not the in-house runtime, so
    // Stdio.printf's _xt_fmt_f went undefined the moment any -l appeared).
    NSMutableArray<NSString *> *w64UserArchives = [NSMutableArray array];
    const char *w64tcEnv = getenv("XTC_WIN64_TOOLCHAIN");
    NSString *w64tc = w64tcEnv ? @(w64tcEnv) : @"/opt/clang/win64";
    NSArray<NSString *> *w64DefDirs =
        @[[w64tc stringByAppendingPathComponent:@"x86_64-w64-mingw32/lib"],
          [w64tc stringByAppendingPathComponent:@"x86_64-w64-mingw32/clang-rt"]];
    BOOL w64ArchivesOK = dashLResolveArchives(opts, fm, w64DefDirs, w64UserArchives);
    if (selfHostByDefault(opts) && onlySystemLibs && w64ArchivesOK) {
        NSString *support = resolveSupportRoot(argv0, opts);
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-win64");
        NSMutableArray<NSString *> *rtPaths = [NSMutableArray array];
        BOOL haveRt = (support != nil && ln != nil);
        for (NSString *n in @[@"crt-win64.s", @"rtgen-win64.s", @"rtfiles-win64.s", @"libmgen-win64.s"]) {
            NSString *pth = [support stringByAppendingPathComponent:
                             [@"win64/runtime/" stringByAppendingString:n]];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [rtPaths addObject:pth];
        }
        if (haveRt) {
            NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                       encoding:NSUTF8StringEncoding error:NULL];
            NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-win64-newstubs.s"];
            [x86_64ClassAllocStubs(prog, YES) writeToFile:stubPath atomically:YES
                                                 encoding:NSUTF8StringEncoding error:NULL];
            NSMutableArray<NSString *> *args = [rtPaths mutableCopy];
            [args addObject:stubPath];
            [args addObject:asmPath];
            // The user's -l archives before the libc pool (finding #15).
            [args addObjectsFromArray:w64UserArchives];
            // The real C runtime goes LAST, so it is only ever a POOL for what
            // is still undefined: our freestanding runtime's own definitions
            // win, and mingw supplies the rest — snprintf, and anything else a
            // program legitimately calls. Same arrangement as musl on x86-64.
            for (NSString *a in win64Libc(support) ?: @[]) [args addObject:a];
            // Everything the freestanding runtime reaches the OS through. Only
            // the ones actually referenced end up in the import table.
            [args addObjectsFromArray:@[@"-import",
                @"kernel32.dll:ExitProcess,GetStdHandle,WriteFile,VirtualAlloc,"
                @"GetSystemTimeAsFileTime,Sleep"]];
            // The generated symbol→DLL table, so a program can call ANY Win32
            // entry point (GetStockObject, CreateWindowExA, InitCommonControls …)
            // and not just the handful the freestanding runtime needs. Without it
            // the self-hosted path could only link runtime-only programs — masked
            // on a Mac by the fallback to mingw, fatal on a host without one.
            NSString *impMap = [support stringByAppendingPathComponent:@"win64/win32-imports.map"];
            if ([fm fileExistsAtPath:impMap])
                [args addObjectsFromArray:@[@"-importmap", impMap]];
            [args addObjectsFromArray:@[@"-e", @"_start", @"-o", outPath]];
            int rc = runChild(ln, args);
            if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
            if (rc == 0) {
                if (!opts.quiet)
                    fprintf(stderr, "xcc: win64 PE (self-hosted, no mingw) -> '%s'\n",
                            outPath.UTF8String);
                return 0;
            }
            // A FAILED in-house link is the case the other four back ends already
            // treat as fatal (arm64, and x86-64 static/dynamic/shared). win64 was
            // the one site that never joined them, and that omission is precisely
            // what let a dead linker look healthy — so it joins them now.
            if (!clangFallbackAllowed()) return clangFallbackRefused("win64 in-house link");
            warnToolchainFallback(opts, "this win64 PE",
                                  "the in-house link failed and XTC_ALLOW_CLANG_FALLBACK is set");
        } else {
            // A missing runtime .s or an unresolvable xcc-ln-win64 dropped
            // straight through to mingw without a word — the same silence, one
            // branch further out.
            warnToolchainFallback(opts, "this win64 PE",
                                  "--self-host was asked for, but the win64 runtime .s files or "
                                  "xcc-ln-win64 could not be found (check -H / the support tree)");
        }
    } else if (selfHostByDefault(opts)) {
        warnToolchainFallback(opts, "this win64 PE",
                              "--self-host was asked for, but the in-house linker cannot yet "
                              "satisfy DLL imports beyond kernel32, or -l/-L was used");
    } else {
        // The in-house path is not even ATTEMPTED without --self-host, unlike
        // macOS/arm64 where it is the default. That asymmetry is the reason a
        // dead win64 linker could sit unnoticed: the everyday command never ran
        // it. Say so on every build until the default flips.
        warnToolchainFallback(opts, "this win64 PE",
                              "-A win64 uses the mingw toolchain unless --self-host is given");
    }

    const char *tcEnv = getenv("XTC_WIN64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/win64";
    NSString *cc      = [tc stringByAppendingPathComponent:@"bin/x86_64-w64-mingw32-clang"];
    NSString *sysroot = [tc stringByAppendingPathComponent:@"x86_64-w64-mingw32"];
    if (![fm fileExistsAtPath:cc]) {
        fprintf(stderr, "xcc: error: win64 mingw toolchain not found at '%s' "
                "(set XTC_WIN64_TOOLCHAIN)\n", tc.UTF8String);
        return 1;
    }
    // The per-program ARC/heap runtime stub (_xtc_alloc/_xtc_dealloc/_xtc_new_*/
    // weak/time), same generator the Linux path uses — portable C, so the mingw
    // libc backs its malloc/free/snprintf.
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-win64-stub.c"];
    [x86_64StubSource(asmText, resolveSupportRoot(argv0, opts)) writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    NSMutableArray<NSString *> *a = [@[cc, @"--target=x86_64-w64-mingw32",
        [@"--sysroot=" stringByAppendingString:sysroot], @"-O2", @"-static",
        asmPath, stubPath] mutableCopy];
    // Link each `#import <Lib>` DLL the front end recorded via its import library:
    // the recorded path is `libFoo.dll`; the loader binds against `libFoo.dll.a`
    // beside it. The DLL itself must be on the client's search path at run time
    // (same directory, or PATH) — under Wine the current directory suffices.
    for (NSString *lib in neededLibs) {
        NSString *implib = [lib stringByAppendingPathExtension:@"a"];  // libFoo.dll → libFoo.dll.a
        [a addObject:[fm fileExistsAtPath:implib] ? implib : lib];
    }
    // User -L/-l/-Wl,/$XTC_LDFLAGS — the mingw clang is a compiler driver, so it
    // takes the same flag set as the macOS clang path.
    [a addObjectsFromArray:appendLinkerFlags(opts, NO)];
    [a addObjectsFromArray:@[@"-o", outPath]];
    if (getenv("XTC_WIN64_MAP"))
        [a addObject:[@"-Wl,-Map," stringByAppendingString:
              [outPath stringByAppendingPathExtension:@"map"]]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: win64 PE -> '%s'\n", outPath.UTF8String);
    return rc;
}

// Build a Win64 DLL from `--emit-lib` output — the Windows analogue of
// linkX86_64Shared/linkArm64Shared. The mingw clang links `-shared` and, with
// `--out-implib`, drops an import library (`<dll>.a`) beside the DLL so a client
// links by name and the loader binds the DLL at run time; `--export-all-symbols`
// exports every `.globl` the backend emitted for the public API. The serialised
// interface rides along as a `.xtc.iface` PE section for `#import <Lib>`.
static int linkWin64Shared(const char *argv0, XTCommandLineOptions *opts, NSString *asmPath,
                           NSString *outPath, NSString *_Nullable ifaceJson) {
    NSFileManager *fm = [NSFileManager defaultManager];
    const char *tcEnv = getenv("XTC_WIN64_TOOLCHAIN");
    NSString *tc = tcEnv ? @(tcEnv) : @"/opt/clang/win64";
    NSString *cc      = [tc stringByAppendingPathComponent:@"bin/x86_64-w64-mingw32-clang"];
    NSString *sysroot = [tc stringByAppendingPathComponent:@"x86_64-w64-mingw32"];
    if (![fm fileExistsAtPath:cc]) {
        fprintf(stderr, "xcc: error: win64 mingw toolchain not found at '%s' "
                "(set XTC_WIN64_TOOLCHAIN)\n", tc.UTF8String);
        return 1;
    }
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath encoding:NSUTF8StringEncoding error:NULL];
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-win64-dll-stub.c"];
    [x86_64StubSource(asmText, resolveSupportRoot(argv0, opts)) writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    // Embed the interface JSON as a `.xtc.iface` COFF/PE section (a tiny .s with
    // .incbin) so an app that `#import <Lib>`s this DLL reconstructs the public
    // declarations from the DLL itself.
    NSString *ifaceAsmPath = nil;
    if (ifaceJson.length) {
        NSString *jsonPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-win64-iface.json"];
        [ifaceJson writeToFile:jsonPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        ifaceAsmPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-win64-iface.s"];
        // COFF section names are capped at 8 chars (longer ones spill to the
        // string table), so use `xtciface` (exactly 8) rather than `.xtc.iface`.
        NSString *ifaceAsm = [NSString stringWithFormat:
            @"\t.section xtciface,\"dr\"\n\t.incbin \"%@\"\n\t.byte 0\n", jsonPath];
        [ifaceAsm writeToFile:ifaceAsmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    }

    // The import library sits beside the DLL as `<dll>.a` (mingw convention:
    // libFoo.dll → libFoo.dll.a). A client links it and the loader binds the DLL.
    NSString *implib = [outPath stringByAppendingPathExtension:@"a"];
    NSMutableArray<NSString *> *a = [@[cc, @"--target=x86_64-w64-mingw32",
        [@"--sysroot=" stringByAppendingString:sysroot], @"-O2", @"-shared",
        [@"-Wl,--out-implib," stringByAppendingString:implib],
        @"-Wl,--export-all-symbols", asmPath, stubPath] mutableCopy];
    if (ifaceAsmPath) [a addObject:ifaceAsmPath];
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) { [fm removeItemAtPath:stubPath error:NULL];
                         if (ifaceAsmPath) [fm removeItemAtPath:ifaceAsmPath error:NULL]; }
    if (rc == 0 && !opts.quiet)
        fprintf(stderr, "xcc: win64 DLL -> '%s' (import lib '%s')\n",
                outPath.UTF8String, implib.UTF8String);
    return rc;
}

// Read the Cortex-A9 ABI flags from support/arm9/bsp-flags.sh (which extracts
// -mcpu/-mfpu/-mfloat-abi from the Vitis BSP, with its own documented fallback).
// Captured + whitespace-split into argv tokens; falls back to the known defaults
// if the script is missing or fails.
static NSArray<NSString *> *arm9BspFlags(NSString *script) {
    NSArray<NSString *> *fallback =
        @[@"-mcpu=cortex-a9", @"-mfloat-abi=hard", @"-mfpu=vfpv3"];
    if (![[NSFileManager defaultManager] fileExistsAtPath:script]) return fallback;
    NSTask *t = [[NSTask alloc] init];
    t.launchPath = @"/bin/sh";
    t.arguments = @[script];
    NSPipe *pipe = [NSPipe pipe];
    t.standardOutput = pipe;
    if (!canLaunchTool(t.launchPath)) return fallback;
    [t launch];
    NSData *d = [[pipe fileHandleForReading] readDataToEndOfFile];
    [t waitUntilExit];
    if (t.terminationStatus != 0) return fallback;
    NSString *s = [[NSString alloc] initWithData:d encoding:NSUTF8StringEncoding];
    NSMutableArray<NSString *> *out = [NSMutableArray array];
    for (NSString *p in [s componentsSeparatedByCharactersInSet:
                         [NSCharacterSet whitespaceAndNewlineCharacterSet]])
        if (p.length) [out addObject:p];
    return out.count ? out : fallback;
}

// (The Tier-1 static bare-metal arm9 path — linkArm9Executable + crt0 + the
// newlib-static support/arm9/runtime/libxt.c — was removed: arm9 output is always

// a loader-hosted PIC .so now (linkArm9Shared, below). Its semihosting runtime
// is gone with it.)

// Print a one-line PIC-contract pre-flight from `readelf` (a shape check before
// the loader: ET_DYN/EM_ARM, the relocation types, undefined-symbol count). Best
// effort — never fails the build.
static void arm9PicPreflight(NSString *soPath) {
    NSTask *t = [[NSTask alloc] init];
    t.launchPath = @"/usr/bin/env";
    t.arguments = @[@"sh", @"-c",
        [NSString stringWithFormat:
         @"t=$(arm-none-eabi-readelf -h '%@' 2>/dev/null | awk -F: '/Type:/{print $2}' | xargs);"
         @"r=$(arm-none-eabi-readelf -r '%@' 2>/dev/null | grep -oE 'R_ARM_[A-Z_0-9]+' | sort | uniq -c | tr '\\n' ' ');"
         @"u=$(arm-none-eabi-readelf --dyn-syms '%@' 2>/dev/null | awk 'NR>3 && $7==\"UND\" && $8!=\"\"{print $8}' | tr '\\n' ' ');"
         // An EMPTY report is not a clean one. With readelf absent every field
         // comes back blank and the line reads like a passed check — which is
         // exactly what it looked like on a host with the GNU toolchain hidden,
         // the one case where the in-house path most needs verifying.
         @"if [ -z \"$t\" ]; then"
         @"  echo \"xcc: PIC pre-flight SKIPPED (no arm-none-eabi-readelf) — NOT CHECKED\" 1>&2;"
         @"else"
         @"  echo \"xcc: PIC pre-flight: type=$t  relocs=[$r] undefined=[$u]\" 1>&2;"
         @"fi",
         soPath, soPath, soPath]];
    // readelf absent — skip the probe rather than failing the build.
    if (canLaunchTool(t.launchPath)) { [t launch]; [t waitUntilExit]; }
}

// Assemble + link an arm9 `.s` into a SELF-CONTAINED position-independent ET_DYN
// (.so) for the Tier-2 xtos loader. PIC codegen (xtcg-arm9 --pic) emits
// `ldr =sym` address loads so references become R_ARM_RELATIVE; this links them
// with the minimal semihosting runtime (libxt-pic.c, newlib-free) under
// `-fPIC -shared -nostdlib -Bsymbolic` so the image has no undefined symbols and
// no crt0 (the loader resolves `main` from .dynsym and calls it). `-lgcc`
// supplies the integer divide helpers (__aeabi_uidiv…).
// Find a shared library file (e.g. "libc.so") across the user's -L dirs and the
// arm9 sysroot lib dir. Used to link the heap runtime against the device libc.
static NSString *resolveArm9SysrootLib(XTCommandLineOptions *opts, NSString *support,
                                       NSString *libName) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSMutableArray<NSString *> *dirs = [opts.libraryPaths mutableCopy] ?: [NSMutableArray array];
    if (support) [dirs addObject:[support stringByAppendingPathComponent:@"arm9/lib"]];
    for (NSString *d in dirs) {
        NSString *p = [d stringByAppendingPathComponent:libName];
        if ([fm fileExistsAtPath:p]) return p;
    }
    return nil;
}


// The per-program allocator trampolines for arm9, as ARM ASSEMBLY rather than
// C — the same split x86_64 has, where the fixed runtime is a checked-in `.s`
// and only these vary with the program. `new u8[N]` lowers to
// `_xtc_new_u8(count)`, which over-allocates eight bytes per element (always at
// least the A32 element size) and writes the same 24-byte header `_xtc_alloc`
// does; a CLASS goes through `_xtc_alloc` itself and needs nothing here.
static NSString *arm9ClassAllocStubs(NSString *prog) {
    NSMutableString *out = [NSMutableString string];
    if (!prog) return out;
    NSRegularExpression *re = [NSRegularExpression
        regularExpressionWithPattern:@"_xtc_new_([A-Za-z_][A-Za-z0-9_]*)" options:0 error:NULL];
    NSMutableSet *seen = [NSMutableSet set];
    for (NSTextCheckingResult *m in [re matchesInString:prog options:0
                                                  range:NSMakeRange(0, prog.length)]) {
        NSString *t = [prog substringWithRange:[m rangeAtIndex:1]];
        if ([seen containsObject:t]) continue;
        [seen addObject:t];
        // `_xtc_new_<T>(count)` — one argument, so the stride argument has to be
        // supplied here. Eight is the widest element the A32 target has.
        [out appendFormat:
            @"\t.text\n\t.globl\t_xtc_new_%@\n\t.type\t_xtc_new_%@, %%function\n"
            @"_xtc_new_%@:\n"
            @"\tmov\tr1, #8\n"
            @"\tmov\tr2, #0\n"
            @"\tb\t_xtc_alloc\n", t, t, t];
    }
    return out;
}

static int linkArm9Shared(const char *argv0, XTCommandLineOptions *opts,
                          NSString *asmPath, NSString *outPath,
                          NSArray<NSString *> *neededLibs,
                          NSString *_Nullable ifaceJson) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    if (!support) {
        fprintf(stderr, "xcc: error: cannot locate support/ (set XTC_HOME) — "
                "needed for the arm9 PIC runtime\n");
        return 1;
    }
    NSString *libxtPic = [support stringByAppendingPathComponent:@"arm9/runtime/libxt-pic.c"];
    if (![fm fileExistsAtPath:libxtPic]) {
        fprintf(stderr, "xcc: error: arm9 PIC runtime not found at '%s'\n", libxtPic.UTF8String);
        return 1;
    }

    // ── -c: assemble to a relocatable object and stop ─────────────────────
    // IN-HOUSE, like the other three, through xcc-ln-arm9 — XAArm32Assembler
    // plus XTElf32Writer. It used to shell out to `arm-none-eabi-gcc -c`, which
    // is fine on a development Mac and useless everywhere else: the Cortex-A9
    // has no gcc and neither does a Windows host, and a compiler that needs
    // someone else's toolchain to produce an object is not portable, merely
    // hosted. A win64 box can now emit arm9 objects.
    //
    // Deliberately NO runtime stub in the object. On the other three targets our
    // own linkers take first-wins on a duplicate, so each object can carry its
    // own copy of the generated ARC/heap helpers; GNU ld (which still performs
    // the final LINK) does not, and two objects each defining `_xtc_alloc`
    // would be a hard error. The stub is therefore generated ONCE at the final
    // link, from the objects' own symbol table.
    //
    // `main` still gives up its name here, not at the link: the C stub owns
    // `main` and calls `xt_main`, and the rename has to happen in the module
    // that defines it — which is this one, and is not visible later.
    if (opts.compileOnly) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm9");
        if (!ln) {
            fprintf(stderr, "xcc: error: -c needs xcc-ln-arm9 (not found)\n");
            return 1;
        }
        NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                      encoding:NSUTF8StringEncoding error:NULL];
        if (asmText) {
            asmText = renameArm9MainSymbol(asmText);
            [asmText writeToFile:asmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        }
        int crc = runChild(ln, @[@"--object", asmPath, outPath]);
        if (crc == 0 && !opts.quiet)
            fprintf(stderr, "xcc: arm9 object -> '%s'\n", outPath.UTF8String);
        return crc;
    }

    // The tier-2 ARC/heap runtime (_xtc_alloc/_xtc_dealloc/_xtc_new_<T>), the
    // same per-program stub the executable path compiles. Linking it into the
    // .so DEFINES those symbols (so the program's refs resolve locally under
    // -Bsymbolic) — its malloc/free stay undefined and resolve dynamically
    // against libc.so (DT_NEEDED), which is the whole point of B2: the heap
    // runtime calls the device libc instead of carrying its own allocator.
    NSString *asmText = [NSString stringWithContentsOfFile:asmPath
                                                  encoding:NSUTF8StringEncoding error:NULL];
    // The xtc entry gives up the name `main` to the C stub (see above), unless
    // this is a library, which has no entry to give up.
    if (asmText && !opts.emitLib) {
        asmText = renameArm9MainSymbol(asmText);
        [asmText writeToFile:asmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    }
    NSString *stubSrc = arm9StubSource(asmText, opts.emitLib);
    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-arm9-pic-stub.c"];
    [stubSrc writeToFile:stubPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];

    // --emit-lib: embed the serialised module interface as a `.xtc.iface` ELF
    // section (a separate .s with .incbin, assembled into the .so). An app that
    // `#import <Lib>`s this .so reads the section back to reconstruct the public
    // declarations without source (B1).
    NSString *ifaceAsmPath = nil;
    if (ifaceJson.length) {
        NSString *jsonPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-iface.json"];
        [ifaceJson writeToFile:jsonPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        ifaceAsmPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-iface.s"];
        NSString *ifaceAsm = [NSString stringWithFormat:
            @"\t.section .xtc.iface,\"\",%%progbits\n"
            @"\t.incbin \"%@\"\n\t.byte 0\n", jsonPath];
        [ifaceAsm writeToFile:ifaceAsmPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
    }

    NSArray<NSString *> *bsp =
        arm9BspFlags([support stringByAppendingPathComponent:@"arm9/bsp-flags.sh"]);
    NSMutableArray<NSString *> *a = [@[@"arm-none-eabi-gcc"] mutableCopy];
    [a addObjectsFromArray:bsp];
    [a addObject:@"-mfloat-abi=softfp"];
    // -Bsymbolic: bind defined globals locally so their refs stay R_ARM_RELATIVE
    // (not preemptible ABS32/GLOB_DAT); -nostdlib: no crt / static libc (the
    // loader calls main); -lgcc: integer-divide helpers.
    // ── --self-host: assemble + link the ET_DYN entirely in-house ─────────
    // No arm-none-eabi-gcc, no ld, no libgcc: XAArm32Assembler encodes,
    // XTElf32Writer lays the image out and writes the dynamic sections the XTOS
    // loader reads. Opt-in while it earns its mileage, exactly as the x86-64
    // and win64 in-house paths were before they did.
    if (selfHostByDefault(opts)) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm9");
        NSString *rtDir = [support stringByAppendingPathComponent:@"arm9/runtime"];
        NSArray<NSString *> *rt = @[@"rtgen-arm9.s", @"libxtgen-arm9.s", @"aeabi64.s"];
        NSMutableArray<NSString *> *args = [NSMutableArray array];
        BOOL haveRt = (ln != nil);
        for (NSString *n in rt) {
            NSString *pth = [rtDir stringByAppendingPathComponent:n];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [args addObject:pth];
        }
        if (!haveRt) {
            fprintf(stderr, "xcc: error: arm9 self-host tools missing "
                    "(xcc-ln-arm9=%s, runtime under %s)\n",
                    ln ? ln.UTF8String : "(missing)", rtDir.UTF8String);
            return 1;
        }
        NSString *prog = [NSString stringWithContentsOfFile:asmPath
                                                   encoding:NSUTF8StringEncoding error:NULL];
        NSString *stubP = [xtcTempDir() stringByAppendingPathComponent:@"xtc-arm9-stubs.s"];
        [arm9ClassAllocStubs(prog) writeToFile:stubP atomically:YES
                                      encoding:NSUTF8StringEncoding error:NULL];
        [args addObject:stubP];
        [args addObject:asmPath];
        // The user's own objects and archives (`-Wl,shim.o -Wl,libfoo.a`), so a
        // library that WRAPS external C is self-contained. xcc-ln-arm9 merges
        // objects and pulls archive members on demand (#1189, #1190); before
        // this the driver never handed them over, so the shim stayed undefined
        // and the .so failed at LOAD on the first wrapped call — the arm9 half
        // of #1191. Only objects and archives: a `.so` is a DT_NEEDED
        // dependency, recorded below, not content to bundle.
        {
            NSMutableArray<NSString *> *uLibs = [NSMutableArray array];
            NSMutableArray<NSString *> *uRaw  = [NSMutableArray array];
            BOOL uSys = NO;
            resolveUserLinkInputs(opts, fm, uLibs, uRaw, &uSys);
            for (NSString *p in uLibs)
                if ([p.pathExtension isEqualToString:@"a"]) [args addObject:p];
            for (NSString *p in uRaw) {
                NSString *e = p.pathExtension;
                if ([e isEqualToString:@"o"] || [e isEqualToString:@"a"]) [args addObject:p];
            }
        }
        // DT_NEEDED. The loader resolves an import by NAME across the
        // libraries it has mapped, so every library that might satisfy one has
        // to be listed — `pow` lives in libm.so, and recording only libc.so is
        // how `auto_cloak` linked cleanly and then failed to LOAD.
        //
        // gcc's path trims this with --as-needed, which inspects each library's
        // symbol table. Not done here: on this device both are always present,
        // and a DT_NEEDED for a library the program does not touch costs a
        // mapping rather than a correctness problem. The `#import <lib>`
        // dependencies are listed too, by name for the same reason.
        NSMutableArray<NSString *> *head =
            [@[@"--shared", @"-o", outPath] mutableCopy];
        // The serialised interface, so `#import <Lib>` can read this library's
        // public declarations back. The .incbin `.s` built above is for the gcc
        // path; the in-house writer takes the JSON directly and gives it a
        // `.xtc.iface` section header.
        if (ifaceJson.length) {
            NSString *ij = [xtcTempDir() stringByAppendingPathComponent:@"xtc-arm9-iface.json"];
            [ifaceJson writeToFile:ij atomically:YES encoding:NSUTF8StringEncoding error:NULL];
            [head addObjectsFromArray:@[@"-iface", ij]];
        }
        for (NSString *lib in neededLibs)
            [head addObjectsFromArray:@[@"-needed", lib.lastPathComponent]];
        for (NSString *libName in @[@"libc.so", @"libm.so"]) {
            if (resolveArm9SysrootLib(opts, support, libName))
                [head addObjectsFromArray:@[@"-needed", libName]];
        }
        if (opts.emitLib) [head addObjectsFromArray:@[@"-soname", outPath.lastPathComponent]];
        [head addObjectsFromArray:args];
        int rc = runChild(ln, head);
        if (!opts.verbose) [fm removeItemAtPath:stubP error:NULL];
        if (rc == 0 && !opts.quiet) {
            fprintf(stderr, "xcc: arm9 PIC ELF (self-hosted, no gcc) -> '%s'\n",
                    outPath.UTF8String);
            arm9PicPreflight(outPath);
        }
        return rc;
    }

    // The 64-bit helpers are OURS (support/arm9/runtime/aeabi64.s), listed ahead
    // of -lgcc so ld takes them: the device libc.so exports the 32-bit divide
    // helpers but none of the 64-bit ones, and `-lgcc` was the last reason an
    // arm9 link needed a GNU toolchain at all.
    NSString *aeabi64 = [support stringByAppendingPathComponent:@"arm9/runtime/aeabi64.s"];
    [a addObjectsFromArray:@[@"-fPIC", @"-shared", @"-nostdlib", @"-Wl,-Bsymbolic",
                             asmPath, libxtPic, stubPath]];
    if ([fm fileExistsAtPath:aeabi64]) [a addObject:aeabi64];
    [a addObject:@"-lgcc"];
    if (ifaceAsmPath) [a addObject:ifaceAsmPath];   // the .xtc.iface section
    // Library build (--emit-lib): record a DT_SONAME so an app that links this
    // .so records `DT_NEEDED <soname>` (by name, not the build path).
    if (opts.emitLib) {
        [a addObject:[NSString stringWithFormat:@"-Wl,-soname,%@",
                      outPath.lastPathComponent]];
    }

    // The program's explicit `#import <lib>` dependencies (from the front-end
    // sidecar) are linked --no-as-needed: they were requested and their symbols
    // are referenced, so each records a DT_NEEDED from its DT_SONAME.
    NSMutableSet<NSString *> *seenBase = [NSMutableSet set];
    if (neededLibs.count > 0) {
        [a addObject:@"-Wl,--no-as-needed"];
        for (NSString *lib in neededLibs) {
            [a addObject:lib];
            [seenBase addObject:lib.lastPathComponent];
        }
    }
    // The device runtime libs the xtc runtime calls into: libc.so (snprintf for
    // %f, rand, malloc/free, memcpy/memset) and libm.so (sqrt/sin/…). Linked
    // --as-needed so a NEEDED entry is recorded only for the libs a given
    // program actually pulls a symbol from — an integer program that never
    // formats a float or allocates stays free of both. Resolved across -L dirs
    // and the arm9 sysroot lib dir.
    NSMutableArray<NSString *> *asNeeded = [NSMutableArray array];
    for (NSString *libName in @[@"libc.so", @"libm.so"]) {
        if ([seenBase containsObject:libName]) continue;       // already via #import
        NSString *p = resolveArm9SysrootLib(opts, support, libName);
        if (p) [asNeeded addObject:p];
    }
    if (asNeeded.count > 0) {
        [a addObject:@"-Wl,--as-needed"];
        [a addObjectsFromArray:asNeeded];
    }
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet) {
        fprintf(stderr, "xcc: arm9 PIC ELF (ET_DYN) -> '%s'\n", outPath.UTF8String);
        arm9PicPreflight(outPath);
    }
    return rc;
}

/****************************************************************************\
|* arm9, stage 2: link separately-compiled objects into the loader-hosted
|* ET_DYN. Same command as linkArm9Shared builds, with the objects in place of
|* the single `.s` — and the ARC/heap stub generated from `symText`, a rendering
|* of the objects' symbol table (see the caller) rather than of asm text,
|* because at this point the asm no longer exists.
|*
|* Kept as its own function rather than another flag on linkArm9Shared: that one
|* also renames `main`, embeds a `.xtc.iface` and records a DT_SONAME, none of
|* which applies here, and threading three `if (objects)` tests through it would
|* make both paths harder to read than either is alone.
\****************************************************************************/
static int linkArm9Objects(const char *argv0, XTCommandLineOptions *opts,
                           NSArray<NSString *> *objects, NSString *symText,
                           NSString *outPath, NSArray<NSString *> *neededLibs) {
    NSFileManager *fm = [NSFileManager defaultManager];
    NSString *support = resolveSupportRoot(argv0, opts);
    NSString *libxtPic = support
        ? [support stringByAppendingPathComponent:@"arm9/runtime/libxt-pic.c"] : nil;
    if (!support || ![fm fileExistsAtPath:libxtPic]) {
        fprintf(stderr, "xcc: error: arm9 PIC runtime not found (set XTC_HOME)\n");
        return 1;
    }
    // ── in-house: the same ET_DYN, with no arm-none-eabi-gcc ──────────────
    // The LAST path in the compiler that shelled out to a GNU tool. xcc-ln-arm9
    // merges the objects into the assembled runtime and hands the whole thing to
    // sharedObjectFromText: — the same writer call an all-source link makes.
    //
    // The ARC/heap helpers come from the prebuilt runtime `.s`, not from
    // arm9StubSource's generated C: there is no C compiler in this path, and the
    // runtime already carries them.
    if (selfHostByDefault(opts)) {
        NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-arm9");
        NSString *rtDir = [support stringByAppendingPathComponent:@"arm9/runtime"];
        NSMutableArray<NSString *> *args = [NSMutableArray array];
        BOOL haveRt = (ln != nil);
        for (NSString *n in @[@"rtgen-arm9.s", @"libxtgen-arm9.s", @"aeabi64.s"]) {
            NSString *pth = [rtDir stringByAppendingPathComponent:n];
            if (![fm fileExistsAtPath:pth]) { haveRt = NO; break; }
            [args addObject:pth];
        }
        if (haveRt) {
            NSMutableArray<NSString *> *head = [@[@"--shared", @"-o", outPath] mutableCopy];
            for (NSString *lib in neededLibs)
                [head addObjectsFromArray:@[@"-needed", lib.lastPathComponent]];
            for (NSString *libName in @[@"libc.so", @"libm.so"]) {
                if (resolveArm9SysrootLib(opts, support, libName))
                    [head addObjectsFromArray:@[@"-needed", libName]];
            }
            [head addObjectsFromArray:args];
            [head addObjectsFromArray:objects];
            int rc = runChild(ln, head);
            if (rc == 0) {
                if (!opts.quiet) {
                    fprintf(stderr, "xcc: arm9 PIC ELF (from %lu object%s, no gcc) -> '%s'\n",
                            (unsigned long)objects.count, objects.count == 1 ? "" : "s",
                            outPath.UTF8String);
                    arm9PicPreflight(outPath);
                }
                return 0;
            }
            if (!clangFallbackAllowed())
                return clangFallbackRefused("arm9 in-house object link");
            warnToolchainFallback(opts, "this arm9 image",
                                  "the in-house object link failed and "
                                  "XTC_ALLOW_CLANG_FALLBACK is set");
        }
    }

    NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-arm9-obj-stub.c"];
    [arm9StubSource(symText, NO) writeToFile:stubPath atomically:YES
                                    encoding:NSUTF8StringEncoding error:NULL];

    NSMutableArray<NSString *> *a = [@[@"arm-none-eabi-gcc"] mutableCopy];
    [a addObjectsFromArray:arm9BspFlags([support stringByAppendingPathComponent:
                                         @"arm9/bsp-flags.sh"])];
    [a addObject:@"-mfloat-abi=softfp"];
    [a addObjectsFromArray:@[@"-fPIC", @"-shared", @"-nostdlib", @"-Wl,-Bsymbolic"]];
    // FIRST DEFINITION WINS, as the other three object links already do — but
    // GNU ld has to be told, because unlike our own linkers its default is a
    // hard error. The reason is the same one written down for x86_64: `-c`
    // compiles each module's imports INTO it, so two objects that both
    // `#import "Stdio.xc"` each define every `Stdio$*`, and the injected
    // `_xtc_obj_conforms` is in every object by construction. A duplicate here
    // is the same body twice.
    //
    // What this DOES give up is ld's own duplicate diagnostic, so the one
    // duplicate that is never benign — `<Class>$cat`, two modules extending one
    // class (§4.2) — is checked by the caller against the same `nm` output it
    // builds the stub from, before we get here.
    [a addObject:@"-Wl,--allow-multiple-definition"];
    [a addObjectsFromArray:objects];
    [a addObjectsFromArray:@[libxtPic, stubPath, @"-lgcc"]];

    NSMutableSet<NSString *> *seenBase = [NSMutableSet set];
    if (neededLibs.count > 0) {
        [a addObject:@"-Wl,--no-as-needed"];
        for (NSString *lib in neededLibs) {
            [a addObject:lib];
            [seenBase addObject:lib.lastPathComponent];
        }
    }
    NSMutableArray<NSString *> *asNeeded = [NSMutableArray array];
    for (NSString *libName in @[@"libc.so", @"libm.so"]) {
        if ([seenBase containsObject:libName]) continue;
        NSString *p = resolveArm9SysrootLib(opts, support, libName);
        if (p) [asNeeded addObject:p];
    }
    if (asNeeded.count > 0) {
        [a addObject:@"-Wl,--as-needed"];
        [a addObjectsFromArray:asNeeded];
    }
    [a addObjectsFromArray:@[@"-o", outPath]];
    int rc = runChild(@"/usr/bin/env", a);
    if (!opts.verbose) [fm removeItemAtPath:stubPath error:NULL];
    if (rc == 0 && !opts.quiet) {
        fprintf(stderr, "xcc: arm9 PIC ELF (from %lu object%s) -> '%s'\n",
                (unsigned long)objects.count, objects.count == 1 ? "" : "s",
                outPath.UTF8String);
        arm9PicPreflight(outPath);
    }
    return rc;
}

// Dispatch the IR path through xtc-fe + xtcg-<arch> subprocesses. The
// separation keeps each binary slim — Stage 8c trims their link lines.
// Returns the exit status. Cleans up the intermediate .ir tempfile.
/****************************************************************************\
|* wasm32: assemble the codegen's WAT text into <out>.wasm and write the
|* JS loader beside it, via xcc-ln-wasm32 (in-house — no wat2wasm, per the
|* native-toolchain rule: an in-house failure is a HARD error, never a
|* silent fallback). `-o prog` produces prog.wasm + prog.js; `node prog.js`
|* runs it, and the same prog.js loads in a browser unchanged.
\****************************************************************************/
static int linkWasm32Module(const char *argv0, XTCommandLineOptions *opts,
                            NSString *watPath, NSString *outPath,
                            NSArray<NSString *> *neededLibs,
                            NSString * _Nullable ifaceJson) {
    NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-wasm32");
    if (!ln) {
        fprintf(stderr, "xcc: error: xcc-ln-wasm32 not found beside xcc\n");
        return 1;
    }
    NSMutableArray<NSString *> *args =
        [NSMutableArray arrayWithObjects:watPath, outPath, nil];
    if (opts.quiet) [args addObject:@"-q"];
    NSString *ifaceTmp = nil;
    if (opts.emitLib) {
        // Library build (W2): the interface JSON is embedded in the .wasm as
        // a custom section (the ELF `.xtc.iface` analogue) by the ln tool.
        [args addObject:@"--emit-lib"];
        if (ifaceJson.length) {
            ifaceTmp = [NSTemporaryDirectory() stringByAppendingPathComponent:
                [NSString stringWithFormat:@"xtc-iface-%d.json", getpid()]];
            [ifaceJson writeToFile:ifaceTmp atomically:YES
                          encoding:NSUTF8StringEncoding error:NULL];
            [args addObjectsFromArray:@[@"--iface", ifaceTmp]];
        }
    }
    // The imported library names, bare. An app bakes them into its loader,
    // which fetches lib<X>.wasm + lib<X>.json beside the app and wires them.
    // A library writes them into its .json, so the loader also loads the
    // libraries it imports and sets them up before it.
    for (NSString *lib in neededLibs) {
        NSString *fn = lib.lastPathComponent;
        if (![fn hasPrefix:@"lib"] || ![fn.pathExtension isEqualToString:@"wasm"])
            continue;
        [args addObjectsFromArray:@[@"--dep",
            [[fn substringFromIndex:3] stringByDeletingPathExtension]]];
    }
    int rc = runChild(ln, args);
    if (ifaceTmp)
        [[NSFileManager defaultManager] removeItemAtPath:ifaceTmp error:NULL];
    if (rc == 0 && !opts.quiet) {
        if (opts.emitLib)
            fprintf(stderr, "xcc: wasm32 library -> '%s.wasm' + '%s.json'\n",
                    outPath.UTF8String, outPath.UTF8String);
        else
            fprintf(stderr, "xcc: wasm32 module -> '%s.wasm' + '%s.js' "
                            "(run: node %s.js)\n",
                    outPath.UTF8String, outPath.UTF8String, outPath.UTF8String);
    }
    return rc;
}

// Merge several IR modules into one, for a link-time recompile (stage 5 of
// private:docs/Design/separate-compilation.md). The IR text is name-based at module
// scope — symbols and functions are named, types spelled inline — so the merge
// is mostly concatenation. TWO things are INDEXED and must be renumbered, and
// getting either wrong corrupts struct offsets silently rather than loudly:
//
//   layout N: …   referenced as Agg(N)
//   constant N: … referenced as #cpool:N
//
// so each module after the first has its indices shifted past the running
// totals, in the declarations AND in every reference. Duplicate symbols and
// functions (the shared runtime helpers every module carries a copy of) keep
// the FIRST definition, which is what a linker does with them anyway.
static NSString *mergeIRTexts(NSArray<NSString *> *texts) {
    NSMutableArray<NSString *> *layouts = [NSMutableArray array];
    NSMutableArray<NSString *> *constants = [NSMutableArray array];
    NSMutableArray<NSString *> *symbols = [NSMutableArray array];
    NSMutableArray<NSString *> *functions = [NSMutableArray array];
    NSMutableSet<NSString *> *seenSym = [NSMutableSet set];
    NSMutableSet<NSString *> *seenFn = [NSMutableSet set];

    NSRegularExpression *aggRe = [NSRegularExpression
        regularExpressionWithPattern:@"Agg\\((\\d+)\\)" options:0 error:NULL];
    NSRegularExpression *cpRe = [NSRegularExpression
        regularExpressionWithPattern:@"#cpool:(\\d+)" options:0 error:NULL];
    NSString *(^shift)(NSString *, NSUInteger, NSUInteger) =
        ^NSString *(NSString *text, NSUInteger dLayout, NSUInteger dConst) {
        if (!dLayout && !dConst) return text;
        NSMutableString *out = [text mutableCopy];
        // Right-to-left so an earlier replacement cannot disturb a later range.
        if (dLayout) {
            NSArray *ms = [aggRe matchesInString:out options:0 range:NSMakeRange(0, out.length)];
            for (NSTextCheckingResult *m in ms.reverseObjectEnumerator) {
                NSUInteger n = [[out substringWithRange:[m rangeAtIndex:1]] integerValue];
                [out replaceCharactersInRange:m.range
                                   withString:[NSString stringWithFormat:@"Agg(%lu)",
                                               (unsigned long)(n + dLayout)]];
            }
        }
        if (dConst) {
            NSArray *ms = [cpRe matchesInString:out options:0 range:NSMakeRange(0, out.length)];
            for (NSTextCheckingResult *m in ms.reverseObjectEnumerator) {
                NSUInteger n = [[out substringWithRange:[m rangeAtIndex:1]] integerValue];
                [out replaceCharactersInRange:m.range
                                   withString:[NSString stringWithFormat:@"#cpool:%lu",
                                               (unsigned long)(n + dConst)]];
            }
        }
        return out;
    };

    for (NSString *raw in texts) {
        NSUInteger dLayout = layouts.count, dConst = constants.count;
        NSString *text = shift(raw, dLayout, dConst);
        NSArray<NSString *> *lines = [text componentsSeparatedByString:@"\n"];
        for (NSUInteger i = 0; i < lines.count; i++) {
            NSString *l = lines[i];
            NSString *t = [l stringByTrimmingCharactersInSet:
                              [NSCharacterSet whitespaceCharacterSet]];
            if ([t hasPrefix:@"module "] || [t isEqualToString:@"}"] || !t.length) continue;
            if ([t hasPrefix:@"layout "]) {
                NSRange c = [t rangeOfString:@":"];
                if (c.location == NSNotFound) continue;
                [layouts addObject:[NSString stringWithFormat:@"  layout %lu%@",
                                    (unsigned long)layouts.count,
                                    [t substringFromIndex:c.location]]];
                continue;
            }
            if ([t hasPrefix:@"constant "]) {
                NSRange c = [t rangeOfString:@":"];
                if (c.location == NSNotFound) continue;
                [constants addObject:[NSString stringWithFormat:@"  constant %lu%@",
                                      (unsigned long)constants.count,
                                      [t substringFromIndex:c.location]]];
                continue;
            }
            if ([t hasPrefix:@"symbol "]) {
                NSRange sp = [t rangeOfString:@":"];
                NSString *nm = sp.location == NSNotFound ? t
                    : [[t substringWithRange:NSMakeRange(7, sp.location - 7)]
                          stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceCharacterSet]];
                BOOL dup = [seenSym containsObject:nm];
                if (!dup) [seenSym addObject:nm];
                // The `attributes:` continuation belongs to its symbol line.
                NSMutableString *blk = [NSMutableString stringWithString:l];
                while (i + 1 < lines.count) {
                    NSString *nx = [lines[i+1] stringByTrimmingCharactersInSet:
                                        [NSCharacterSet whitespaceCharacterSet]];
                    if (![nx hasPrefix:@"attributes:"]) break;
                    [blk appendFormat:@"\n%@", lines[++i]];
                }
                if (!dup) [symbols addObject:blk];
                continue;
            }
            if ([t hasPrefix:@"function "]) {
                NSRange par = [t rangeOfString:@"("];
                NSString *nm = par.location == NSNotFound ? t
                    : [[t substringWithRange:NSMakeRange(9, par.location - 9)]
                          stringByTrimmingCharactersInSet:[NSCharacterSet whitespaceCharacterSet]];
                // Take the whole body: from here to the matching `  }`.
                NSMutableString *blk = [NSMutableString stringWithString:l];
                NSUInteger j = i + 1;
                for (; j < lines.count; j++) {
                    [blk appendFormat:@"\n%@", lines[j]];
                    if ([lines[j] isEqualToString:@"  }"]) break;
                }
                i = j;
                if (![seenFn containsObject:nm]) { [seenFn addObject:nm]; [functions addObject:blk]; }
                continue;
            }
        }
    }
    NSMutableString *out = [NSMutableString stringWithString:@"module \"lto\" {\n"];
    for (NSString *l in layouts)   [out appendFormat:@"%@\n", l];
    for (NSString *l in constants) [out appendFormat:@"%@\n", l];
    for (NSString *l in symbols)   [out appendFormat:@"%@\n", l];
    for (NSString *l in functions) [out appendFormat:@"%@\n", l];
    [out appendString:@"}\n"];
    return out;
}

static int dispatchIRPipeline(const char *argv0, XTCommandLineOptions *opts) {
    if (opts.inputFiles.count == 0) {
        fprintf(stderr, "xcc: error: no input file\n");
        return 1;
    }
    // ── linking objects: `xcc a.o b.o -o prog` ───────────────────────────
    // Multiple .xc inputs stay refused — that is a compile-many-into-one model,
    // and the whole point of separate compilation is not to need it. Multiple
    // OBJECT inputs are the opposite case: each was compiled on its own and this
    // is the link step. The runtime (crt+rt) is the primary input and the
    // objects ride as extras, which is exactly the shape the linker already
    // takes for static archives. Stage 2 of private:docs/Design/separate-compilation.md.
    {
        // A `.a` counts as a link input too: our linkers read archives, and an
        // archive on the command line is the ordinary way to say "resolve what
        // is still missing from in here". At least one `.o` is still required —
        // an archive is a POOL, so a link of nothing but pools has nothing to
        // seed the demand and would produce an empty image rather than an error.
        BOOL allObjects = YES, anyObject = NO;
        for (NSString *f in opts.inputFiles) {
            NSString *e = f.pathExtension;
            if ([e isEqualToString:@"o"]) { anyObject = YES; continue; }
            if ([e isEqualToString:@"a"]) continue;
            allObjects = NO; break;
        }
        allObjects = allObjects && anyObject;

        // The `#import <Lib>` list each object recorded when it was compiled.
        // An object link has no front end, so this sidecar is the only way it
        // can learn that the program needs a library at all — and getting it
        // wrong fails at LOAD ("Symbol not found"), never at link, because the
        // undefined symbols resolve happily against a .so that is then not
        // recorded as a dependency. Union across objects, first mention wins
        // the ordering, so a library named by two modules appears once.
        NSMutableArray<NSString *> *objNeeds = [NSMutableArray array];
        if (allObjects) {
            NSMutableSet<NSString *> *seenNeed = [NSMutableSet set];
            for (NSString *o in opts.inputFiles) {
                if (![o.pathExtension isEqualToString:@"o"]) continue;
                NSString *side = [[o stringByDeletingPathExtension]
                                     stringByAppendingPathExtension:@"xtc.needs"];
                NSString *body = [NSString stringWithContentsOfFile:side
                                                          encoding:NSUTF8StringEncoding error:NULL];
                for (NSString *ln in [(body ?: @"") componentsSeparatedByString:@"\n"]) {
                    NSString *t = [ln stringByTrimmingCharactersInSet:
                                      [NSCharacterSet whitespaceCharacterSet]];
                    if (!t.length || [seenNeed containsObject:t]) continue;
                    [seenNeed addObject:t];
                    [objNeeds addObject:t];
                }
            }
        }
        if (allObjects && opts.inputFiles.count >= 1 && !opts.compileOnly
            && opts.useArm9Backend) {
            // arm9: the objects carry no runtime stub (GNU ld has no first-wins
            // for a duplicate definition, unlike our own linkers), so the ARC and
            // heap helpers are generated ONCE, here.
            //
            // Which ones? Ask `nm` rather than guess. arm9StubSource decides what
            // to emit by scanning the module's ASM TEXT for the names it
            // references, and an object's symbol table carries exactly that
            // information more precisely — undefined names are what the program
            // still needs, defined ones (written back with the `:` the scanner
            // expects after a label) are what it already has. Guessing "emit them
            // all" would work today and rot the moment a helper became
            // module-specific again.
            // -flto: merge the IR each object carries, recompile as ONE module,
            // and hand the result to the ordinary arm9 link — after the merge
            // there is a single module again, which is the case linkArm9Shared
            // already handles.
            //
            // `--pic` is LOAD-BEARING and was the whole bug when this was first
            // attempted: the loader maps the image as a PIC ET_DYN, so codegen
            // without it emits absolute addresses and the program DATA-ABORTs.
            // The ordinary path passes it via `arm9Pic`; an LTO invocation that
            // rebuilds the codegen arguments by hand has to pass it too. It
            // linked, and was 5.2 KB smaller, and faulted — a missing flag looks
            // exactly like a miscompile from the outside.
            if (opts.lto) {
                NSMutableArray<NSString *> *irs = [NSMutableArray array];
                for (NSString *o in opts.inputFiles) {
                    NSString *side = [[o stringByDeletingPathExtension]
                                         stringByAppendingPathExtension:@"xtc.ir"];
                    NSString *t = [NSString stringWithContentsOfFile:side
                                                            encoding:NSUTF8StringEncoding error:NULL];
                    if (!t.length) {
                        fprintf(stderr, "xcc: error: -flto needs '%s' (compile that module "
                                        "with -c so it carries its IR)\n", side.UTF8String);
                        return 1;
                    }
                    [irs addObject:t];
                }
                NSString *mergedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-arm9.ir"];
                [mergeIRTexts(irs) writeToFile:mergedPath atomically:YES
                                      encoding:NSUTF8StringEncoding error:NULL];
                NSString *cg = resolveSiblingTool(argv0, @"xcc-cg-arm9");
                NSString *ltoAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-arm9.s"];
                NSMutableArray<NSString *> *cgArgs2 =
                    [@[[NSString stringWithFormat:@"-O%ld", (long)opts.optimisationLevel],
                       @"--pic", @"-o", ltoAsm, mergedPath] mutableCopy];
                if (opts.quiet) [cgArgs2 insertObject:@"-q" atIndex:0];
                int crc = runChild(cg, cgArgs2);
                if (crc != 0) return crc;
                int rc2 = linkArm9Shared(argv0, opts, ltoAsm, opts.outputPath, objNeeds, nil);
                if (rc2 == 0 && !opts.quiet)
                    fprintf(stderr, "xcc: arm9 image (LTO, %lu modules) -> '%s'\n",
                            (unsigned long)opts.inputFiles.count, opts.outputPath.UTF8String);
                return rc2;
            }
            // `nm` is only needed by the GCC fallback below, whose C stub is
            // generated from the symbol list. The in-house link reads the
            // objects itself and gets the same information more directly, so
            // requiring nm up front would reintroduce the very dependency this
            // path exists to remove — and did: with the GNU toolchain hidden,
            // the link failed here before reaching the in-house branch at all.
            NSString *nmOut = @"";
            if (!selfHostByDefault(opts)) {
                NSMutableArray<NSString *> *nmArgs = [@[@"arm-none-eabi-nm"] mutableCopy];
                [nmArgs addObjectsFromArray:opts.inputFiles];
                nmOut = runChildCapturingOutput(@"/usr/bin/env", nmArgs);
                if (!nmOut) {
                    fprintf(stderr, "xcc: error: arm9 object link needs arm-none-eabi-nm "
                                    "to read '%s'\n", opts.inputFiles.firstObject.UTF8String);
                    return 1;
                }
            }
            NSMutableString *symText = [NSMutableString string];
            NSMutableSet<NSString *> *seenCat = [NSMutableSet set];
            for (NSString *ln in [nmOut componentsSeparatedByString:@"\n"]) {
                NSString *t = [ln stringByTrimmingCharactersInSet:
                               [NSCharacterSet whitespaceCharacterSet]];
                if (!t.length) continue;
                NSArray<NSString *> *f = [t componentsSeparatedByString:@" "];
                NSString *name = f.lastObject;
                if (!name.length) continue;
                BOOL undef = [f.firstObject isEqualToString:@"U"];
                // Category-chain duplicates (§4.3b) — the in-house linkers catch
                // these themselves; here ld runs with
                // --allow-multiple-definition, so the check has to be ours.
                // `C$cat$Names` (owner anchor) duplicated = the same-NAMED
                // category on one class in two modules; bare `X$cat` duplicated
                // = the class itself compiled into two modules. Either way the
                // link would silently keep one table and run one module's
                // category method as the other's body.
                NSRange catr = [name rangeOfString:@"$cat$"];
                if (!undef && catr.location != NSNotFound) {
                    if ([seenCat containsObject:name]) {
                        fprintf(stderr, "xcc: error: two modules define category "
                                "'%s' on class '%s' ('%s' defined twice). The "
                                "category name is the extender's identity "
                                "(separate-compilation §4.3b) — rename one, or "
                                "compile both from one module\n",
                                [name substringFromIndex:catr.location + 5].UTF8String,
                                [name substringToIndex:catr.location].UTF8String,
                                name.UTF8String);
                        return 1;
                    }
                    [seenCat addObject:name];
                } else if (!undef && [name hasSuffix:@"$cat"]) {
                    if ([seenCat containsObject:name]) {
                        fprintf(stderr, "xcc: error: class '%s' is compiled into two "
                                "modules ('%s', its category-chain table, defined "
                                "twice)\n",
                                [name substringToIndex:name.length - 4].UTF8String,
                                name.UTF8String);
                        return 1;
                    }
                    [seenCat addObject:name];
                }
                // `U <name>` is undefined; anything else is a definition, and the
                // scanner looks for `<Class>$dealloc:` with the label colon.
                [symText appendFormat:@"%@%@\n", name, undef ? @"" : @":"];
            }
            // The `#import <lib>` list comes from each object's `.xtc.needs`
            // sidecar, written when the module was compiled — an object link
            // has no front end to ask.
            return linkArm9Objects(argv0, opts, opts.inputFiles, symText,
                                   opts.outputPath, objNeeds);
        }
        if (allObjects && opts.inputFiles.count >= 1 && !opts.compileOnly
            && opts.useWin64Backend) {
            // win64: same shape again, with the Windows runtime as the primary
            // input and the import table built from the same map the self-host
            // executable path uses — an OBJECT declares no imports, so every
            // kernel32 call arrives here still undefined and is resolved now.
            NSString *support = resolveSupportRoot(argv0, opts);
            NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-win64");
            NSFileManager *lfm = [NSFileManager defaultManager];
            NSMutableArray<NSString *> *args = [NSMutableArray array];
            for (NSString *n in @[@"crt-win64.s", @"rtgen-win64.s", @"rtfiles-win64.s", @"libmgen-win64.s"]) {
                NSString *p = [support stringByAppendingPathComponent:
                               [@"win64/runtime/" stringByAppendingString:n]];
                if (!ln || ![lfm fileExistsAtPath:p]) {
                    fprintf(stderr, "xcc: error: win64 link tools missing "
                            "(xcc-ln-win64=%s, runtime under %s)\n",
                            ln ? ln.UTF8String : "(missing)",
                            support ? support.UTF8String : "(no support root)");
                    return 1;
                }
                [args addObject:p];
            }
            // -flto: every object carries its IR, so merge them and recompile
            // as ONE module — the same shape as arm64 and x86-64, with the
            // Windows code generator and MS-ABI allocator stubs. The IR already
            // round-trips as text on every ordinary compile, so this needs no
            // new format; only the back end differs.
            if (opts.lto) {
                NSMutableArray<NSString *> *irs = [NSMutableArray array];
                for (NSString *o in opts.inputFiles) {
                    NSString *side = [[o stringByDeletingPathExtension]
                                         stringByAppendingPathExtension:@"xtc.ir"];
                    NSString *t = [NSString stringWithContentsOfFile:side
                                                            encoding:NSUTF8StringEncoding error:NULL];
                    if (!t.length) {
                        fprintf(stderr, "xcc: error: -flto needs '%s' (compile that module "
                                        "with -c so it carries its IR)\n", side.UTF8String);
                        return 1;
                    }
                    [irs addObject:t];
                }
                NSString *mergedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-win.ir"];
                [mergeIRTexts(irs) writeToFile:mergedPath atomically:YES
                                      encoding:NSUTF8StringEncoding error:NULL];
                NSString *cg = resolveSiblingTool(argv0, @"xcc-cg-win64");
                NSString *ltoAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-win.s"];
                NSMutableArray<NSString *> *cgArgs2 =
                    [@[[NSString stringWithFormat:@"-O%ld", (long)opts.optimisationLevel],
                       @"-o", ltoAsm, mergedPath] mutableCopy];
                if (opts.quiet) [cgArgs2 insertObject:@"-q" atIndex:0];
                int crc = runChild(cg, cgArgs2);
                if (crc != 0) return crc;
                NSString *prog2 = [NSString stringWithContentsOfFile:ltoAsm
                                                            encoding:NSUTF8StringEncoding error:NULL];
                NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-win-stubs.s"];
                [x86_64ClassAllocStubs(prog2, YES) writeToFile:stubPath atomically:YES
                                                      encoding:NSUTF8StringEncoding error:NULL];
                [args addObject:stubPath];
                [args addObject:ltoAsm];
                for (NSString *a in win64Libc(support) ?: @[]) [args addObject:a];
                [args addObjectsFromArray:@[@"-import",
                    @"kernel32.dll:ExitProcess,GetStdHandle,WriteFile,VirtualAlloc,"
                    @"GetSystemTimeAsFileTime,Sleep"]];
                NSString *impMap2 = [support stringByAppendingPathComponent:@"win64/win32-imports.map"];
                if ([lfm fileExistsAtPath:impMap2])
                    [args addObjectsFromArray:@[@"-importmap", impMap2]];
                [args addObjectsFromArray:@[@"-e", @"_start", @"-o", opts.outputPath]];
                int rc2 = runChild(ln, args);
                if (rc2 == 0 && !opts.quiet)
                    fprintf(stderr, "xcc: win64 PE (LTO, %lu modules) -> '%s'\n",
                            (unsigned long)opts.inputFiles.count, opts.outputPath.UTF8String);
                return rc2;
            }
            // As x86-64 below: an xtc `#import <Lib>` has no DLL import entry
            // here, so refuse rather than emit a PE that dies at load.
            if (objNeeds.count) {
                fprintf(stderr, "xcc: error: these objects import xtc librar%s (%s), "
                        "but a win64 object link cannot record a DLL dependency for "
                        "them yet.\n  Link from source, or compile the modules "
                        "together.\n",
                        objNeeds.count == 1 ? "y" : "ies",
                        [objNeeds componentsJoinedByString:@", "].UTF8String);
                return 1;
            }
            [args addObjectsFromArray:opts.inputFiles];
            [args addObjectsFromArray:@[@"-import",
                @"kernel32.dll:ExitProcess,GetStdHandle,WriteFile,VirtualAlloc,"
                @"GetSystemTimeAsFileTime,Sleep"]];
            NSString *impMap = [support stringByAppendingPathComponent:@"win64/win32-imports.map"];
            if ([lfm fileExistsAtPath:impMap])
                [args addObjectsFromArray:@[@"-importmap", impMap]];
            [args addObjectsFromArray:@[@"-e", @"_start", @"-o", opts.outputPath]];
            int rc = runChild(ln, args);
            if (rc == 0 && !opts.quiet)
                fprintf(stderr, "xcc: win64 PE (from %lu object%s) -> '%s'\n",
                        (unsigned long)opts.inputFiles.count,
                        opts.inputFiles.count == 1 ? "" : "s", opts.outputPath.UTF8String);
            return rc;
        }
        if (allObjects && opts.inputFiles.count >= 1 && !opts.compileOnly
            && opts.useX86_64Backend) {
            // x86-64: the same shape, with the Linux runtime as the primary
            // input. In-house whether or not `--self-host` was asked for —
            // objects come from our own writer, so the link that consumes them
            // is ours too, and musl-clang could not read our `.s` runtime
            // anyway.
            NSString *support = resolveSupportRoot(argv0, opts);
            NSString *ln = resolveSiblingTool(argv0, @"xcc-ln-x86_64");
            NSFileManager *lfm = [NSFileManager defaultManager];
            NSMutableArray<NSString *> *args = [NSMutableArray array];
            for (NSString *n in @[@"crt-linux.s", @"sys-linux.s",
                                  @"rtgen-linux.s", @"rtfiles-linux.s", @"libmgen-linux.s"]) {
                NSString *p = [support stringByAppendingPathComponent:
                               [@"x86_64/runtime/" stringByAppendingString:n]];
                if (!ln || ![lfm fileExistsAtPath:p]) {
                    fprintf(stderr, "xcc: error: x86-64 link tools missing "
                            "(xcc-ln-x86_64=%s, runtime under %s)\n",
                            ln ? ln.UTF8String : "(missing)",
                            support ? support.UTF8String : "(no support root)");
                    return 1;
                }
                [args addObject:p];
            }
            // -flto: the same trick as arm64 — every object carries its IR, so
            // merge those and recompile as ONE module, which gives the inliner
            // and cross-function DCE the whole program back. The IR is already
            // a text format with a parser (it crosses a process boundary on
            // every compile), so this needs no new format on either target.
            if (opts.lto) {
                NSMutableArray<NSString *> *irs = [NSMutableArray array];
                for (NSString *o in opts.inputFiles) {
                    NSString *side = [[o stringByDeletingPathExtension]
                                         stringByAppendingPathExtension:@"xtc.ir"];
                    NSString *t = [NSString stringWithContentsOfFile:side
                                                           encoding:NSUTF8StringEncoding error:NULL];
                    if (!t.length) {
                        fprintf(stderr, "xcc: error: -flto needs '%s' (compile that module "
                                        "with -c so it carries its IR)\n", side.UTF8String);
                        return 1;
                    }
                    [irs addObject:t];
                }
                NSString *mergedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-x86.ir"];
                [mergeIRTexts(irs) writeToFile:mergedPath atomically:YES
                                      encoding:NSUTF8StringEncoding error:NULL];
                NSString *cg = resolveSiblingTool(argv0, @"xcc-cg-x86_64");
                NSString *ltoAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-x86.s"];
                NSMutableArray<NSString *> *cgArgs2 =
                    [@[[NSString stringWithFormat:@"-O%ld", (long)opts.optimisationLevel],
                       @"-o", ltoAsm, mergedPath] mutableCopy];
                if (opts.quiet) [cgArgs2 insertObject:@"-q" atIndex:0];
                int crc = runChild(cg, cgArgs2);
                if (crc != 0) return crc;
                NSString *prog2 = [NSString stringWithContentsOfFile:ltoAsm
                                                           encoding:NSUTF8StringEncoding error:NULL];
                NSString *stubPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-x86-stubs.s"];
                [x86_64ClassAllocStubs(prog2, NO) writeToFile:stubPath atomically:YES
                                                     encoding:NSUTF8StringEncoding error:NULL];
                [args addObject:stubPath];
                [args addObject:ltoAsm];
                { NSString *mA = x86MuslLibc(support);
                  if (!mA) return x86MissingPool(support);
                  [args addObject:mA];
                  NSString *gA = x86MuslLibgcc(support); if (gA) [args addObject:gA]; }
                [args addObjectsFromArray:@[@"-o", opts.outputPath]];
                int rc2 = runChild(ln, args);
                if (rc2 == 0 && !opts.quiet)
                    fprintf(stderr, "xcc: x86-64 ELF (LTO, %lu modules) -> '%s'\n",
                            (unsigned long)opts.inputFiles.count, opts.outputPath.UTF8String);
                return rc2;
            }
            // A `#import <Lib>` recorded by one of these objects cannot be
            // honoured here: this link is a STATIC ELF, which has no DT_NEEDED
            // to record it in. Say so, rather than letting the link fail lower
            // down with "undefined symbol ... is the runtime missing?" — the
            // symbols really are absent, but the reason is the library.
            if (objNeeds.count) {
                fprintf(stderr, "xcc: error: these objects import xtc librar%s (%s), "
                        "but an x86-64 object link is a STATIC ELF and cannot record "
                        "a shared-library dependency.\n  Link from source, or compile "
                        "the modules together.\n",
                        objNeeds.count == 1 ? "y" : "ies",
                        [objNeeds componentsJoinedByString:@", "].UTF8String);
                return 1;
            }
            [args addObjectsFromArray:opts.inputFiles];
            // The libc pool, exactly as the ordinary static-exec link appends
            // it: the runtime's heap delegates to calloc/free now, and an
            // object is free to call anything musl defines.
            { NSString *mA = x86MuslLibc(support);
              if (!mA) return x86MissingPool(support);
              [args addObject:mA];
              NSString *gA = x86MuslLibgcc(support); if (gA) [args addObject:gA]; }
            [args addObjectsFromArray:@[@"-o", opts.outputPath]];
            int rc = runChild(ln, args);
            if (rc == 0 && !opts.quiet)
                fprintf(stderr, "xcc: x86-64 ELF (from %lu object%s) -> '%s'\n",
                        (unsigned long)opts.inputFiles.count,
                        opts.inputFiles.count == 1 ? "" : "s", opts.outputPath.UTF8String);
            return rc;
        }
        if (allObjects && opts.inputFiles.count >= 1 && !opts.compileOnly) {
            if (!opts.useArm64Backend) {
                fprintf(stderr, "xcc: error: linking objects is implemented for the "
                                "hosted targets only (private:docs/Design/separate-compilation.md "
                                "§7)\n");
                return 1;
            }
            NSString *support = resolveSupportRoot(argv0, opts);
            NSString *ln  = resolveSiblingTool(argv0, @"xcc-ln-arm64");
            NSString *crt = [support stringByAppendingPathComponent:@"arm64/runtime/crt-macos.s"];
            NSString *rt  = [support stringByAppendingPathComponent:@"arm64/runtime/rt-macos.s"];
            NSFileManager *lfm = [NSFileManager defaultManager];
            if (!ln || ![lfm fileExistsAtPath:crt] || ![lfm fileExistsAtPath:rt]) {
                fprintf(stderr, "xcc: error: link tools missing (ln=%s, crt=%s)\n",
                        ln ? ln.UTF8String : "(missing)", crt.UTF8String);
                return 1;
            }
            // -flto: every object carries its IR, so merge them and recompile
            // as ONE module. That restores exactly what per-object compilation
            // gives up — the inliner and cross-function DCE see the whole
            // program again — and it needs no new format, because the IR
            // already round-trips as text on every ordinary compile.
            if (opts.lto) {
                NSMutableArray<NSString *> *irs = [NSMutableArray array];
                for (NSString *o in opts.inputFiles) {
                    NSString *side = [[o stringByDeletingPathExtension]
                                         stringByAppendingPathExtension:@"xtc.ir"];
                    NSString *t = [NSString stringWithContentsOfFile:side
                                                            encoding:NSUTF8StringEncoding error:NULL];
                    if (!t.length) {
                        fprintf(stderr, "xcc: error: -flto needs '%s' (compile that module "
                                        "with -c so it carries its IR)\n", side.UTF8String);
                        return 1;
                    }
                    [irs addObject:t];
                }
                NSString *merged = mergeIRTexts(irs);
                NSString *mergedPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto.ir"];
                [merged writeToFile:mergedPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
                NSString *cg = resolveSiblingTool(argv0, @"xcc-cg-arm64");
                NSString *ltoAsm = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto.s"];
                NSMutableArray<NSString *> *cgArgs2 =
                    [@[[NSString stringWithFormat:@"-O%ld", (long)opts.optimisationLevel],
                       @"-o", ltoAsm, mergedPath] mutableCopy];
                if (opts.quiet) [cgArgs2 insertObject:@"-q" atIndex:0];
                int crc = runChild(cg, cgArgs2);
                if (crc != 0) return crc;
                NSString *prog2 = [NSString stringWithContentsOfFile:ltoAsm
                                                           encoding:NSUTF8StringEncoding error:NULL];
                NSString *ltoCombined = [NSString stringWithFormat:@"%@\n%@\n%@\n%@",
                    [NSString stringWithContentsOfFile:crt encoding:NSUTF8StringEncoding error:NULL] ?: @"",
                    [NSString stringWithContentsOfFile:rt  encoding:NSUTF8StringEncoding error:NULL] ?: @"",
                    arm64ClassAllocStubs(prog2), prog2 ?: @""];
                NSString *ltoPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-lto-all.s"];
                [ltoCombined writeToFile:ltoPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
                int rc2 = runChild(ln, @[ltoPath, opts.outputPath]);
                if (rc2 == 0 && !opts.quiet)
                    fprintf(stderr, "xcc: arm64 executable (LTO, %lu modules) -> '%s'\n",
                            (unsigned long)opts.inputFiles.count, opts.outputPath.UTF8String);
                return rc2;
            }
            NSString *combined = [NSString stringWithFormat:@"%@\n%@",
                [NSString stringWithContentsOfFile:crt encoding:NSUTF8StringEncoding error:NULL] ?: @"",
                [NSString stringWithContentsOfFile:rt  encoding:NSUTF8StringEncoding error:NULL] ?: @""];
            if (opts.applePlatform) {                    // the iOS shim, as the source path links it
                NSString *ios = [support stringByAppendingPathComponent:
                                 [opts.applePlatform isEqualToString:@"ios-sim"]
                                     ? @"ios/runtime/xtios-sim.s" : @"ios/runtime/xtios.s"];
                NSString *iossrc = [NSString stringWithContentsOfFile:ios encoding:NSUTF8StringEncoding error:NULL];
                if (!iossrc.length) {
                    fprintf(stderr, "xcc: error: the iOS runtime shim %s is missing\n", ios.UTF8String);
                    return 1;
                }
                combined = [NSString stringWithFormat:@"%@\n%@", combined, iossrc];
            }
            NSString *rtPath = [xtcTempDir() stringByAppendingPathComponent:@"xtc-link-rt.s"];
            [combined writeToFile:rtPath atomically:YES encoding:NSUTF8StringEncoding error:NULL];
            NSMutableArray<NSString *> *args =
                [@[rtPath, opts.outputPath] mutableCopy];
            // The platform stamp, as the source path passes it (137's other half).
            if (opts.applePlatform) [args addObjectsFromArray:@[@"-platform", opts.applePlatform]];
            [args addObjectsFromArray:opts.inputFiles];
            [args addObjectsFromArray:objNeeds];    // LC_LOAD_DYLIB per #import <Lib>
            int rc = runChild(ln, args);
            if (rc == 0 && !opts.quiet)
                fprintf(stderr, "xcc: arm64 executable (from %lu object%s) -> '%s'\n",
                        (unsigned long)opts.inputFiles.count,
                        opts.inputFiles.count == 1 ? "" : "s", opts.outputPath.UTF8String);
            return rc;
        }
    }
    // `-o foo.o` WITHOUT `-c` is the lie this whole programme exists to end
    // (design §9). What it actually did was run a full link and write an
    // EXECUTABLE to the `.o` path — reporting success on arm64, and failing
    // deep inside someone else's crt1.o on x86_64. Neither is what the person
    // who typed `.o` asked for.
    //
    // C says nothing here (`cc -o foo.o x.c` really does make an executable),
    // but in this tree `.o` means object everywhere else — `xcc a.o b.o` links
    // them — so silently meaning the opposite in one place is a trap rather
    // than a convention. Name the flag that does what they meant.
    if (!opts.compileOnly && opts.outputPath.length
        && [opts.outputPath.pathExtension isEqualToString:@"o"]) {
        fprintf(stderr, "xcc: error: '-o %s' without -c would LINK an executable and "
                        "name it '.o'. Use `-c` to compile to an object, or choose "
                        "another output name\n", opts.outputPath.UTF8String);
        return 1;
    }
    // -c is a hosted-target feature. Refuse HERE, before the per-arch dispatch:
    // the implementation lives in each backend's link function, so a target
    // without one would sail straight past it and write an EXECUTABLE to the .o
    // path. 6502 and m68k are deferred (private:docs/Design/separate-compilation.md §7).
    if (opts.compileOnly && !opts.useArm64Backend && !opts.useX86_64Backend
        && !opts.useWin64Backend && !opts.useArm9Backend) {
        fprintf(stderr, "xcc: error: -c is implemented for the hosted targets (arm64, "
                        "x86_64, win64, arm9) only — 6502 and m68k are single-module by "
                        "construction (private:docs/Design/separate-compilation.md §7)\n");
        return 1;
    }
    if (opts.inputFiles.count > 1) {
        fprintf(stderr, "xcc: error: multi-file inputs not supported on the new-IR path yet\n");
        return 1;
    }
    NSString *input = opts.inputFiles.firstObject;

    NSString *feTool = resolveSiblingTool(argv0, @"xcc-fe");
    NSString *cgName = opts.useM68kBackend ? @"xcc-cg-68k"
                     : opts.useWin64Backend ? @"xcc-cg-win64"
                     : opts.useX86_64Backend ? @"xcc-cg-x86_64"
                     : opts.useWasm32Backend ? @"xcc-cg-wasm32"
                     : opts.useArm9Backend ? @"xcc-cg-arm9"
                     : opts.useArm64Backend ? @"xcc-cg-arm64"
                     : @"xcc-cg-6502";
    NSString *cgTool = resolveSiblingTool(argv0, cgName);
    if (!feTool || !cgTool) {
        fprintf(stderr, "xcc: error: helper binaries not found "
                        "(xtc-fe=%s, %s=%s)\n",
                feTool ? feTool.UTF8String : "(missing)",
                cgName.UTF8String,
                cgTool ? cgTool.UTF8String : "(missing)");
        return 1;
    }

    NSString *base = [input.lastPathComponent stringByDeletingPathExtension];
    NSString *irPath = [NSTemporaryDirectory()
        stringByAppendingPathComponent:
            [NSString stringWithFormat:@"xtc-%@-%d.ir", base, getpid()]];

    // Build the xtc-fe arg list. We need -m, -I*, -D*, -q, -V, the input,
    // and -o irPath. We can rebuild from the parsed options rather than
    // forwarding argv literally — cleaner, and lets us drop flags the fe
    // doesn't care about (e.g. -O passes through to cg).
    NSMutableArray<NSString *> *feArgs = [NSMutableArray array];
    if (opts.useArm9Backend) {
        // ARMv7-A / AArch32 (Zynq Cortex-A9): libs from support/arm9/, ARCH_arm9.
        [feArgs addObjectsFromArray:@[@"-m", @"arm9"]];
    } else if (opts.useArm64Backend) {
        [feArgs addObjectsFromArray:@[@"-m", @"arm64"]];
        // The iOS platform LAYER (support/ios/lib, PLATFORM_ios) is the front
        // end's business too: without this the front end saw plain arm64 and
        // the prelude the port found was invisible to the reference.
        if (opts.applePlatform) [feArgs addObjectsFromArray:@[@"-A", opts.applePlatform]];
    } else if (opts.useM68kBackend) {
        // Atari ST/TT platform: libs from support/atarist/, ARCH_m68k, no
        // 6502 memory model. (Was a temporary `-m arm64` shim through M2.5.)
        [feArgs addObjectsFromArray:@[@"-m", @"atarist"]];
    } else if (opts.useWin64Backend) {
        // x86-64 Windows: libs from support/win64+x86_64, ARCH_x86_64+ARCH_win64.
        [feArgs addObjectsFromArray:@[@"-m", @"win64"]];
    } else if (opts.targetName) {
        [feArgs addObjectsFromArray:@[@"-m", opts.targetName]];
    }
    for (NSString *path in opts.includePaths) {
        [feArgs addObjectsFromArray:@[@"-I", path]];
    }
    // Library-metadata search dirs — the front end resolves `#import <lib>`
    // against these (.so → .dynsym ∩ DWARF) and types the imported symbols.
    for (NSString *path in opts.libraryPaths) {
        [feArgs addObjectsFromArray:@[@"-L", path]];
    }
    [opts.defines enumerateKeysAndObjectsUsingBlock:^(NSString *k, NSString *v, BOOL *s) {
        [feArgs addObject:[NSString stringWithFormat:@"-D%@=%@", k, v]];
    }];
    // Warning suppressions. Every -Wno- category is diagnosed by the FRONT END
    // (lexer / preprocessor / sema), so a flag the dispatcher keeps to itself
    // silences nothing: `xcc -Wno-comment` still printed the warning while
    // `xcc-fe -Wno-comment` did not. That made every documented category a
    // no-op through the driver, which is the only way most people invoke it.
    for (NSString *cat in opts.suppressedWarnings) {
        [feArgs addObject:[NSString stringWithFormat:@"-Wno-%@", cat]];
    }
    if (opts.quiet)   [feArgs addObject:@"-q"];
    // A CHECKED build is decided in the LOWERING, which runs in the front-end
    // process — so a dispatcher that keeps this to itself emits no checks at
    // all, exactly as the -Wno- note above describes. Found that way: the flag
    // parsed, the driver passed it to its own in-process lowering, and
    // `xcc -fbounds-check` still produced zero check sites.
    if (opts.boundsCheck) [feArgs addObject:@"-fbounds-check"];
    if (opts.emitLib) [feArgs addObject:@"--emit-lib"];  // L2: write the .xtc.iface sidecar
    if (opts.emitIface) [feArgs addObject:@"--emit-iface"];  // same sidecar, without becoming a library build
    // -c wants the same sidecar (stage 3): the front end is a separate process,
    // so it has to be told, or compileOnly is simply false over there.
    if (opts.compileOnly) [feArgs addObject:@"-c"];
    if (opts.verbose) [feArgs addObject:@"-V"];
    if (opts.xtcHome) [feArgs addObjectsFromArray:@[@"-H", opts.xtcHome]];
    // Nothing to forward for ARC: the flag is retired (bug 026) and ARC is
    // always on. `delete` of a struct or primitive array — the case those
    // programs actually needed — is now allowed outright, so there is no
    // front-end mode to keep the two paths in step on. (-falloc is left for
    // xtc-fe to resolve from the target.)
    //
    // -f[no-]thread-safe-arc IS forwarded, and the reason is easy to miss:
    // atomic ARC is a BACK-END decision (hence the cgArgs forward further down),
    // but the race-free static-init once that rides the same switch is decided
    // in LOWERING — which runs here, in xcc-fe. Without this the flag reaches the
    // back end and silently misses the front end, so -fno-thread-safe-arc still
    // emitted the once, and the fixture meant to prove the fix passed with the
    // fix turned off.
    if (opts.threadSafeARC == 1)      [feArgs addObject:@"-fthread-safe-arc"];
    else if (opts.threadSafeARC == 0) [feArgs addObject:@"-fno-thread-safe-arc"];
    if (opts.migrateVersions.length)
        [feArgs addObject:[NSString stringWithFormat:@"--migrate=%@",
                           opts.migrateVersions]];
    [feArgs addObjectsFromArray:@[input, @"-o", irPath]];

    int feRc = runChild(feTool, feArgs);
    if (feRc != 0) {
        [[NSFileManager defaultManager] removeItemAtPath:irPath error:NULL];
        return feRc < 0 ? 1 : feRc;
    }

    // Pick up the DT_NEEDED sidecar the front end wrote (the .so paths whose
    // symbols this program imports). The dispatcher can't see #import itself,
    // so the front end hands them across via `<irPath>.needs`.
    NSString *needsPath = [irPath stringByAppendingPathExtension:@"needs"];
    NSArray<NSString *> *neededLibs = @[];
    {
        NSString *needsBody = [NSString stringWithContentsOfFile:needsPath
                                                        encoding:NSUTF8StringEncoding error:NULL];
        if (needsBody.length) {
            NSMutableArray<NSString *> *libs = [NSMutableArray array];
            for (NSString *ln in [needsBody componentsSeparatedByString:@"\n"]) {
                NSString *t = [ln stringByTrimmingCharactersInSet:
                                  [NSCharacterSet whitespaceCharacterSet]];
                if (t.length) [libs addObject:t];
            }
            neededLibs = libs;
        }
        [[NSFileManager defaultManager] removeItemAtPath:needsPath error:NULL];
    }

    // --emit-lib: the front end serialised the public declarations to
    // `<irPath>.iface`; the dispatcher embeds them in the library's `.xtc.iface`
    // section so an app can `#import <Lib>` the binary (B1).
    NSString *ifaceSidecar = [irPath stringByAppendingPathExtension:@"iface"];
    NSString *ifaceJson = (opts.emitLib || opts.compileOnly || opts.emitIface)
        ? [NSString stringWithContentsOfFile:ifaceSidecar encoding:NSUTF8StringEncoding error:NULL]
        : nil;
    // --emit-iface: the interface IS the output. Stop here — the caller is a
    // designer asking what this source declares, not a build asking for code,
    // and running codegen would be pure latency in an editor loop.
    if (opts.emitIface) {
        if (!ifaceJson.length) {
            fprintf(stderr, "xcc: --emit-iface: no public declarations to describe\n");
            return 1;
        }
        if (opts.outputPath.length && ![opts.outputPath isEqualToString:@"-"]) {
            NSError *werr = nil;
            if (![ifaceJson writeToFile:opts.outputPath atomically:YES
                               encoding:NSUTF8StringEncoding error:&werr]) {
                fprintf(stderr, "xcc: cannot write '%s': %s\n",
                        opts.outputPath.UTF8String,
                        werr.localizedDescription.UTF8String ?: "write failed");
                return 1;
            }
            if (!opts.quiet)
                fprintf(stderr, "xcc: interface -> '%s'\n", opts.outputPath.UTF8String);
        } else {
            fputs(ifaceJson.UTF8String, stdout);
            if (![ifaceJson hasSuffix:@"\n"]) fputc('\n', stdout);
        }
        return 0;
    }
    // -c keeps it beside the object as `<out>.xtc.iface`: the interface is a
    // BUILD ARTIFACT of compiling the module, exactly as the .o is, and whoever
    // compiles against this module reads it rather than its source.
    if (opts.compileOnly && ifaceJson.length) {
        NSString *side = [[opts.outputPath stringByDeletingPathExtension]
                             stringByAppendingPathExtension:@"xtc.iface"];
        [ifaceJson writeToFile:side atomically:YES encoding:NSUTF8StringEncoding error:NULL];
        if (!opts.quiet) fprintf(stderr, "xcc: interface -> '%s'\n", side.UTF8String);
    }
    // ...and the same for the DT_NEEDED list. `#import <Lib>` is a FRONT-END
    // fact, discovered when the module was compiled, and an object link has no
    // front end — so without this the linker cannot know the program needs the
    // library at all. It does not fail at link (the symbols come from the
    // object's own undefined list and resolve against the .so on the command
    // line, or not at all); it fails at LOAD, with "Symbol not found".
    //
    // Written even when EMPTY, so the link can tell "this object needs nothing"
    // apart from "this object predates the sidecar and I know nothing about it".
    if (opts.compileOnly) {
        // SHARED libraries only. `neededLibs` also carries the archives the
        // back end auto-injects (win64's libkernel32.a / libuser32.a /
        // libgdi32.a), and a `.a` is not a runtime dependency at all — it is
        // linked in, not loaded. Recording those made every win64 and arm9
        // object link refuse itself. DT_NEEDED / LC_LOAD_DYLIB name a shared
        // object, so that is exactly the test.
        NSMutableArray<NSString *> *shared = [NSMutableArray array];
        for (NSString *l in neededLibs) {
            NSString *base = l.lastPathComponent;
            if ([base hasSuffix:@".dylib"] || [base hasSuffix:@".so"]
                || [base rangeOfString:@".so."].location != NSNotFound)
                [shared addObject:l];
        }
        NSString *needSide = [[opts.outputPath stringByDeletingPathExtension]
                                 stringByAppendingPathExtension:@"xtc.needs"];
        [[shared componentsJoinedByString:@"\n"] writeToFile:needSide atomically:YES
                                                    encoding:NSUTF8StringEncoding error:NULL];
        if (!opts.quiet && shared.count)
            fprintf(stderr, "xcc: needs -> '%s' (%lu librar%s)\n", needSide.UTF8String,
                    (unsigned long)shared.count, shared.count == 1 ? "y" : "ies");
    }
    // -c also keeps the module's IR beside the object (stage 5). The IR is
    // already a serialisable text format with a parser — it crosses a process
    // boundary on EVERY compile, xcc-fe writing it and xcc-cg reading it back —
    // so carrying it costs a file copy rather than a new format. A link that
    // finds these can re-run the inliner across module boundaries, which is what
    // per-object compilation otherwise gives up.
    if (opts.compileOnly) {
        NSString *irSide = [[opts.outputPath stringByDeletingPathExtension]
                               stringByAppendingPathExtension:@"xtc.ir"];
        NSString *irText = [NSString stringWithContentsOfFile:irPath
                                                     encoding:NSUTF8StringEncoding error:NULL];
        if (irText.length) {
            [irText writeToFile:irSide atomically:YES encoding:NSUTF8StringEncoding error:NULL];
            if (!opts.quiet) fprintf(stderr, "xcc: ir -> '%s'\n", irSide.UTF8String);
        }
    }
    [[NSFileManager defaultManager] removeItemAtPath:ifaceSidecar error:NULL];

    // arm64: a native executable when the output isn't raw assembly (.s/.asm)
    // and isn't stdout — codegen to a temp .s, then clang assembles + links it.
    NSString *outExt = opts.outputPath.pathExtension.lowercaseString;
    BOOL arm64Exe = opts.useArm64Backend && opts.outputPath
        && !([@[@"s", @"asm"] containsObject:outExt ?: @""]);
    // arm9: any non-assembly output is a loader-hosted, position-independent
    // ET_DYN (PIC) — whether spelled `.so` or a bare program name. It links the
    // heap runtime against the device libc.so (DT_NEEDED) and is loaded by the
    // XTOS loader, which resolves the imports. There is no static bare-metal arm9
    // image — the newlib-static path (linkArm9Executable / arm9/runtime/libxt.c)
    // was retired once the loader/PIC path was the only one selected.
    BOOL arm9Pic = opts.useArm9Backend && opts.outputPath
        && !([@[@"s", @"asm"] containsObject:outExt ?: @""]);
    // x86-64: a static-musl native Linux ELF (codegen to a temp .s, then the musl
    // cross-clang assembles + ld.lld links).
    BOOL x86Exe = opts.useX86_64Backend && opts.outputPath
        && !([@[@"s", @"asm"] containsObject:outExt ?: @""]);
    // win64: any non-assembly output is a static PE built by the mingw toolchain.
    BOOL win64Exe = opts.useWin64Backend && opts.outputPath
        && !([@[@"s", @"asm"] containsObject:outExt ?: @""]);
    // wasm32: `.wat` (or .s/.asm) stops after codegen with the WAT text; any
    // other output runs the in-house module build — <out>.wasm plus the .js
    // loader that runs it under Node.js or a browser.
    BOOL wasm32Mod = opts.useWasm32Backend && opts.outputPath
        && !([@[@"wat", @"s", @"asm"] containsObject:outExt ?: @""]);
    NSString *cgOut = opts.outputPath;
    NSString *tmpAsm = nil;
    if (arm64Exe || arm9Pic || x86Exe || win64Exe || wasm32Mod) {
        tmpAsm = [NSTemporaryDirectory() stringByAppendingPathComponent:
            [NSString stringWithFormat:@"xtc-%@-%d.%@", base, getpid(),
                                       wasm32Mod ? @"wat" : @"s"]];
        cgOut = tmpAsm;
    }

    // Build xtcg arg list: -m (xt only), -O level, -o output, the .ir.
    NSMutableArray<NSString *> *cgArgs = [NSMutableArray array];
    if (!opts.useArm64Backend && !opts.useM68kBackend && !opts.useArm9Backend
        && !opts.useX86_64Backend && !opts.useWin64Backend
        && !opts.useWasm32Backend && opts.targetName) {
        [cgArgs addObjectsFromArray:@[@"-m", opts.targetName]];
        // Forward the resolved xtc home so xtcg-6502 finds its layout (.lnk) AND
        // its runtime harness / asm tree under the SAME root the driver used —
        // not cwd or a stale /opt/xtc. (feArgs already forwards -H the same way.)
        if (opts.xtcHome) [cgArgs addObjectsFromArray:@[@"-H", opts.xtcHome]];
        // The xt6502 options are all the code generator's business: the quit
        // style edits the startup it wraps round the program, and the rest
        // change or report the functions it emits and where it puts them.
        if (opts.quitLoop) [cgArgs addObjectsFromArray:@[@"-Q", @"loop"]];
        if (opts.useXtcStack) [cgArgs addObject:@"--xtc-stack"];
        if (opts.fnMinBanked > 0)
            [cgArgs addObjectsFromArray:@[@"-Fmb",
                [NSString stringWithFormat:@"%lu", (unsigned long)opts.fnMinBanked]]];
        if (opts.dumpPlacement) [cgArgs addObject:@"-dp"];
        if (opts.dumpUsage) [cgArgs addObject:@"-du"];
    }
    if (opts.useM68kBackend) {
        [cgArgs addObjectsFromArray:@[@"--cpu",
            [NSString stringWithFormat:@"%ld", (long)opts.m68kCpu]]];
        if (opts.m68kHardFloat) [cgArgs addObject:@"--hard-float"];
        if (opts.m68kPic) [cgArgs addObject:@"--pic"];
    }
    if (opts.optimisationLevel > 0) {
        [cgArgs addObject:[NSString stringWithFormat:@"-O%ld",
                           (long)opts.optimisationLevel]];
    } else {
        [cgArgs addObject:@"-O0"];
    }
    if (opts.quiet) [cgArgs addObject:@"-q"];
    // Thread-safe ARC. Forwarded only when the user forced it: left alone, the
    // code generator decides per module ("does anything here spawn a thread?"),
    // which is the answer the driver can't compute — it never sees the IR.
    // Android is plain AAPCS64, not Darwin. A CODEGEN decision, so it must be
    // forwarded here — the LINK is identical either way, which is why getting
    // it wrong prints garbage rather than failing to build.
    if (opts.androidTarget) {
        [cgArgs addObject:@"--aapcs64-abi"];
        // Android's minSdk floor is plain armv8-a, so the LSE atomics Apple
        // Silicon always has are not available. The emulator on an arm64 Mac
        // HAS them, which is why this cannot be found by running there — the
        // NDK assembler refusing them is the only signal.
        [cgArgs addObject:@"--no-lse-atomics"];
    }
    if (opts.threadSafeARC == 1)      [cgArgs addObject:@"--thread-safe-arc"];
    else if (opts.threadSafeARC == 0) [cgArgs addObject:@"--no-thread-safe-arc"];
    if (arm9Pic) [cgArgs addObject:@"--pic"];   // Tier-2 position-independent codegen
    if (opts.emitLib) [cgArgs addObject:@"--emit-lib"];  // L1: keep + export the public class API
    // -c: an object's functions are all potentially called from another object,
    // so cross-function DCE must not treat "nothing here calls it" as dead.
    if (opts.compileOnly) [cgArgs addObject:@"--object"];
    // wasm32 app that #imports .wasm libraries: the code generator must
    // export the runtime/memory/table surface the loader wires each library
    // to (and resolve library symbols through package imports). The
    // dispatcher is the only party that knows the dep list — it read the
    // front end's `.needs` sidecar.
    if (opts.useWasm32Backend && !opts.emitLib) {
        for (NSString *lib in neededLibs) {
            if ([lib.pathExtension isEqualToString:@"wasm"]) {
                [cgArgs addObject:@"--link-libs"];
                break;
            }
        }
    }
    // Target-specific options (-x-<arch>,<opt>...): forward the ones for THIS
    // arch verbatim; sets for other arches were validated then ignored.
    {
        NSString *archKey = opts.useWasm32Backend ? @"wasm32" : nil;
        NSArray<NSString *> *xopts = archKey ? opts.targetOptions[archKey] : nil;
        if (xopts.count)
            [cgArgs addObject:[NSString stringWithFormat:@"-x-%@,%@",
                archKey, [xopts componentsJoinedByString:@","]]];
    }
    if (cgOut) [cgArgs addObjectsFromArray:@[@"-o", cgOut]];
    [cgArgs addObject:irPath];

    int cgRc = runChild(cgTool, cgArgs);

    // Clean up the intermediate .ir unless verbose (keeps it for debugging).
    if (!opts.verbose) {
        [[NSFileManager defaultManager] removeItemAtPath:irPath error:NULL];
    } else {
        fprintf(stderr, "xcc: intermediate IR kept at '%s'\n", irPath.UTF8String);
    }
    if (cgRc != 0) {
        if (tmpAsm) [[NSFileManager defaultManager] removeItemAtPath:tmpAsm error:NULL];
        return cgRc < 0 ? 1 : cgRc;
    }
    if (arm64Exe || arm9Pic || x86Exe || win64Exe || wasm32Mod) {
        // --emit-apk is an Android-only packaging step. Silently producing a
        // plain executable for it would look like it worked.
        if (opts.emitApk && !opts.androidTarget) {
            fprintf(stderr, "xcc: error: --emit-apk requires -A android\n");
            return 1;
        }
        int linkRc = wasm32Mod
            ? linkWasm32Module(argv0, opts, tmpAsm, opts.outputPath, neededLibs, ifaceJson)
            : arm9Pic
            ? linkArm9Shared(argv0, opts, tmpAsm, opts.outputPath, neededLibs, ifaceJson)
            : (win64Exe && opts.emitLib && !opts.compileOnly)
            ? linkWin64Shared(argv0, opts, tmpAsm, opts.outputPath, ifaceJson)
            : win64Exe
            ? linkWin64Executable(argv0, opts, tmpAsm, opts.outputPath, neededLibs)
            // `-c` must reach linkX86_64Executable, which is where the object
            // path lives — the -shared and dynamic-exe variants are LINKS, and
            // a compile that imported a library was being routed into one of
            // them and handed the `.xtc.iface` to ld.lld ("unknown file type").
            : (x86Exe && opts.emitLib && !opts.compileOnly)
            ? linkX86_64Shared(argv0, opts, tmpAsm, opts.outputPath, ifaceJson)
            : (x86Exe && neededLibs.count > 0 && !opts.compileOnly)
            ? linkX86_64Dynamic(argv0, opts, tmpAsm, opts.outputPath, neededLibs)
            : x86Exe
            ? linkX86_64Executable(argv0, opts, tmpAsm, opts.outputPath)
            // `-A android --emit-lib` used to land HERE, because android rides
            // the arm64 back end and the android branch lives inside
            // linkArm64Executable — which this arm goes around. The result was
            // a Mach-O dylib written to a `.so`, for a target that cannot load
            // one: silently the wrong FORMAT, which nothing downstream would
            // have told you either. A loud refusal until the real thing exists
            // (an android .so is its own link: no glue, no crt, exported API,
            // soname + the base DT_NEEDED set).
            : (opts.androidTarget && opts.emitLib && !opts.compileOnly)
            ? linkAndroidShared(argv0, opts, tmpAsm, opts.outputPath)
            : (opts.useArm64Backend && opts.emitLib && !opts.compileOnly)
            ? linkArm64Shared(argv0, opts, tmpAsm, opts.outputPath, ifaceJson, neededLibs)
            : linkArm64Executable(argv0, opts, tmpAsm, opts.outputPath, neededLibs);
        if (!opts.verbose) [[NSFileManager defaultManager] removeItemAtPath:tmpAsm error:NULL];
        return linkRc < 0 ? 1 : linkRc;
    }
    return cgRc < 0 ? 1 : cgRc;
}

int main(int argc, const char *argv[]) {
    @autoreleasepool {
    // Record argv[0] so the support tree is found relative to THIS binary —
    // an installed compiler must not need the current directory to locate
    // its own libraries.
    [XTCommandLineOptions setExecutablePath:argv[0]];
        for (int i = 1; i < argc; i++) {
            if (strcmp(argv[i], "-v") == 0 || strcmp(argv[i], "--version") == 0) {
                // The build identity, not just the release number. "Is the
                // fix in this install?" was otherwise only answerable by
                // running a repro against it.
                printf("xcc %s (%s, %s)\n", XTC_VERSION, XTC_BUILD_ID, XTC_BUILD_DATE);
                return 0;
            }
        }

        XTCommandLineOptions *opts = [XTCommandLineOptions parseArgc:argc argv:argv];
        if (!opts) return 1;

        // arm9 links against a device sysroot that lives in ANOTHER repo, so it
        // is vendored into the install (lib/xc/arm9-sysroot) and added here as
        // a default -L. Without it arm9 would be the one target that needs an
        // extra flag to build a simple program. An explicit -L still wins: this
        // is appended, so it is only consulted after the user's own paths.
        if (opts.useArm9Backend) {
            NSString *sup = [XTCommandLineOptions resolveSupportRoot:opts.xtcHome];
            NSString *vend = [sup stringByAppendingPathComponent:@"arm9-sysroot"];
            BOOL isDir = NO;
            if (sup && [[NSFileManager defaultManager] fileExistsAtPath:vend
                                                           isDirectory:&isDir] && isDir)
                [opts addLibraryPath:vend];
        }

        if (opts.dumpLayout) {
            XTMemoryModel *m = opts.memoryModel;
            if (!m) {
                fprintf(stderr, "xcc: error: --dump-layout requires -m <model>\n");
                return 1;
            }
            printf("%s", m.generateMemoryMapDiagram.UTF8String);
            return 0;
        }

        // The IR pipeline is the only path: xtc is a thin dispatcher that
        // runs xtc-fe (→ IR text) then xtcg-<arch> (→ asm/xex), with an arm64
        // executable finished by clang. (The legacy AST codegen was retired —
        // the IR backend strictly outperformed it on every measured 6502
        // program and is the sole arm64 backend.)
        return dispatchIRPipeline(argv[0], opts);
    }
}
