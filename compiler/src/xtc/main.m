// Program-specific ARC/heap allocators for the arm9 target, synthesised from the
// `_xtc_new_<T>` symbols the generated asm references (the A32 analogue of the
// arm64 path above). Differences from arm64: ELF symbols are BARE (the C name
// `_xtc_new_X` is the symbol — no Mach-O `_` prefix, so the asm/regex use a
// single underscore), and the object header uses 4-byte fields:
//   [stride:u32 @0][count:u32 @4][dealloc-fnptr:u32 @8][pad @12][refcount:u16 @14]
// The returned object pointer is base+16, so the refcount sits at obj-2 (matching
// the backend's ldrh/strh [obj,#-2]) and dealloc recovers base = obj-16.
// The program-independent runtime (putc/float/math/syscalls) lives in
// support/arm9/runtime/libxt.c; only these per-program allocators are generated.
static NSString *arm9StubSource(NSString *asmText, BOOL forLibrary) {
    NSMutableString *s = [NSMutableString stringWithString:
        @"#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n"];
    // A program's real `main` lives here, so the two arguments the loader
    // passes can be recorded for Process.xc before the xtc entry runs. A
    // library has no entry point and gets neither.
    if (!forLibrary) {
        [s appendString:
            @"extern int xt_main(void);\n"
            "void _xt_capture_args(int,char**);\n"
            "int main(int argc, char **argv){ _xt_capture_args(argc, argv); return xt_main(); }\n"];
    }
    if (!asmText) return s;

    // `.length` of a runtime-sized heap array (private:docs/bugs/045): count from the
    // 24-byte header (u32 at payload-16, matching Runtime.xc on the device).
    if ([asmText containsString:@"_xtc_count"]) {
        [s appendString:
            @"uint32_t _xtc_count(void*o){return *(uint32_t*)((uint8_t*)o-16);}\n"];
    }
    NSRegularExpression *re = [NSRegularExpression
        regularExpressionWithPattern:@"\\b_xtc_new_([A-Za-z_][A-Za-z0-9_]*)" options:0 error:NULL];
    NSMutableSet<NSString *> *seen = [NSMutableSet set];
    for (NSTextCheckingResult *m in [re matchesInString:asmText options:0
                                                  range:NSMakeRange(0, asmText.length)]) {
        NSString *suffix = [asmText substringWithRange:[m rangeAtIndex:1]];
        if ([seen containsObject:suffix]) continue;
        [seen addObject:suffix];
        if (XTIRIsPrimitiveElemName(suffix)) {
            // Primitive element array: single `count` arg, no per-element dealloc.
            // Over-allocate (count*8) — always ≥ the A32-native element size.
            [s appendFormat:
                @"void *_xtc_new_%@(unsigned long n){unsigned long b=n*8; if(b<256)b=256;"
                @"uint8_t*p=(uint8_t*)calloc(1,b+24);"
                @"if(!p){fprintf(stderr,\"xcc: out of memory (%%lu elements)\\n\",n);abort();}"
                @"*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=8;*(uint32_t*)(p+8)=(uint32_t)n;"
                @"*(void(**)(void*))(p+12)=0;*(void**)(p+16)=0;*(uint16_t*)(p+22)=1;return p+24;}\n", suffix];
            continue;
        }
        BOOL hasDealloc = [asmText containsString:
            [NSString stringWithFormat:@"%@$dealloc:", suffix]];
        [s appendFormat:
            @"%@"
            @"void *_xtc_new_%@(unsigned long count,unsigned long stride){if(count<1)count=1;"
            @"unsigned long b=count*stride; if(b<256)b=256;"
            @"uint8_t*p=(uint8_t*)calloc(1,b+24);"
            @"if(!p){fprintf(stderr,\"xcc: out of memory (%%lu x %%lu bytes)\\n\",count,stride);abort();}"
            @"*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=(uint32_t)stride;*(uint32_t*)(p+8)=(uint32_t)count;"
            @"*(void(**)(void*))(p+12)=%@;*(void**)(p+16)=0;*(uint16_t*)(p+22)=1;return p+24;}\n",
            hasDealloc ? [NSString stringWithFormat:@"extern void %@$dealloc(void*);\n", suffix] : @"",
            suffix,
            hasDealloc ? [NSString stringWithFormat:@"(void(*)(void*))&%@$dealloc", suffix] : @"0"];
    }

    // B1: the single generic class allocator. `new T` lowers to
    // `_xtc_alloc(count, stride, &T$dealloc)` (dealloc null when the class has
    // none), so one allocator serves every class — the per-class `_xtc_new_<T>`
    // above is now only emitted for primitive-element arrays. Same header layout
    // the per-class version wrote, with the dealloc fnptr taken as an argument.
    if ([asmText containsString:@"_xtc_alloc"]) {
        [s appendString:
            @"void *_xtc_alloc(unsigned long count,unsigned long stride,void(*dealloc)(void*)){"
            @"if(count<1)count=1;unsigned long b=count*stride; if(b<256)b=256;"
            @"uint8_t*p=(uint8_t*)calloc(1,b+24);"
            @"if(!p){fprintf(stderr,\"xcc: out of memory (%lu x %lu bytes)\\n\",count,stride);abort();}"
            @"*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=(uint32_t)stride;*(uint32_t*)(p+8)=(uint32_t)count;"
            @"*(void(**)(void*))(p+12)=dealloc;*(void**)(p+16)=0;*(uint16_t*)(p+22)=1;return p+24;}\n"];
    }
    // ALWAYS on, for the three backends that can be linked as multiple modules.
    // The lazy-link gate used to ask "does MY module reference _xtc_weak_*?" — but
    // that is the wrong question. A LIBRARY can register a weak reference to an
    // object the APPLICATION allocated (`b.setAction(&obj.method)` — the slot lives
    // in the lib, the object in the app), and then the app's _xtc_dealloc, seeing no
    // weak use of its own, would free the object WITHOUT zeroing the lib's slot,
    // leaving it dangling. The only thing that knows whether an object is weakly
    // referenced is the object's own header, so every dealloc must ask it.
    //
    // The cost is one null test per dealloc (weak_head == 0 for the overwhelming
    // majority of objects) plus ~40 lines of runtime the linker keeps. On a hosted
    // target that is nothing. The 6502's gate stays as it is — it has no dynamic
    // linking, so its module IS the whole program, and there the saving is real.
    BOOL usesWeak = YES;
    if ([asmText containsString:@"_xtc_dealloc"]) {
        if (usesWeak) [s appendString:@"void _xtc_weak_zero_for(void*);\n"];
        [s appendString:@"void _xtc_dealloc(void *o){"];
        if (usesWeak) [s appendString:@"_xtc_weak_zero_for(o);"];
        [s appendString:
            @"uint8_t*base=(uint8_t*)o-24;"
            @"unsigned long stride=*(uint32_t*)(base+4);unsigned long count=*(uint32_t*)(base+8);"
            @"void(*d)(void*)=*(void(**)(void*))(base+12);"
            // Non-re-entrant: bump the refcount (u16 @ obj-2) to a high sentinel
            // before running dealloc, so a balanced retain/release inside the body
            // (the self-retain bracket a method keeps around an opaque call) can't
            // fall back to 0 and re-dispatch dealloc on the object being freed.
            @"if(d){*(unsigned short*)((uint8_t*)o-2)=0x8000u;"
            @"for(unsigned long i=0;i<count;i++)d((uint8_t*)o+i*stride);}free(base);}\n"];
    }
    if (usesWeak) {
        [s appendString:
            // Intrusive doubly-linked list — no table, no cap, no scan.
            // slot[-2]=pprev  slot[-1]=next  slot[0]=referent; head at obj-8.
            // `pprev` is the ADDRESS OF THE POINTER THAT POINTS AT THIS SLOT (the
            // Linux hlist idiom): unlink is O(1) and never needs the object — which
            // matters, because a WIDENED `^` holds a FUNCTION pointer in its
            // referent word, so recovering the object by reading *slot would
            // dereference `.text` as a header. It also makes `pprev != 0` an
            // unambiguous "am I linked?" test.
            @"#define _XT_WH(o) (*(void***)((uint8_t*)(o)-8))\n"
            @"void _xtc_weak_unregister(void **slot){"
            @"void ***pp=(void***)slot[-2]; if(!pp) return;"
            @"void **nx=(void**)slot[-1];"
            @"*pp=nx; if(nx) nx[-2]=(void*)pp;"
            @"slot[-2]=0; slot[-1]=0;}\n"
            @"void _xtc_weak_register(void **slot,void *obj){"
            @"_xtc_weak_unregister(slot);"
            @"if(!obj) return;"
            // NOT-AN-OBJECT GUARD. `obj` here is the RECV word of a `^`, and for a
            // WIDENED `^` that word is a FUNCTION POINTER, not an object. The IR
            // emits a compare against __bm_tramp_<sig> to catch that — but a .so
            // has its OWN copy of the trampoline, and the loader binds a defined
            // symbol to the module that defines it (no interposition), so a `^`
            // widened in the app and stored by the library FAILS the library's
            // compare. We would then take the app's function pointer for an object
            // and write the chain head to *(void***)(fn - N) — into .text. That is
            // a real DATA-ABORT, reproduced on the XTOS loader, not a theory.
            //
            // The magic makes the test value-based instead of address-based, so it
            // cannot be fooled by a foreign module's trampoline, a stale `^`, or
            // any other non-object. Failing it means "not one of ours" — skip.
            @"if(*(uint32_t*)((uint8_t*)obj-24)!=0x58544F42U) return;"
            @"void **nx=_XT_WH(obj);"
            @"slot[-2]=(void*)&_XT_WH(obj); slot[-1]=(void*)nx;"
            @"if(nx) nx[-2]=(void*)&slot[-1];"
            @"_XT_WH(obj)=slot;}\n"
            @"void *_xtc_weak_load(void **slot){return *slot;}\n"
            @"void _xtc_weak_zero_for(void *obj){if(!obj)return;"
            @"void **s=_XT_WH(obj);"
            @"while(s){void **nx=(void**)s[-1];"
            @"*s=0; s[-2]=0; s[-1]=0; s=nx;}"
            @"_XT_WH(obj)=0;}\n"];
    }
    // bank(type, idx) → a lazily-allocated, zeroed 12 KB region per (type, idx).
    // On the 6502 these are real bank-switched windows; on a flat target (arm9,
    // like arm64) the builtin degrades to plain backing memory so raw:u8@ round
    // trips work. Without this, `bl _xtc_bank` was an undefined symbol and the
    // loader refused to run the program.
    if ([asmText containsString:@"_xtc_bank"]) {
        [s appendString:
            @"static void *_xtc_bank_regions[3][256]={{0}};\n"
            @"void *_xtc_bank(uint8_t type,uint8_t idx){if(type>1)return 0;"
            @"if(!_xtc_bank_regions[type][idx])_xtc_bank_regions[type][idx]=calloc(1,12288);"
            @"return _xtc_bank_regions[type][idx];}\n"];
    }
    return s;
}

// Program-specific ARC/heap allocators for the x86-64 (musl, ELF) target. Like
// arm9: BARE ELF symbols (single `_`), a 16-byte object header with 4-byte fields
//   [stride:u32 @0][count:u32 @4][dealloc-fnptr:u32 @8][pad][refcount:u16 @14]
// object pointer = base+16, refcount at obj-2 (the backend's inline ARC). The host
// is 64-bit, so the dealloc fn pointer is written/read as an explicit uint32_t (a
// static non-PIE ELF lives in the low 4 GB, so 32 bits hold the code address).
static NSString *x86_64StubSource(NSString *asmText, NSString *supportRoot) {
    NSMutableString *s = [NSMutableString stringWithString:
        @"#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n"];
    // Threading (private:docs/Design/threading.md Phase 2). Both toolchains that use
    // this stub have a real libc — musl on Linux, mingw on Windows — so they get
    // the same pthreads/Win32 bodies macOS does, from the same file, rather than
    // a third copy of the contract. The FREESTANDING x86-64 paths (the in-house
    // linker's static ELF and PE) have no libc and carry their own in
    // rt-freestanding.c. Included by absolute path because the stub is generated
    // into a temp directory.
    if (supportRoot.length) {
        // ABSOLUTE: the stub is compiled from a temp directory, so a support
        // root that resolved relatively ("./support", the dev-tree case) would
        // be looked up beside the stub and not found.
        NSString *root = supportRoot.isAbsolutePath ? supportRoot
            : [[[NSFileManager defaultManager] currentDirectoryPath]
                  stringByAppendingPathComponent:supportRoot];
        [s appendFormat:@"#include \"%@/generic/runtime/xt-threads.c\"\n",
                        root.stringByStandardizingPath];
    }
    if (!asmText) return s;

    // On Windows the C runtime opens stdout/stderr in TEXT mode, so a raw
    // write() of '\n' is expanded to "\r\n". xtc's Stdio emits bytes literally
    // (write(1,&b,1)), so force binary mode before main runs to keep output
    // byte-identical to the other backends. `#ifdef _WIN32` fires only when the
    // stub is compiled by the mingw toolchain (win64); the musl/Linux build
    // skips it. A constructor runs it ahead of main without touching codegen.
    [s appendString:
        @"#ifdef _WIN32\n#include <fcntl.h>\n#include <io.h>\n"
        @"__attribute__((constructor)) static void _xtc_stdio_binary(void){"
        @"_setmode(1,_O_BINARY);_setmode(2,_O_BINARY);}\n#endif\n"];

    // XG-NIB load-time factory registration on win64. The other targets emit a
    // pointer to `_xtc_nib_register` into their constructor list directly
    // (Mach-O __mod_init_func / ELF .init_array), but a hand-emitted PE
    // .CRT$XCU entry is dead-stripped by this toolchain's linker. The stub is
    // compiled by the mingw C compiler, whose `__attribute__((constructor))`
    // DOES land in the CRT's _initterm range — so run the registrar from here
    // instead, only when the program actually defines one. `#ifdef _WIN32`
    // keeps it off the Linux build (which uses .init_array).
    if ([asmText containsString:@"_xtc_nib_register"]) {
        [s appendString:
            @"#ifdef _WIN32\nextern void _xtc_nib_register(void);\n"
            @"__attribute__((constructor)) static void _xtc_nib_register_ctor(void){"
            @"_xtc_nib_register();}\n#endif\n"];
    }

    // POSIX random()/srandom() are in musl (Linux) but not mingw (Windows). The
    // Math library calls them directly for its PRNG. Provide a 31-bit LCG on
    // Windows only — the corpus's rand fixtures test value RANGES, not an exact
    // sequence, so any correct generator satisfies them.
    if ([asmText containsString:@"random"]) {
        [s appendString:
            @"#ifdef _WIN32\n"
            @"static unsigned long long _xt_rng=1ULL;\n"
            @"void srandom(unsigned s){_xt_rng=s?s:1ULL;}\n"
            @"int random(void){_xt_rng=_xt_rng*6364136223846793005ULL+1442695040888963407ULL;"
            @"return (int)((_xt_rng>>33)&0x7fffffffU);}\n"
            @"#endif\n"];
    }

    // Time primitives, same standardized names arm64's libxt.c and arm9's libxt-pic.c
    // export. Without them x86_64 had no Time.xc at all — so `#import "Time.xc"` failed
    // outright, taking `ahl` and `time_elapsed` with it, and Math came in transitively
    // through Time so anything importing Time lost Math too.
    if ([asmText containsString:@"_xt_clk_"]) {
        [s appendString:
            @"#include <time.h>\n"
            @"static double xt_clk_origin;\n"
            @"static double xt_now_secs(void){struct timespec ts;"
            @"clock_gettime(CLOCK_MONOTONIC,&ts);"
            @"return (double)ts.tv_sec+(double)ts.tv_nsec*1e-9;}\n"
            @"void _xt_clk_reset(void){xt_clk_origin=xt_now_secs();}\n"
            // microseconds since the reset; wraps after ~71 min, exactly as on arm64.
            @"uint32_t _xt_clk_ticks(void){return (uint32_t)((xt_now_secs()-xt_clk_origin)*1.0e6);}\n"
            @"void _xt_clk_delay(uint32_t jiffies){double sec=(double)jiffies/60.0;"
            @"struct timespec req;req.tv_sec=(time_t)sec;"
            @"req.tv_nsec=(long)((sec-(double)req.tv_sec)*1.0e9);"
            @"nanosleep(&req,(struct timespec *)0);}\n"];
    }
    // `.length` of a runtime-sized heap array (private:docs/bugs/045): count from the
    // 30-byte header (u32 at payload-22). Serves the musl AND mingw links.
    if ([asmText containsString:@"_xtc_count"]) {
        [s appendString:
            @"uint32_t _xtc_count(void*o){return *(uint32_t*)((uint8_t*)o-22);}\n"];
    }
    // The list lives in XTIRElemKind.h and nowhere else. Four private copies
    // had grown beside it, all missing i64/u64, which is how bug 233 reached
    // three different stub generators at once.
    NSRegularExpression *re = [NSRegularExpression
        regularExpressionWithPattern:@"\\b_xtc_new_([A-Za-z_][A-Za-z0-9_]*)" options:0 error:NULL];
    NSMutableSet<NSString *> *seen = [NSMutableSet set];
    for (NSTextCheckingResult *m in [re matchesInString:asmText options:0
                                                  range:NSMakeRange(0, asmText.length)]) {
        NSString *suffix = [asmText substringWithRange:[m rangeAtIndex:1]];
        if ([seen containsObject:suffix]) continue;
        [seen addObject:suffix];
        if (XTIRIsPrimitiveElemName(suffix)) {
            [s appendFormat:
                @"void *_xtc_new_%@(unsigned long n){unsigned long b=n*8; if(b<256)b=256;"
                @"uint8_t*p=(uint8_t*)calloc(1,b+30);*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=8;*(uint32_t*)(p+8)=(uint32_t)n;"
                @"*(void**)(p+12)=0;*(void**)(p+20)=0;*(uint16_t*)(p+28)=1;return p+30;}\n", suffix];
            continue;
        }
        BOOL hasDealloc = [asmText containsString:[NSString stringWithFormat:@"%@$dealloc:", suffix]];
        [s appendFormat:
            @"%@"
            @"void *_xtc_new_%@(unsigned long count,unsigned long stride){if(count<1)count=1;"
            @"unsigned long b=count*stride; if(b<256)b=256;"
            @"uint8_t*p=(uint8_t*)calloc(1,b+30);*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=(uint32_t)stride;*(uint32_t*)(p+8)=(uint32_t)count;"
            @"*(void(**)(void*))(p+12)=%@;*(void**)(p+20)=0;*(uint16_t*)(p+28)=1;return p+30;}\n",
            hasDealloc ? [NSString stringWithFormat:@"extern void %@$dealloc(void*);\n", suffix] : @"",
            suffix,
            hasDealloc ? [NSString stringWithFormat:@"&%@$dealloc", suffix] : @"0"];
    }
    if ([asmText containsString:@"_xtc_alloc"]) {
        [s appendString:
            @"void *_xtc_alloc(unsigned long count,unsigned long stride,void(*dealloc)(void*)){"
            @"if(count<1)count=1;unsigned long b=count*stride; if(b<256)b=256;"
            @"uint8_t*p=(uint8_t*)calloc(1,b+30);*(uint32_t*)(p+0)=0x58544F42U;*(uint32_t*)(p+4)=(uint32_t)stride;*(uint32_t*)(p+8)=(uint32_t)count;"
            @"*(void(**)(void*))(p+12)=dealloc;*(void**)(p+20)=0;*(uint16_t*)(p+28)=1;return p+30;}\n"];
    }
    // ALWAYS on, for the three backends that can be linked as multiple modules.
    // The lazy-link gate used to ask "does MY module reference _xtc_weak_*?" — but
