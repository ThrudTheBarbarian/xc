/****************************************************************************\
|* A per-invocation temp DIRECTORY, so the files inside it can have stable
|* BASENAMES.
|*
|* This matters because a temp file's basename can end up inside the artefact:
|* gcc/gas record a compiled source as an STT_FILE symbol in .symtab, so a stub
|* named `xtc-arm9-pic-stub-<pid>.c` made every .so we emit differ from build to
|* build. Uniqueness has to live SOMEWHERE, but it belongs in the directory (which
|* nothing records) rather than the filename (which does).
\****************************************************************************/
static NSString *xtcTempDir(void) {
    static NSString *dir = nil;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        // globallyUniqueString is portable (macOS / GNUstep / Windows) and
        // already carries the pid plus a unique counter — no arc4random (absent
        // on Windows) needed.
        NSString *t = [NSTemporaryDirectory() stringByAppendingPathComponent:
            [@"xtc-" stringByAppendingString:
                [[NSProcessInfo processInfo] globallyUniqueString]]];
        [[NSFileManager defaultManager] createDirectoryAtPath:t
                                  withIntermediateDirectories:YES
                                                   attributes:nil error:NULL];
        dir = t;
    });
    return dir;
}

