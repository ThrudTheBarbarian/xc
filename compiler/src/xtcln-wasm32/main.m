                   // Whatever clock id is asked for, this answers with a
                   // MONOTONIC reading: performance.now() is monotonic, which is
                   // what every caller of this actually wants, and wasm has no
                   // wall clock to offer anyway. The DataView is re-derived per
                   // call because memory.grow detaches the buffer.
                   //
                   // Without it any program that timed itself — every benchmark
                   // in benchmark/src — died on `missing host import
                   // env.clock_gettime` before printing a line.
                   "    clock_gettime: (clk, ts) => {\n"
                   "      const ns = BigInt(Math.round(performance.now() * 1e6));\n"
                   "      const dv = new DataView(XCC.memory.buffer);\n"
                   "      dv.setBigInt64(ts, ns / 1000000000n, true);\n"
                   "      dv.setBigInt64(ts + 8, ns % 1000000000n, true);\n"
                   "      return 0;\n"
                   "    },\n"
                   "  };\n"
                   "  if (isWorker && ringI32) {\n"
                   "    const ri = ringI32;\n"
                   "    // The blocking primitives (XG-WEB-BACKEND sec 3): the worker CAN block.\n"
                   "    // memory views are re-derived per call — memory.grow detaches buffers.\n"
                   "    Object.assign(base, {\n"
                   "      _xt_ring_wait: (timeoutMs) => {\n"
                   "        const w = Atomics.load(ri, 0);\n"
                   "        if (Atomics.load(ri, 1) < w) return 1;\n"
                   "        const r = Atomics.wait(ri, 0, w, timeoutMs < 0 ? Infinity : timeoutMs);\n"
                   "        return r === \"timed-out\" ? 0 : 1;\n"
                   "      },\n"
                   "      _xt_ring_read: (ptr) => {\n"
                   "        const r = Atomics.load(ri, 1);\n"
                   "        if (r >= Atomics.load(ri, 0)) return -1;\n"
                   "        const cap = (ri.length - 8) >> 3;\n"
                   "        const s = 8 + (r % cap) * 8;\n"
                   "        const m = new Int32Array(XCC.memory.buffer);\n"
                   "        for (let k = 0; k < 8; k++) m[(ptr >> 2) + k] = ri[s + k];\n"
                   "        Atomics.store(ri, 1, r + 1);\n"
                   "        return ri[s];\n"
                   "      },\n"
                   "      _xt_req_block: (kind, a, b, c) => {\n"
                   "        const seq = ++reqSeq;\n"
                   "        self.postMessage({ xccReq: { seq, kind, a, b, c } });\n"
                   "        for (;;) {\n"
                   "          const cur = Atomics.load(ri, 2);\n"
                   "          if (cur === seq) break;\n"
                   "          Atomics.wait(ri, 2, cur);\n"
                   "        }\n"
                   "        return Atomics.load(ri, 3);\n"
                   "      },\n"
                   "    });\n"
                   "  }\n"
                   "  // Host-supplied packages (#package <name>): set globalThis.xccImports =\n"
                   "  // { pkgName: { fn: ... }, env: { overrides } } BEFORE this script runs\n"
                   "  // (in worker mode: inside cfg.workerScript, which runs in the WORKER).\n"
                   "  const extra = globalThis.xccImports || {};\n"
                   "  if (extra.env) Object.assign(base, extra.env);\n"
                   "  const env = new Proxy(base, {\n"
                   "    get(t, name) {\n"
                   "      if (name in t) return t[name];\n"
                   "      return () => { throw new Error(`missing host import env.${String(name)}`); };\n"
                   "    },\n"
                   "  });\n"
                   "  const imports = Object.assign({}, extra, { env });\n"
                   "  // The `browser` package (wasm32 Platform.xc, #package browser): default\n"
                   "  // implementations live IN the loader so an app ships with no side files;\n"
                   "  // any key the page sets in xccImports.browser overrides one of these. An\n"
                   "  // imports entry for a package the module never asks for is ignored, so\n"
                   "  // this costs a Browser-free module nothing.\n"
                   "  const bdec = new TextDecoder();\n"
                   "  const bmem = () => new Uint8Array(XCC.memory.buffer);\n"
                   "  const bstr = (p, n) => bdec.decode(bmem().subarray(p, p + n));\n"
                   "  imports.browser = Object.assign({\n"
                   "    _b_fetch(tok, url, n) {\n"
                   "      const u = bstr(url, n);            // decode BEFORE awaiting: the\n"
                   "      Promise.resolve()                  //   pointer dies when this returns\n"
                   "        .then(() => fetch(u))\n"
                   "        .then(r => r.arrayBuffer().then(buf => {\n"
                   "          const b = new Uint8Array(buf);\n"
                   "          const e = XCC.instance.exports;\n"
                   "          const p = e._xt_browser_alloc(b.length);\n"
                   "          bmem().set(b, p);              // re-derive: alloc may grow memory\n"
                   "          e._xt_browser_dispatch(tok, r.status, p, b.length);\n"
                   "        }))\n"
                   "        .catch(() => XCC.instance.exports._xt_browser_dispatch(tok, 0, 0, 0));\n"
                   "    },\n"
                   "    _b_inject(sp, sn, hp, hn) {\n"
                   "      if (typeof document === \"undefined\") return;\n"
                   "      const el = document.querySelector(bstr(sp, sn));\n"
                   "      if (el) el.innerHTML = bstr(hp, hn);\n"
                   "    },\n"
                   "    _b_push_state(p, n) {\n"
                   "      if (typeof history !== \"undefined\") history.pushState(null, \"\", bstr(p, n));\n"
                   "    },\n"
                   "    _b_log(lvl, p, n) {\n"
                   "      (lvl >= 2 ? console.error : lvl === 1 ? console.warn : console.log)(bstr(p, n));\n"
                   "    },\n"
                   "  }, extra.browser || {});\n"
                   "  // Imported xtc libraries (W2): each dep package is satisfied by LAZY\n"
                   "  // thunks so the app can instantiate FIRST (it owns memory + table); the\n"
                   "  // thunks resolve once the dep's exports exist.\n"
                   "  const deps = __DEPS__;\n"
                   "  const depExports = {};\n"
                   "  for (const d of deps)\n"
                   "    imports[d] = new Proxy({}, { get: (t, n) => (...a) => depExports[d][n](...a) });\n"
                   "  let bytes;\n"
                   "  if (isNode) {\n"
                   "    const path = require(\"path\").join(__dirname, \"__BASE__.wasm\");\n"
                   "    bytes = require(\"fs\").readFileSync(path);\n"
                   "  } else {\n"
                   "    bytes = await (await fetch(\"__BASE__.wasm\")).arrayBuffer();\n"
                   "  }\n"
                   "  const { instance } = await WebAssembly.instantiate(bytes, imports);\n"
                   "  // A per-module handle. This used to be ONLY `globalThis.xcc`, so loading a\n"
                   "  // second independent module clobbered the first — and the clobber was not\n"
                   "  // cosmetic: the callbacks below read `XCC.memory`, so module A's\n"
                   "  // browser dispatch would start reading module B's memory. That is the\n"
                   "  // shared-NOTHING model (a group loading its own module on demand), where two\n"
                   "  // unrelated modules must coexist in one realm.\n"
                   "  //\n"
                   "  // `globalThis.xcc` still points at the most recent module, because callers\n"
                   "  // rely on it; `globalThis.xccModules[<base>]` is the stable per-module one,\n"
                   "  // and everything INSIDE this loader now closes over XCC instead.\n"
                   "  XCC = { instance, memory: instance.exports.memory };\n"
                   "  globalThis.xcc = XCC;\n"
                   "  (globalThis.xccModules || (globalThis.xccModules = {}))[\"__BASE__\"] = XCC;\n"
                   "  // Instantiate each dep: data goes BETWEEN the app's static data and the\n"
                   "  // 1 MiB heap base (so the ARC \"is this a heap object\" compare stays a\n"
                   "  // single guard — library statics must NOT read as heap objects), funcs\n"
                   "  // go at the grown end of the app's one table, env is thunked to the\n"
                   "  // app's exported runtime, and the dep's reloc-apply patches the vtable\n"
                   "  // words a data segment cannot compute. __stack_low is raised past the\n"
                   "  // last dep so the shadow stack cannot grow down into library data.\n"
                   "  let dcur = deps.length ? instance.exports.__data_end.value : 0;\n"
                   "  for (const d of deps) {\n"
                   "    let dbytes, dmeta;\n"
                   "    if (isNode) {\n"
                   "      const p = require(\"path\"), f = require(\"fs\");\n"
                   "      dbytes = f.readFileSync(p.join(__dirname, `lib${d}.wasm`));\n"
                   "      dmeta = JSON.parse(f.readFileSync(p.join(__dirname, `lib${d}.json`), \"utf8\"));\n"
                   "    } else {\n"
                   "      dbytes = await (await fetch(`lib${d}.wasm`)).arrayBuffer();\n"
                   "      dmeta = await (await fetch(`lib${d}.json`)).json();\n"
                   "    }\n"
                   "    const dbase = (dcur + 15) & ~15;\n"
                   "    if (dbase < 0x10000) throw new Error(`xcc: lib${d} data base ${dbase} below 0x10000 (classid guard)`);\n"
                   "    if (dbase + dmeta.dataSize > 0x100000)\n"
                   "      throw new Error(`xcc: lib${d} data (${dmeta.dataSize} bytes at ${dbase}) overflows the pre-heap region`);\n"
                   "    const dtable = instance.exports.__indirect_function_table;\n"
                   "    const dtbase = dmeta.tableSize ? dtable.grow(dmeta.tableSize) : dtable.length;\n"
                   "    const denvBase = {\n"
                   "      memory: instance.exports.memory,\n"
                   "      __indirect_function_table: dtable,\n"
                   "      __memory_base: dbase, __table_base: dtbase,\n"
                   "      __sp: instance.exports.__sp, __stack_low: instance.exports.__stack_low,\n"
                   "    };\n"
                   "    const denv = new Proxy(denvBase, {\n"
                   "      get(t, n) {\n"
                   "        if (n in t) return t[n];\n"
                   "        if (n in instance.exports) return instance.exports[n];\n"
                   "        if (n in base) return base[n];\n"
                   "        return () => { throw new Error(`missing library import env.${String(n)} (lib${d})`); };\n"
                   "      },\n"
                   "    });\n"
                   "    // Start from the APP's import object, not just `extra`. The loader builds\n"
                   "    // the `browser` package itself (default implementations ship inside it), and\n"
                   "    // passing only the host-supplied `xccImports` meant a library using\n"
                   "    // `#package browser` died at instantiation with \"Import #8 browser: module\n"
                   "    // is not an object or function\" until the caller re-supplied it by hand.\n"
                   "    // env is the one entry that must be the DEP's thunked version.\n"
                   "    // A library that subclasses another library's class imports that\n"
                   "    // library's methods (into its own table slots) and __addr_ getters (for\n"
                   "    // its vtable words). A dep already instantiated is passed as its real\n"
                   "    // exports, so those table slots hold its wasm functions directly.\n"
                   "    const dimp = Object.assign({}, imports, { env: denv });\n"
                   "    for (const o of deps) if (o !== d) dimp[o] = depExports[o] || imports[o];\n"
                   "    const di = await WebAssembly.instantiate(dbytes, dimp);\n"
                   "    depExports[d] = di.instance.exports;\n"
                   "    dcur = dbase + dmeta.dataSize;\n"
                   "  }\n"
                   "  // Relocate after every dep exists: a library's vtable words can name\n"
                   "  // another library's data, read through that library's __addr_ getter.\n"
                   "  for (const d of deps) depExports[d].__wasm_apply_relocs();\n"
                   "  if (deps.length) instance.exports.__stack_low.value = (dcur + 15) & ~15;\n"
                   "  const rc = instance.exports.main();\n"
                   "  flush();\n"
                   "  if (isNode) process.exitCode = rc | 0;\n"
                   "  else if (isWorker) self.postMessage({ xccExit: rc | 0 });\n"
                   "  else if (rc) console.warn(`main() returned ${rc}`);\n"
                   "})().catch((e) => {\n"
                   "  const isNode = typeof process !== \"undefined\" && !!(process.versions && process.versions.node);\n"
                   "  if (isNode) { console.error(e); process.exitCode = 70; } else { console.error(e); }\n"
                   "});\n";
    t = [t stringByReplacingOccurrencesOfString:@"__BASE__" withString:baseName];
    NSMutableArray<NSString*>* quoted = [NSMutableArray array];
    for (NSString* d in deps)
        [quoted addObject:[NSString stringWithFormat:@"\"%@\"", d]];
    return [t stringByReplacingOccurrencesOfString:@"__DEPS__"
                                        withString:[NSString stringWithFormat:@"[%@]",
                                                                              [quoted componentsJoinedByString:@", "]]];
    }

// A starter page: stdout into a <pre> via the loader's xccOut hook. Written
// only when absent — customised pages must survive a rebuild (the .js and
// .wasm regenerate every build; the page is the user's).
static NSString* starterHTML(NSString* baseName)
    {
    return [NSString stringWithFormat:
                         @"<!doctype html>\n"
                         @"<!-- Generated once by xcc-ln-wasm32 for %@.wasm — edit freely; a rebuild\n"
                         @"     rewrites %@.js and %@.wasm but leaves this page alone. -->\n"
                         @"<html lang=\"en\">\n"
                         @"<head>\n"
                         @"<meta charset=\"utf-8\">\n"
                         @"<title>%@</title>\n"
                         @"<style>\n"
                         @"  body { background: #1e1e1e; color: #d4d4d4; font: 14px/1.5 ui-monospace, monospace;\n"
                         @"         margin: 2rem; }\n"
                         @"  pre  { white-space: pre-wrap; }\n"
                         @"</style>\n"
                         @"</head>\n"
                         @"<body>\n"
                         @"<h1>%@</h1>\n"
                         @"<pre id=\"out\"></pre>\n"
                         @"<script>\n"
                         @"  const out = document.getElementById(\"out\");\n"
                         @"  globalThis.xccOut = (line) => { out.textContent += line + \"\\n\"; };\n"
                         @"  // Host packages (#package): define before the loader runs, e.g.\n"
                         @"  // globalThis.xccImports = { js: { jsPing: (v) => console.log(v) } };\n"
                         @"</script>\n"
                         @"<script src=\"%@.js\"></script>\n"
                         @"</body>\n"
                         @"</html>\n",
                         baseName, baseName, baseName, baseName, baseName, baseName];
    }

int main(int argc, const char* argv[])
    {
    @autoreleasepool
        {
        NSString *inPath = nil, *outBase = nil, *ifacePath = nil;
        NSMutableArray<NSString*>* deps = [NSMutableArray array];
        BOOL quiet = NO, emitLib = NO;
        for (int i = 1; i < argc; i++)
            {
            NSString* a = @(argv[i]);
            if ([a isEqualToString:@"-v"] || [a isEqualToString:@"--version"])
                {
                printf("xcc-ln-wasm32 %s\n", XTC_VERSION);
                return 0;
                }
            else if ([a isEqualToString:@"-q"])
                {
                quiet = YES;
                }
            else if ([a isEqualToString:@"--emit-lib"])
                {
                emitLib = YES;
                }
            else if ([a isEqualToString:@"--iface"] && i + 1 < argc)
                {
                ifacePath = @(argv[++i]);
                }
            else if ([a isEqualToString:@"--dep"] && i + 1 < argc)
                {
                [deps addObject:@(argv[++i])];
                }
            else if (!inPath)
                {
                inPath = a;
                }
            else if (!outBase)
                {
                outBase = a;
                }
            else
                {
                fprintf(stderr, "xcc-ln-wasm32: unexpected argument '%s'\n", argv[i]);
                return 1;
                }
            }
        if (!inPath || !outBase)
            {
            fprintf(stderr, "Usage: xcc-ln-wasm32 <input.wat> <output-base> [-q] "
                            "[--emit-lib] [--iface <json>] [--dep <name>]...\n");
            return 1;
            }
        NSString* wat = [NSString stringWithContentsOfFile:inPath
                                                  encoding:NSUTF8StringEncoding
                                                     error:NULL];
        if (!wat)
            {
            fprintf(stderr, "xcc-ln-wasm32: cannot read '%s'\n", inPath.UTF8String);
            return 1;
            }
        NSError* err = nil;
        NSData* module = [XTWasmWriter wasmModuleFromWat:wat error:&err];
        if (!module)
            {
            fprintf(stderr, "xcc-ln-wasm32: error: %s\n",
                    err ? err.localizedDescription.UTF8String : "(no detail)");
            return 1;
            }

        // `-o prog` → prog.wasm + prog.js; `-o prog.wasm` keeps the base.
        NSString* base = [outBase.pathExtension isEqualToString:@"wasm"]
                             ? outBase.stringByDeletingPathExtension
                             : outBase;
        NSString* wasmPath = [base stringByAppendingPathExtension:@"wasm"];

        if (emitLib)
            {
            // ── Library build (W2). ──────────────────────────────────────
            // 1. Embed the interface JSON as a `xtc.iface` CUSTOM section —
            //    the same role the ELF `.xtc.iface` section plays, so
            //    `#import <X>` reads the types from the binary itself.
            NSMutableData* libModule = [module mutableCopy];
            NSString* ifaceJson = ifacePath
                                      ? [NSString stringWithContentsOfFile:ifacePath
                                                                  encoding:NSUTF8StringEncoding
                                                                     error:NULL]
                                      : nil;
            if (ifaceJson.length)
                {
                NSData* name = [@"xtc.iface" dataUsingEncoding:NSUTF8StringEncoding];
                NSData* json = [ifaceJson dataUsingEncoding:NSUTF8StringEncoding];
                NSMutableData* payload = [NSMutableData data];
                uint8_t nl = (uint8_t)name.length;
                [payload appendBytes:&nl length:1]; // name len < 128: 1-byte LEB
                [payload appendData:name];
                [payload appendData:json];
                uint8_t zero = 0;
                [libModule appendBytes:&zero length:1]; // section id 0 (custom)
                uint64_t v = payload.length;            // section size, LEB128
                do
                    {
                    uint8_t b = v & 0x7F;
                    v >>= 7;
                    if (v)
                        b |= 0x80;
                    [libModule appendBytes:&b length:1];
                    } while (v);
                [libModule appendData:payload];
                }
            if (![libModule writeToFile:wasmPath atomically:YES])
                {
                fprintf(stderr, "xcc-ln-wasm32: cannot write '%s'\n", wasmPath.UTF8String);
                return 1;
                }
            // 2. The placement sidecar: the backend put the two numbers on
            //    the `;; xtc-lib data=<N> table=<M>` marker line.
            uint64_t dataSize = 0, tableSize = 0;
            for (NSString* ln in [wat componentsSeparatedByString:@"\n"])
                {
                NSString* tr = [ln stringByTrimmingCharactersInSet:
                                       [NSCharacterSet whitespaceCharacterSet]];
                if (![tr hasPrefix:@";; xtc-lib "])
                    continue;
                NSScanner* sc = [NSScanner scannerWithString:tr];
                [sc scanUpToString:@"data=" intoString:NULL];
                [sc scanString:@"data=" intoString:NULL];
                long long d = 0, t = 0; // scanLongLong: — GNUstep's
                                        // NSScanner has no
                                        // scanUnsignedLongLong:
                [sc scanLongLong:&d];
                [sc scanUpToString:@"table=" intoString:NULL];
                [sc scanString:@"table=" intoString:NULL];
                [sc scanLongLong:&t];
                dataSize = d;
                tableSize = t;
                break;
                }
            NSString* jsonPath = [base stringByAppendingPathExtension:@"json"];
            NSString* sidecar = [NSString stringWithFormat:
                                              @"{\"dataSize\": %llu, \"tableSize\": %llu}\n",
                                              (unsigned long long)dataSize, (unsigned long long)tableSize];
            if (![sidecar writeToFile:jsonPath
                           atomically:YES
                             encoding:NSUTF8StringEncoding
                                error:NULL])
                {
                fprintf(stderr, "xcc-ln-wasm32: cannot write '%s'\n", jsonPath.UTF8String);
                return 1;
                }
            if (!quiet)
                fprintf(stderr, "xcc-ln-wasm32: %s (%lu bytes, library) + %s\n",
                        wasmPath.UTF8String, (unsigned long)libModule.length,
                        jsonPath.UTF8String);
            return 0;
            }

        NSString* jsPath = [base stringByAppendingPathExtension:@"js"];
        if (![module writeToFile:wasmPath atomically:YES])
            {
            fprintf(stderr, "xcc-ln-wasm32: cannot write '%s'\n", wasmPath.UTF8String);
            return 1;
            }
        NSString* js = loaderJS(base.lastPathComponent, deps);
        if (![js writeToFile:jsPath
                  atomically:YES
                    encoding:NSUTF8StringEncoding
                       error:NULL])
            {
            fprintf(stderr, "xcc-ln-wasm32: cannot write '%s'\n", jsPath.UTF8String);
            return 1;
            }
        NSString* htmlPath = [base stringByAppendingPathExtension:@"html"];
        BOOL wroteHTML = NO;
        if (![[NSFileManager defaultManager] fileExistsAtPath:htmlPath])
            {
            wroteHTML = [starterHTML(base.lastPathComponent)
                writeToFile:htmlPath
                 atomically:YES
                   encoding:NSUTF8StringEncoding
                      error:NULL];
            }
        if (!quiet)
            fprintf(stderr, "xcc-ln-wasm32: %s (%lu bytes) + %s%s\n",
                    wasmPath.UTF8String, (unsigned long)module.length,
                    jsPath.UTF8String, wroteHTML ? " + starter .html" : "");
        return 0;
        }
    }
