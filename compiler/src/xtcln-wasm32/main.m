                   "  const isNode = typeof process !== \"undefined\" && !!(process.versions && process.versions.node);\n"
                   "  const isWorker = !isNode && typeof importScripts === \"function\";\n"
                   "  const cfg = (!isNode && !isWorker && globalThis.xccConfig) || {};\n"
