                   "    },\n"
                   "    _xt_file_exists: (p) => (isNode && require(\"fs\").existsSync(cstr(p))) ? 1 : 0,\n"
                   "    _xt_file_exists_exact: (p) => {\n"
                   "      // The host filesystem may be case-insensitive (macOS); ask for the\n"
                   "      // real spelling and compare the last component.\n"
                   "      if (!isNode) return 0;\n"
                   "      try {\n"
                   "        const fs = require(\"fs\"), path = require(\"path\"), q = cstr(p);\n"
                   "        const real = fs.realpathSync.native(q);\n"
                   "        return path.basename(real) === path.basename(q) ? 1 : 0;\n"
                   "      } catch (e) { return 0; }\n"
                   "    },\n"
                   "    _xt_file_chmod_exec: (p) => {\n"
                   "      if (!isNode) return -1;\n"
                   "      try { require(\"fs\").chmodSync(cstr(p), 0o755); return 0; } catch (e) { return -1; }\n"
                   "    },\n"
                   "    _xt_mkdir: (p) => {\n"
                   "      if (!isNode) return -1;\n"
                   "      try { require(\"fs\").mkdirSync(cstr(p)); return 0; } catch (e) { return -1; }\n"
                   "    },\n"
                   "    _xt_argc: () => isNode ? Math.max(1, process.argv.length - 1) : 1,\n"
                   "    _xt_argv: (i) => {\n"
                   "      const args = isNode ? process.argv.slice(1) : [];\n"
                   "      const s = (i >= 0 && i < args.length) ? args[i] : \"\";\n"
                   "      return argvPtr(i, s);\n"
                   "    },\n"
                   "    _xt_exit: (c) => { if (isNode) process.exit(c | 0); throw new Error(`Process.exit(${c})`); },\n"
                   "    // Math.rand host surface: a seeded xorshift32 — deterministic per\n"
                   "    // seed; the rand fixtures assert BOUNDS, not a reference sequence.\n"
                   "    _xt_srand: (s) => { rndState = (s >>> 0) || 1; },\n"
                   "    _xt_rand_u32: rnd32,\n"
                   "    _xt_rand_f: () => Math.fround(0.5 + (rnd32() / 0x100000000) * 0.5),\n"
                   "    _xt_rand_d: () => 0.5 + (rnd32() / 0x100000000) * 0.5,\n"
                   "    // Math.xc's host surface (float variants round through fround).\n"
                   "    _xm_sqrt: Math.sqrt,  _xm_sqrtf: (x) => Math.fround(Math.sqrt(x)),\n"
                   "    _xm_sin:  Math.sin,   _xm_sinf:  (x) => Math.fround(Math.sin(x)),\n"
                   "    _xm_cos:  Math.cos,   _xm_cosf:  (x) => Math.fround(Math.cos(x)),\n"
                   "    _xm_tan:  Math.tan,   _xm_tanf:  (x) => Math.fround(Math.tan(x)),\n"
                   "    _xm_atan: Math.atan,  _xm_atanf: (x) => Math.fround(Math.atan(x)),\n"
                   "    _xm_atan2: Math.atan2, _xm_atan2f: (y, x) => Math.fround(Math.atan2(y, x)),\n"
                   "    _xm_exp:  Math.exp,   _xm_expf:  (x) => Math.fround(Math.exp(x)),\n"
                   "    _xm_log:  Math.log,   _xm_logf:  (x) => Math.fround(Math.log(x)),\n"
                   "    _xm_pow:  Math.pow,   _xm_powf:  (x, y) => Math.fround(Math.pow(x, y)),\n"
                   "    _xm_floor: Math.floor, _xm_floorf: (x) => Math.fround(Math.floor(x)),\n"
                   "    _xm_ceil: Math.ceil,  _xm_ceilf: (x) => Math.fround(Math.ceil(x)),\n"
                   "    _xm_fabs: Math.abs,   _xm_fabsf: (x) => Math.fround(Math.abs(x)),\n"
                   "    _xm_fmod: (a, b) => a % b, _xm_fmodf: (a, b) => Math.fround(a % b),\n"
