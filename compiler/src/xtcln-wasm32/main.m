                   "      window.addEventListener(\"keyup\",     (e) => push(5, e.keyCode));\n"
                   "    }\n"
                   "    const off = (canvas && canvas.transferControlToOffscreen)\n"
                   "              ? canvas.transferControlToOffscreen() : null;\n"
                   "    const url = (document.currentScript && document.currentScript.src) || \"__BASE__.js\";\n"
                   "    const worker = new Worker(url);\n"
                   "    worker.onmessage = (m) => {\n"
                   "      const d = m.data || {};\n"
                   "      if (d.xccOut !== undefined) { (globalThis.xccOut || console.log)(d.xccOut); return; }\n"
                   "      if (d.xccReq !== undefined) {\n"
                   "        const v = (globalThis.xccOnRequest || (() => 0))(d.xccReq) | 0;\n"
                   "        Atomics.store(i32, 3, v);\n"
                   "        Atomics.store(i32, 2, d.xccReq.seq | 0);\n"
                   "        Atomics.notify(i32, 2);\n"
                   "        return;\n"
                   "      }\n"
                   "      if (d.xccExit) console.warn(`main() returned ${d.xccExit}`);\n"
                   "    };\n"
                   "    worker.postMessage({ ring, canvas: off,\n"
                   "                         workerScript: cfg.workerScript || null },\n"
                   "                       off ? [off] : []);\n"
                   "    return;\n"
                   "  }\n"
                   "\n"
                   "  // ── Node, plain browser, or the WORKER side: instantiate and run. ──\n"
                   "  let ringI32 = null, reqSeq = 0;\n"
                   "  if (isWorker) {\n"
                   "    const boot = await new Promise((res) => { self.onmessage = (m) => res(m.data); });\n"
                   "    if (boot.ring) ringI32 = new Int32Array(boot.ring);\n"
                   "    globalThis.xccCanvas = boot.canvas || null;   // OffscreenCanvas for the driver\n"
                   "    if (boot.workerScript) importScripts(boot.workerScript); // may set xccImports HERE\n"
                   "  }\n"
                   "  let line = [];\n"
                   "  const flush = () => {\n"
                   "    if (!line.length) return;\n"
                   "    const text = String.fromCharCode(...line); line = [];\n"
                   "    if (isNode) process.stdout.write(text);\n"
                   "    else if (isWorker) self.postMessage({ xccOut: text.replace(/\\n$/, \"\") });\n"
                   "    else (globalThis.xccOut || console.log)(text.replace(/\\n$/, \"\"));\n"
                   "  };\n"
                   "  let rndState = 0x2545F491;\n"
                   "  const rnd32 = () => {\n"
                   "    rndState ^= rndState << 13; rndState >>>= 0;\n"
                   "    rndState ^= rndState >> 17;\n"
                   "    rndState ^= rndState << 5;  rndState >>>= 0;\n"
                   "    return rndState;\n"
                   "  };\n"
                   "  const putc = (c) => { line.push(c & 0xFF); if ((c & 0xFF) === 10 || line.length > 4096) flush(); };\n"
                   "  const emit = (s) => { for (const ch of s) putc(ch.charCodeAt(0)); };\n"
                   "  // Read a NUL-terminated string out of linear memory; copy one in.\n"
                   "  const mem8 = () => new Uint8Array(XCC.memory.buffer);\n"
                   "  const cdec = new TextDecoder();\n"
                   "  const cstr = (p) => { const m = mem8(); let e = p; while (m[e]) e++; return cdec.decode(m.subarray(p, e)); };\n"
                   "  const argvCache = new Map();\n"
                   "  const argvPtr = (i, s) => {\n"
                   "    const key = i < 0 ? -1 : i;\n"
                   "    if (argvCache.has(key)) return argvCache.get(key);\n"
                   "    const bytes = new TextEncoder().encode(s);\n"
                   "    const p = XCC.instance.exports._xt_browser_alloc(bytes.length + 1);\n"
                   "    mem8().set(bytes, p); mem8()[p + bytes.length] = 0;   // re-derive: alloc may grow memory\n"
                   "    argvCache.set(key, p);\n"
                   "    return p;\n"
                   "  };\n"
                   "  const base = {\n"
                   "    putc, _putc: putc,\n"
                   "    // Fixed-point float/double formatters, matching the corpus C stub's\n"
                   "    // printf(\"%.*f\"): float defaults to 6 decimal places, double to 10.\n"
                   "    _xtc_pf:  (f) => emit(f.toFixed(6)),\n"
                   "    _xtc_pd:  (d) => emit(d.toFixed(10)),\n"
                   "    // Explicit `%.Nf` precision TRUNCATES (the reference _xtc_truncf\n"
                   "    // formats at N+1 digits and drops the last char); N=0 keeps the\n"
                   "    // 6 / 10 digit defaults.\n"
                   "    _xtc_pfp: (f, p) => emit(p ? f.toFixed(p + 1).slice(0, -1) : f.toFixed(6)),\n"
                   "    _xtc_pdp: (d, p) => emit(p ? d.toFixed(p + 1).slice(0, -1) : d.toFixed(10)),\n"
                   "    time_ms: () => Date.now() & 0x7FFFFFFF,\n"
                   "    getpid: () => 1,\n"
                   "    // Files.xc / Process.xc host surface (CI task #81). Node has a\n"
                   "    // filesystem and a command line; a page has neither, so there every\n"
                   "    // file call answers the way a missing file does and argc is 1.\n"
                   "    // Handles are node's fds. Modes are fopen's, with the `b` dropped.\n"
                   "    // `_xt_argv` hands the module a pointer, so the string is copied INTO\n"
