                   "    const push = (t, a=0, b=0, c=0, d=0, e=0, f=0, g=0) => {\n"
                   "      const w = Atomics.load(i32, 0);\n"
                   "      if (w - Atomics.load(i32, 1) >= cap) Atomics.add(i32, 1, 1); // drop oldest\n"
                   "      const s = 8 + (w % cap) * 8;\n"
